#SBATCH --mem 64GB
#SBATCH -t 4:00:00
#SBATCH --output=/gpfs/projects/b1255/hzhang/TwINFER_KA/analysis_data/paper_analysis/real_networks/beeline_inference_t1_10/logs/genie3_grnboost2_%j.out
#SBATCH --error=/gpfs/projects/b1255/hzhang/TwINFER_KA/analysis_data/paper_analysis/real_networks/beeline_inference_t1_10/logs/genie3_grnboost2_%j.err
set -euo pipefail
# [2026-09-30 note: #SBATCH paths cannot use variables; check them before submitting. Source clean_code/env.sh before sbatch (sbatch exports the environment).]
: "${TWINFER_CODE_ROOT:?source clean_code/env.sh before running or submitting this script}"
: "${TWINFER_PROJECT_ROOT:?source clean_code/env.sh before running or submitting this script}"
: "${TWINFER_BEELINE_PATH:?source clean_code/env.sh first (full Beeline install: BLRunner.py + Algorithms/)}"

# GENIE3 + GRNBOOST2 for every real_networks t1=10 dataset, ONE BLRunner.py process (no
# per-dataset parallelism) -- same memory-safety reasoning as
# run_mixed_network_sweep_genie3_grnboost2_t1_10.sh/run_e13_pos100_genie3_grnboost2_t1_10.sh.
# This launcher was missing from the original t1=10 build-out (2026-09-18): the config
# (config_real_networks_t1_10_genie3_grnboost2.yaml) already existed with should_run=true for
# GENIE3/GRNBOOST2, generated by generate_t1_10_beeline_configs.py alongside the other 3
# families, but no companion sbatch script was ever written for it -- the main
# run_real_network_benchmark_t1_10.sh's config has GENIE3/GRNBOOST2 should_run=false, so those
# two competitors were simply never run at t1=10 until now. 65 datasets across 7 real-topology
# networks (some considerably more genes than the simulated-GRN benchmarks) -> sized like
# mixed_network_sweep's 4h/64GB/16cpu rather than e13's smaller 2h/32GB/8cpu.
#
# Regenerate the config first if the dataset set changed:
#   python generate_t1_10_beeline_configs.py
#
# Usage: sbatch run_real_network_genie3_grnboost2_t1_10.sh

# SCRIPT_DIR=/gpfs/projects/b1255/hzhang/TwINFER_KA/code/Beeline   # [2026-09-30 replaced by env.sh variable]
SCRIPT_DIR=${TWINFER_BEELINE_PATH}
# LOG_DIR="/gpfs/projects/b1255/hzhang/TwINFER_KA/analysis_data/paper_analysis/real_networks/beeline_inference_t1_10/logs"   # [2026-09-30 replaced by env.sh variable]
LOG_DIR="${TWINFER_PROJECT_ROOT}/analysis_data/paper_analysis/real_networks/beeline_inference_t1_10/logs"
# BEELINE_PYTHON=/home/gzu5140/.conda/envs/BEELINE/bin/python   # [2026-09-30 replaced by env.sh variable]
BEELINE_PYTHON="${BEELINE_PYTHON:-/home/gzu5140/.conda/envs/BEELINE/bin/python}"

mkdir -p "$LOG_DIR"
module load R/4.2.3 ruby/3.1.0-gcc-4.8.5
cd "$SCRIPT_DIR"

echo "[$(date)] Running GENIE3 + GRNBOOST2 sequentially over real_networks t1=10..."
"$BEELINE_PYTHON" BLRunner.py \
    --config config-files/config_real_networks_t1_10_genie3_grnboost2.yaml \
    --yes --skip-populated \
    > "${LOG_DIR}/genie3_grnboost2.out" 2> "${LOG_DIR}/genie3_grnboost2.err"

echo "[$(date)] real_networks t1=10 GENIE3 + GRNBOOST2 run finished."
