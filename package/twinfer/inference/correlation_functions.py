# =============================================================================
# Twin observations and clone weighting
# =============================================================================
#
# Canonical RAW input schema:
#     clone_id  : biological clone identity
#     cell_id   : physical cell identity
#     time_step : measurement time
#
# Simulation input additionally contains:
#     replicate : sibling-lineage label
#
# twin_id is INTERNAL metadata generated by TwINFER.
#
# Twin construction:
#   - simulation: clone == twin.
#   - real data, Step 2: every unordered pair of cells within a clone at the
#     same time point is one twin observation.
#   - real data, Step 4: every t1 x t2 cell combination within a clone is one
#     cross-time twin observation.
#
# Step 1:
#   Controlled ONLY by use_clone.
#   use_clone=False : ordinary unweighted cell-level Spearman rho with the
#                     analytic cell-level null.
#   use_clone=True  : clone-weighted Spearman rho. Cell i in clone c has
#                     weight 1/n_c, and the null is clone-aware.
#
# Twin-derived Steps 2+:
#   Controlled by unit.
#   unit="twin"  : every enumerated twin observation has weight 1.
#   unit="clone" : every biological clone has total weight 1, split across
#                  that clone's enumerated twins.
#
# Step-1 gene-gene rho is always computed from raw cells. When use_clone=True,
# the null deranges clones and samples one target cell per source cell; it does
# NOT average over all cross-clone Cartesian cell pairings. Twin-expanded
# tables are used only for twin-difference and cross-time statistics.
#
# TwINFER names / notation used in the comments below:
#   Gene-expression correlation:             \rho(t)
#   Signed change in gene correlation:        \Delta\rho = \rho(t_2) - \rho(t_1)
#   Random-pair difference correlation:       \rho_{\Delta}(t)
#   Twin difference correlation:              \hat{\rho}_{\Delta}(t)
#   Heterogeneity-gated regulation:            \hat{\rho}_{reg}(\lambda)
#   Change in twin difference correlation:    d = \hat{\rho}_{\Delta}(t_2) - \hat{\rho}_{\Delta}(t_1)
#   Twin cross-correlation:                   \hat{\rho}^{\dagger}_{x(t_1)\to y(t_2)}
#   Directional asymmetry:                    \gamma = |\hat{\rho}^{\dagger}_{x(t_1)\to y(t_2)}| - |\hat{\rho}^{\dagger}_{y(t_1)\to x(t_2)}|
#


def _validate_canonical_input(df, is_simulation_data):
    """Validate raw one-row-per-cell-per-timepoint TwINFER input."""
    required = ["clone_id", "cell_id", "time_step"]
    if is_simulation_data:
        required.append("replicate")

    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(
            f"TwINFER input is missing required column(s): {missing}"
        )

    gene_cols = [c for c in df.columns if c.endswith("_mRNA")]
    if not gene_cols:
        raise ValueError("TwINFER input must contain at least one '*_mRNA' column")

    forbidden = [
        c for c in ("twin_id", "pair_id", "n_twins", "n_pairs")
        if c in df.columns
    ]
    if forbidden:
        raise ValueError(
            "Pass raw cell-level data only; remove twin-expansion columns: "
            f"{forbidden}"
        )

    check_cols = required + gene_cols
    if df[check_cols].isna().any().any():
        bad = [c for c in check_cols if df[c].isna().any()]
        raise ValueError(f"TwINFER input contains missing values in: {bad}")

    duplicated = df.duplicated(
        subset=["cell_id", "time_step"], keep=False
    )
    if duplicated.any():
        examples = (
            df.loc[duplicated, ["cell_id", "time_step"]]
            .drop_duplicates()
            .head(5)
            .to_dict("records")
        )
        raise ValueError(
            "TwINFER expects one row per physical cell per timepoint; "
            f"duplicate examples: {examples}"
        )


def _build_cross_time_twins(t1_cells, t2_cells):
    """
    Build aligned cross-time twins from every t1 x t2 combination in a clone.

    Simulation callers provide one selected sibling at each time, so each clone
    contributes one cross-time twin. Real data use the full Cartesian product.
    """
    left = t1_cells.reset_index(drop=True).copy()
    right = t2_cells.reset_index(drop=True).copy()

    if left.empty or right.empty:
        raise ValueError("Cannot build cross-time twins from an empty timepoint")

    value_cols = [c for c in left.columns if c != "clone_id"]
    if set(value_cols) != {c for c in right.columns if c != "clone_id"}:
        raise ValueError("t1 and t2 raw frames must have the same columns")

    twinned = left.merge(
        right,
        on="clone_id",
        how="inner",
        suffixes=("_t1", "_t2"),
        sort=True,
    )

    if "cell_id_t1" in twinned.columns and "cell_id_t2" in twinned.columns:
        twinned = twinned.loc[
            twinned["cell_id_t1"] != twinned["cell_id_t2"]
        ].copy()

    if twinned.empty:
        raise ValueError("No valid cross-time twins were found")

    twinned = twinned.reset_index(drop=True)
    twinned["twin_id"] = [f"twin_{i}" for i in range(len(twinned))]

    cols_t1 = ["clone_id"] + [f"{c}_t1" for c in value_cols]
    cols_t2 = ["clone_id"] + [f"{c}_t2" for c in value_cols]

    frame_t1 = twinned[cols_t1].rename(
        columns=lambda c: c[:-3] if c.endswith("_t1") else c
    )
    frame_t2 = twinned[cols_t2].rename(
        columns=lambda c: c[:-3] if c.endswith("_t2") else c
    )

    frame_t1["twin_id"] = twinned["twin_id"].to_numpy()
    frame_t2["twin_id"] = twinned["twin_id"].to_numpy()

    n_twins = twinned.groupby(
        "clone_id"
    )["twin_id"].transform("nunique").to_numpy()
    frame_t1["n_twins"] = n_twins
    frame_t2["n_twins"] = n_twins

    return frame_t1.reset_index(drop=True), frame_t2.reset_index(drop=True)


def _resolve_unit(unit=None):
    """
    Resolve the inference unit.

    Public terminology:
      - "twin": every enumerated twin observation has weight 1.
      - "clone": every biological clone has total weight 1.

    Legacy "pair" is accepted as an alias for "twin".
    """
    if unit is None:
        unit = os.environ.get("TWINFER_UNIT", "clone")

    unit = str(unit).strip().lower()
    if unit == "pair":
        warnings.warn(
            "unit='pair' is deprecated; use unit='twin'.",
            DeprecationWarning,
            stacklevel=2,
        )
        unit = "twin"

    if unit not in ("twin", "clone"):
        raise ValueError(f"unit={unit!r}; expected 'twin' or 'clone'")
    return unit

def get_conservative_null_draw_count(
    n_shuffles=None,
    alpha=0.01,
    expected_rejections=50,
    minimum=2000,
):
    """
    Resolve the Monte Carlo null size.

    Explicit integer n_shuffles always wins.

    Otherwise:
        B = max(minimum, ceil(expected_rejections / alpha))

    Defaults are deliberately conservative:
        alpha=0.05  -> 2,000
        alpha=0.01  -> 5,000
        alpha=0.001 -> 50,000

    There is no adaptive early stopping.
    """
    if n_shuffles is not None and str(n_shuffles).lower() != "auto":
        b = int(n_shuffles)
        if b < 2:
            raise ValueError("n_shuffles must be at least 2")
        return b

    alpha = float(alpha)
    if not 0 < alpha < 1:
        raise ValueError("alpha must be between 0 and 1")

    expected_rejections = int(expected_rejections)
    minimum = int(minimum)
    if expected_rejections < 1:
        raise ValueError("expected_rejections must be positive")
    if minimum < 2:
        raise ValueError("minimum must be at least 2")

    return max(
        minimum,
        int(math.ceil(expected_rejections / alpha)),
    )


def _requested_gene_subset(gene_list, gene_pairs=None):
    """Return the ordered genes and undirected pairs actually needed."""
    gene_list = list(gene_list)

    if gene_pairs is None:
        pairs = [
            tuple(sorted((gene_list[i], gene_list[j])))
            for i, j in zip(
                *np.triu_indices(len(gene_list), k=1)
            )
        ]
        return gene_list, pairs

    pairs = []
    seen = set()
    needed = set()

    for gene_i, gene_j in gene_pairs:
        if gene_i == gene_j:
            continue
        if gene_i not in gene_list or gene_j not in gene_list:
            raise ValueError(
                f"Unknown gene pair: ({gene_i}, {gene_j})"
            )

        key = tuple(sorted((gene_i, gene_j)))
        if key not in seen:
            seen.add(key)
            pairs.append(key)
            needed.update(key)

    active_genes = [
        gene for gene in gene_list
        if gene in needed
    ]
    return active_genes, pairs


def get_clone_weights(frame):
    """
    Return row weights such that every biological clone has total weight 1.

    clone_id is factorized once to integer codes, so counting and row-weight
    lookup stay in NumPy rather than repeated object/dict operations.
    """
    if "clone_id" not in frame.columns:
        raise ValueError("clone weighting requires a 'clone_id' column")

    clone_ids = frame["clone_id"].to_numpy()
    codes, labels = pd.factorize(clone_ids, sort=False)
    if np.any(codes < 0):
        raise ValueError("clone_id contains missing values")

    counts = np.bincount(codes, minlength=len(labels)).astype(float)
    weights = 1.0 / counts[codes]

    if not np.isclose(weights.sum(), float(len(labels)), rtol=0.0, atol=1e-9):
        raise AssertionError("clone weights do not sum to the number of biological clones")
    return weights


def get_unit_weights(frame, unit=None):
    """Return row weights under twin or clone units."""
    unit = _resolve_unit(unit)
    if unit == "twin":
        return np.ones(len(frame), dtype=float)
    return get_clone_weights(frame)


def get_number_of_units(frame, unit=None):
    """Number of twin observations or biological clones in a twin-level frame."""
    unit = _resolve_unit(unit)

    if unit == "twin":
        if "twin_id" not in frame.columns:
            raise ValueError("twin units require a 'twin_id' column")
        return int(frame["twin_id"].nunique())

    if "clone_id" not in frame.columns:
        raise ValueError("clone units require a 'clone_id' column")
    return int(frame["clone_id"].nunique())

def weighted_rank(values, weights):
    """Weighted mid-ranks; equal weights are affine-equivalent to ordinary ranks."""
    values = np.asarray(values, dtype=float)
    weights = np.asarray(weights, dtype=float)

    if values.shape != weights.shape:
        raise ValueError("values and weights must have the same shape")
    if not np.isfinite(values).all():
        return np.full(values.shape, np.nan, dtype=float)
    if (
        np.any(weights < 0)
        or not np.isfinite(weights).all()
        or weights.sum() <= 0
    ):
        raise ValueError(
            "weights must be finite, non-negative, and have positive total"
        )
    if len(values) == 0:
        return np.empty(0, dtype=float)

    order = np.argsort(values, kind="mergesort")
    vs = values[order]
    ws = weights[order]

    # Exact weighted mid-ranks, vectorized over tie blocks.
    #
    # For each tie block:
    #   rank = cumulative weight below the block + half the block's weight.
    #
    # This is mathematically identical to the former Python while-loop but
    # removes the per-element/tie-block Python iteration.
    new_block = np.empty(len(vs), dtype=bool)
    new_block[0] = True
    new_block[1:] = vs[1:] != vs[:-1]

    block_of = np.cumsum(new_block) - 1
    block_starts = np.flatnonzero(new_block)

    cumulative_with_zero = np.concatenate(
        ([0.0], np.cumsum(ws))
    )
    below = cumulative_with_zero[block_starts]

    tie_weight = np.bincount(
        block_of,
        weights=ws,
    )
    ranked_sorted = (
        below[block_of]
        + tie_weight[block_of] / 2.0
    )

    ranked = np.empty(len(values), dtype=float)
    ranked[order] = ranked_sorted
    return ranked


def weighted_spearman(x, y, weights):
    """Spearman under twin/clone weights: weighted ranks, then weighted Pearson."""
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    weights = np.asarray(weights, dtype=float)
    if not (x.shape == y.shape == weights.shape):
        raise ValueError("x, y, and weights must have the same shape")
    if len(x) < 2:
        return np.nan
    if not (np.isfinite(x).all() and np.isfinite(y).all() and np.isfinite(weights).all()):
        return np.nan

    rx = weighted_rank(x, weights)
    ry = weighted_rank(y, weights)
    sw = float(weights.sum())
    cx = rx - float(np.sum(weights * rx) / sw)
    cy = ry - float(np.sum(weights * ry) / sw)
    den = float(np.sqrt(np.sum(weights * cx * cx) * np.sum(weights * cy * cy)))
    return float(np.sum(weights * cx * cy) / den) if den > 0 else np.nan


def _weighted_spearman_matrix(values, weights):
    """
    All-gene weighted Spearman matrix.

    Rank all genes together through the fixed-value rank cache instead of
    calling weighted_rank once per gene. The cache performs the weight update
    with one 2-D cumulative-weight pass across genes x sorted rows.
    """
    values = np.asarray(values, dtype=float)
    weights = np.asarray(weights, dtype=float)

    if values.ndim != 2 or values.shape[0] != len(weights):
        raise ValueError(
            "values must be (n_observations, n_genes) and match weights"
        )
    if not np.isfinite(values).all():
        raise ValueError(
            "weighted Spearman matrix does not accept NaN/Inf values"
        )

    cache = _prepare_delta_rank_permutation_cache(values, weights)
    centered = cache["cx"]

    cov = centered.T @ (weights[:, None] * centered)
    scale = cache["sx"]
    den = np.outer(scale, scale)

    with np.errstate(divide="ignore", invalid="ignore"):
        corr_matrix = cov / den
    corr_matrix[den == 0] = np.nan
    return corr_matrix


def _random_derangement(n, rng):
    """Sample a permutation with no fixed points."""
    if n < 2:
        raise ValueError("A derangement requires at least 2 items")
    base = np.arange(n)
    while True:
        perm = rng.permutation(n)
        if np.all(perm != base):
            return perm


def _prepare_clone_row_groups(clone_ids):
    """
    Precompute clone membership for repeated null draws.

    Returns
    -------
    clone_ids : np.ndarray
        Original clone id per row.
    clones : np.ndarray
        Unique clones in first-occurrence order.
    groups : dict
        clone_id -> integer row indices.
    """
    clone_ids = np.asarray(clone_ids, dtype=object)
    clones = np.asarray(pd.unique(clone_ids), dtype=object)

    groups = {}
    for row, clone_id in enumerate(clone_ids):
        groups.setdefault(clone_id, []).append(row)

    groups = {
        clone_id: np.asarray(rows, dtype=int)
        for clone_id, rows in groups.items()
    }

    return clone_ids, clones, groups


def _prepare_clone_sampling_cache(clone_ids):
    """
    Precompute everything needed for repeated clone-matched cell sampling.

    The clone structure never changes across null draws. We therefore store:
      - source clone code for every row;
      - clone sizes;
      - offsets into one concatenated clone-row array.

    A null draw can then sample one target row per source row with a single
    rng.random(N) call and vectorized integer indexing -- no Python loop over
    clones and no rng.choice call per clone.
    """
    clone_ids = np.asarray(clone_ids, dtype=object)
    source_code, clones = pd.factorize(
        clone_ids,
        sort=False,
    )
    if np.any(source_code < 0):
        raise ValueError("clone_id contains missing values")

    clones = np.asarray(clones, dtype=object)
    n_clones = len(clones)
    if n_clones < 2:
        raise ValueError(
            "Need at least 2 biological clones for clone-matched sampling"
        )

    # Stable row grouping by integer clone code.
    row_order = np.argsort(
        source_code,
        kind="stable",
    )
    sizes = np.bincount(
        source_code,
        minlength=n_clones,
    ).astype(int)
    starts = np.empty(n_clones, dtype=int)
    starts[0] = 0
    if n_clones > 1:
        starts[1:] = np.cumsum(sizes[:-1])

    return {
        "clone_ids": clone_ids,
        "clones": clones,
        "source_code": source_code.astype(int, copy=False),
        "sizes": sizes,
        "starts": starts,
        "row_order": row_order.astype(int, copy=False),
    }


def _sample_clone_matched_target_rows(
    clone_ids,
    rng,
    clones=None,
    groups=None,
    sampling_cache=None,
    validate=False,
):
    """
    Vectorized one-target-cell-per-source-cell sampler for the Step-1 null.

    Biological clones are deranged first. Then every source row draws one cell
    uniformly from its matched target clone.

    When sampling_cache is supplied, the draw is fully vectorized:
      target_clone_code_per_row = perm[source_clone_code]
      local_index = floor(U * target_clone_size)
      target_row = concatenated_clone_rows[target_start + local_index]

    This removes the Python loop over clones and one rng.choice call per clone.

    `clones`/`groups` remain accepted for backward compatibility; new internal
    callers should pass sampling_cache.
    """
    clone_ids = np.asarray(clone_ids, dtype=object)

    if sampling_cache is None:
        sampling_cache = _prepare_clone_sampling_cache(clone_ids)

    clones_arr = sampling_cache["clones"]
    source_code = sampling_cache["source_code"]
    sizes = sampling_cache["sizes"]
    starts = sampling_cache["starts"]
    row_order = sampling_cache["row_order"]

    perm = _random_derangement(len(clones_arr), rng)
    target_code = perm[source_code]
    target_size = sizes[target_code]

    # rng.random is in [0, 1), so the cast is an exact uniform integer draw
    # from 0,...,target_size-1 for each row.
    local = (
        rng.random(len(source_code))
        * target_size
    ).astype(np.int64)

    target_idx = row_order[
        starts[target_code] + local
    ]

    if validate:
        if np.any(clone_ids == clone_ids[target_idx]):
            raise AssertionError(
                "internal error: Step-1 null sampled from the source clone"
            )

    return target_idx


def _clone_block_sampled_spearman_null(
    values,
    clone_ids,
    n_shuffles,
    random_state,
    pair_i,
    pair_j,
):
    """
    Clone-aware Step-1 null for the clone-weighted Spearman statistic.

    Observed Step-1 rho uses raw cells with source-cell weight

        w_i = 1 / n_c

    for cell i in clone c.

    Each null shuffle:
      1. deranges the biological clones (no c -> c match);
      2. for every source cell i in clone c, draws ONE target cell uniformly
         from the matched target clone d;
      3. keeps the source row's weight at 1/n_c;
      4. recomputes the same weighted Spearman statistic.

    The statistical null and RNG stream are unchanged. The hot path stays in
    gene x row layout and reuses the cached weighted centered-X matrix, avoiding
    repeated row x gene temporaries.
    """
    values = np.asarray(values, dtype=float)
    clone_ids = np.asarray(clone_ids, dtype=object)
    pair_i = np.asarray(pair_i, dtype=int)
    pair_j = np.asarray(pair_j, dtype=int)

    if values.ndim != 2 or values.shape[0] != len(clone_ids):
        raise ValueError("values and clone_ids have incompatible shapes")
    if not np.isfinite(values).all():
        raise ValueError("Step-1 clone null does not accept NaN/Inf")
    if int(n_shuffles) < 2:
        raise ValueError("n_shuffles must be at least 2")

    sampling_cache = _prepare_clone_sampling_cache(clone_ids)
    clone_ids = sampling_cache["clone_ids"]
    clones = sampling_cache["clones"]
    if len(clones) < 2:
        raise ValueError(
            f"Need at least 2 biological clones for Step 1; got {len(clones)}"
        )

    counts = pd.Series(clone_ids).value_counts()
    weights = np.asarray(
        [1.0 / counts[c] for c in clone_ids],
        dtype=float,
    )

    rank_cache = _prepare_delta_rank_permutation_cache(values, weights)
    sx = rank_cache["sx"]
    weighted_cx_T = rank_cache["weighted_cx_T"]
    weight_sum = rank_cache["weight_sum"]
    n_rows = values.shape[0]

    out = np.full(
        (int(n_shuffles), len(pair_i)),
        np.nan,
        dtype=float,
    )

    rng = np.random.default_rng(random_state)

    for b in range(int(n_shuffles)):
        target_idx = _sample_clone_matched_target_rows(
            clone_ids,
            rng,
            sampling_cache=sampling_cache,
        )

        # Aggregate the source weights onto the fixed target rows, update exact
        # weighted ranks from the cached per-gene ordering, then gather in G x N
        # layout. This is the same ranking operation as the previous helper but
        # avoids an extra gather-and-transpose cycle.
        weight_by_original_row = np.bincount(
            target_idx,
            weights=weights,
            minlength=n_rows,
        )
        ranks_original_gn = _weighted_ranks_from_rank_cache(
            rank_cache,
            weight_by_original_row,
        )
        ry_gn = ranks_original_gn[:, target_idx]

        my = (ry_gn @ weights) / weight_sum
        cy_gn = ry_gn - my[:, None]
        sy = np.sqrt((cy_gn * cy_gn) @ weights)

        # (G x N) @ (N x G), then read only requested pairs.
        numer_matrix = weighted_cx_T @ cy_gn.T
        den = sx[pair_i] * sy[pair_j]
        valid = den > 0
        out[b, :] = np.nan
        out[b, valid] = (
            numer_matrix[pair_i[valid], pair_j[valid]]
            / den[valid]
        )

    return out


    
def _build_raw_clone_index(raw_clone_ids):
    """
    Map clone_id -> raw-cell row indices.

    The returned mapping is used by the two-step null sampler:
        1. choose a target clone uniformly;
        2. choose one raw cell uniformly within that clone.

    The grouping is built with factorization plus one stable argsort rather than
    a Python loop over every raw-cell row. First-occurrence clone order and
    within-clone row order are unchanged.
    """
    raw_clone_ids = np.asarray(raw_clone_ids, dtype=object)
    codes, clone_labels = pd.factorize(raw_clone_ids, sort=False)
    if np.any(codes < 0):
        raise ValueError("clone_id contains missing values")

    clone_labels = np.asarray(clone_labels, dtype=object)
    if len(clone_labels) == 0:
        return {}

    order = np.argsort(codes, kind="stable")
    sizes = np.bincount(codes, minlength=len(clone_labels)).astype(np.int64)
    starts = np.empty(len(clone_labels), dtype=np.int64)
    starts[0] = 0
    if len(clone_labels) > 1:
        starts[1:] = np.cumsum(sizes[:-1])

    return {
        clone_id: order[start:start + size].astype(int, copy=False)
        for clone_id, start, size in zip(clone_labels, starts, sizes)
    }



def _sample_cross_clone_raw_targets(source_clones, raw_clone_ids, rng):
    """
    Two-step clone-balanced random partner sampling.

    For every observed source twin slot:
        1. choose a biological target clone uniformly from all clones other
           than the source clone;
        2. choose one raw cell uniformly from within that target clone.

    Sampling is with replacement across twin slots. Thus singleton clones can
    contribute as unrelated random partners, and a 50-cell clone is NOT 50x
    more likely than a 1-cell clone to be selected as the target clone.
    """
    source_clones = np.asarray(source_clones, dtype=object)
    raw_clone_ids = np.asarray(raw_clone_ids, dtype=object)

    if len(source_clones) < 1:
        raise ValueError("Need at least one observed twin slot to randomize")
    if len(raw_clone_ids) < 1:
        raise ValueError("Need at least one raw cell to build the random reference")

    raw_groups = _build_raw_clone_index(raw_clone_ids)
    raw_clones = np.asarray(list(raw_groups), dtype=object)

    if len(raw_clones) < 2:
        raise ValueError(
            "Need at least two biological clones for a cross-clone random reference"
        )

    target = np.empty(len(source_clones), dtype=int)

    for slot, source_clone in enumerate(source_clones):
        candidate_clones = raw_clones[raw_clones != source_clone]
        if len(candidate_clones) == 0:
            raise ValueError(
                f"No target clone exists outside clone_id={source_clone!r}"
            )

        target_clone = rng.choice(candidate_clones)
        target[slot] = rng.choice(raw_groups[target_clone])

    if np.any(source_clones == raw_clone_ids[target]):
        raise AssertionError("internal error: sampled a same-clone raw-cell target")

    return target


def _prepare_cross_clone_integer_cache(clone_ids):
    """
    Factorize rho_cross clone ids once and cache clone-row arrays.

    padded_groups lets every clone's within-block row order be randomized in
    one NumPy call per side of a null draw.
    """
    clone_ids = np.asarray(clone_ids, dtype=object)
    codes, labels = pd.factorize(clone_ids, sort=False)
    if np.any(codes < 0):
        raise ValueError("clone_id contains missing values")

    codes = codes.astype(np.int32, copy=False)
    labels = np.asarray(labels, dtype=object)
    groups = [
        np.flatnonzero(codes == code)
        for code in range(len(labels))
    ]
    max_size = max(len(ix) for ix in groups)

    padded_groups = np.full(
        (len(labels), max_size),
        -1,
        dtype=np.int64,
    )
    for code, rows in enumerate(groups):
        padded_groups[code, :len(rows)] = rows

    return {
        "codes": codes,
        "labels": labels,
        "groups": groups,
        "padded_groups": padded_groups,
        "n_clones": len(labels),
        "max_size": int(max_size),
    }


def _cross_clone_permutation_indices(
    clone_ids,
    rng,
    clones=None,
    groups=None,
    max_size=None,
    integer_cache=None,
    validate=False,
):
    """
    One-to-one rho_cross permutation with mandatory source-clone exclusion.

    Clone membership is cached once. Per draw, NumPy independently permutes
    every padded clone row along axis 1, removing the two Python loops over
    all biological clones from the hot path.
    """
    if integer_cache is None:
        integer_cache = _prepare_cross_clone_integer_cache(clone_ids)

    codes = integer_cache["codes"]
    n_clones = integer_cache["n_clones"]
    max_clone_size = integer_cache["max_size"]
    padded_groups = integer_cache["padded_groups"]
    n_obs = len(codes)

    if n_obs < 2:
        raise ValueError(
            "Need at least 2 cross-time twin rows to shuffle"
        )
    if n_clones < 2:
        raise ValueError(
            "The rho_cross null requires at least two biological clones"
        )
    if max_clone_size > n_obs - max_clone_size:
        raise ValueError(
            "Cannot build a one-to-one source-clone-excluding rho_cross "
            "permutation because one clone contains more than half of the "
            "cross-time twin rows."
        )

    clone_order = rng.permutation(n_clones)

    source_padded = rng.permuted(
        padded_groups,
        axis=1,
    )[clone_order]
    target_padded = rng.permuted(
        padded_groups,
        axis=1,
    )[clone_order]

    source_order = source_padded.ravel()
    source_order = source_order[source_order >= 0]

    target_order = target_padded.ravel()
    target_order = target_order[target_order >= 0]

    shift = int(
        rng.integers(
            max_clone_size,
            n_obs - max_clone_size + 1,
        )
    )
    shifted_target = np.roll(target_order, -shift)

    perm = np.empty(n_obs, dtype=int)
    perm[source_order] = shifted_target

    if np.any(codes == codes[perm]):
        raise AssertionError(
            "internal error: rho_cross null matched the source clone"
        )

    if validate and len(np.unique(perm)) != n_obs:
        raise AssertionError(
            "internal error: rho_cross null is not one-to-one"
        )

    return perm


def _cross_null_chunk(
    values_t2,
    weights,
    clone_ids,
    seeds,
    pair_i,
    pair_j,
    weighted_cx_T,
    sx,
    equal_weights,
    cy_equal_T=None,
    sy_equal=None,
):
    """One thread-safe chunk of the rho_cross permutation null."""
    values_t2 = np.asarray(values_t2, dtype=float)
    weights = np.asarray(weights, dtype=float)
    clone_ids = np.asarray(clone_ids, dtype=object)
    seeds = np.asarray(seeds, dtype=np.int64)

    n_obs = values_t2.shape[0]
    integer_cache = _prepare_cross_clone_integer_cache(clone_ids)

    # _weighted_ranks_from_rank_cache reuses mutable scratch buffers. Build a
    # private cache per worker whenever clone weights make ranks permutation-
    # dependent; never share this cache across threads.
    y_rank_cache = None
    if not equal_weights:
        y_rank_cache = _prepare_delta_rank_permutation_cache(values_t2, weights)

    out = np.empty((len(seeds), len(pair_i)), dtype=float)
    weight_sum = float(weights.sum())

    for s, seed in enumerate(seeds):
        rng = np.random.default_rng(int(seed))
        perm = _cross_clone_permutation_indices(
            clone_ids,
            rng,
            integer_cache=integer_cache,
        )

        if equal_weights:
            cy_gn = cy_equal_T[:, perm]
            sy = sy_equal
        else:
            inv_perm = np.empty(n_obs, dtype=np.int64)
            inv_perm[perm] = np.arange(n_obs, dtype=np.int64)
            y_weight_by_original_row = weights[inv_perm]

            ry_original_gn = _weighted_ranks_from_rank_cache(
                y_rank_cache,
                y_weight_by_original_row,
            )
            ry_gn = ry_original_gn[:, perm]
            my = (ry_gn @ weights) / weight_sum
            cy_gn = ry_gn - my[:, None]
            sy = np.sqrt((cy_gn * cy_gn) @ weights)

        # One BLAS GEMM replaces the large n_obs x n_pairs elementwise
        # temporaries used by the previous implementation.
        numer_matrix = weighted_cx_T @ cy_gn.T
        den = sx[pair_i] * sy[pair_j]
        valid = den > 0
        out[s, :] = np.nan
        out[s, valid] = (
            numer_matrix[pair_i[valid], pair_j[valid]]
            / den[valid]
        )

    return out


def _weighted_cross_permutation_null(
    values_t1,
    values_t2,
    weights,
    clone_ids,
    seeds,
    pair_i,
    pair_j,
    n_cores_to_use=1,
):
    """
    Cross-time rho-dagger null with source-clone exclusion.

    The statistic, permutations, seeds and RNG consumption are unchanged. Fixed
    X ranks are prepared once; each draw uses one (G x N) @ (N x G) GEMM and
    reads only the requested directed pairs. Clone-weighted Y rank scratch is
    private to each worker, so the threaded path is deterministic and safe.
    """
    values_t1 = np.asarray(values_t1, dtype=float)
    values_t2 = np.asarray(values_t2, dtype=float)
    weights = np.asarray(weights, dtype=float)
    clone_ids = np.asarray(clone_ids, dtype=object)
    seeds = np.asarray(seeds, dtype=np.int64)
    pair_i = np.asarray(pair_i, dtype=int)
    pair_j = np.asarray(pair_j, dtype=int)

    if values_t1.shape != values_t2.shape:
        raise ValueError("cross-time matrices must have the same shape")
    if values_t1.shape[0] != len(weights):
        raise ValueError("weights must match the number of twin rows")
    if values_t1.shape[0] != len(clone_ids):
        raise ValueError("clone_ids must match the number of twin rows")

    n_obs = values_t1.shape[0]
    integer_cache = _prepare_cross_clone_integer_cache(clone_ids)
    max_clone_size = integer_cache["max_size"]
    if max_clone_size > n_obs - max_clone_size:
        raise ValueError(
            "Cannot build a one-to-one source-clone-excluding rho_cross "
            "permutation because one clone contains more than half of the "
            "cross-time twin rows."
        )

    # Batched rank setup from the existing exact per-gene/tie cache.
    x_cache = _prepare_delta_rank_permutation_cache(values_t1, weights)
    weighted_cx_T = np.ascontiguousarray(x_cache["weighted_cx_T"])
    sx = x_cache["sx"]

    equal_weights = bool(np.allclose(weights, weights[0]))
    cy_equal_T = None
    sy_equal = None
    if equal_weights:
        y_cache = _prepare_delta_rank_permutation_cache(values_t2, weights)
        cy_equal_T = np.ascontiguousarray(y_cache["cx"].T)
        sy_equal = y_cache["sx"]

    n_cores_to_use = max(1, int(n_cores_to_use))
    if n_cores_to_use == 1 or len(seeds) < 2:
        return _cross_null_chunk(
            values_t2,
            weights,
            clone_ids,
            seeds,
            pair_i,
            pair_j,
            weighted_cx_T,
            sx,
            equal_weights,
            cy_equal_T,
            sy_equal,
        )

    n_chunks = min(n_cores_to_use, len(seeds))
    seed_chunks = [
        chunk
        for chunk in np.array_split(seeds, n_chunks)
        if len(chunk)
    ]

    with threadpool_limits(limits=1, user_api="blas"):
        parts = Parallel(
            n_jobs=len(seed_chunks),
            prefer="threads",
            require="sharedmem",
        )(
            delayed(_cross_null_chunk)(
                values_t2,
                weights,
                clone_ids,
                chunk,
                pair_i,
                pair_j,
                weighted_cx_T,
                sx,
                equal_weights,
                cy_equal_T,
                sy_equal,
            )
            for chunk in seed_chunks
        )

    return np.vstack(parts)

def _clone_group_indices(pair_frame):
    """Map biological clone_id -> indices of one-row-per-twin observations."""
    if "clone_id" not in pair_frame.columns:
        raise ValueError("pair_frame must contain 'clone_id'")

    groups = {}
    for idx, clone in enumerate(pair_frame["clone_id"].to_numpy()):
        groups.setdefault(clone, []).append(idx)
    return {c: np.asarray(ix, dtype=int) for c, ix in groups.items()}



def _bootstrap_clone_spearman(rep_0, rep_1, gene_i, gene_j, n_boot, rng):
    """Whole-clone bootstrap of one twin difference-correlation."""
    groups = _clone_group_indices(rep_0)
    clones = np.asarray(list(groups), dtype=object)
    dx = (rep_0[f"{gene_i}_mRNA"] - rep_1[f"{gene_i}_mRNA"]).to_numpy(float)
    dy = (rep_0[f"{gene_j}_mRNA"] - rep_1[f"{gene_j}_mRNA"]).to_numpy(float)
    out = np.empty(n_boot, dtype=float)
    for b in range(n_boot):
        idx = []
        w = []
        for clone in rng.choice(clones, size=len(clones), replace=True):
            ix = groups[clone]
            idx.extend(ix.tolist())
            w.extend([1.0 / len(ix)] * len(ix))
        idx = np.asarray(idx, dtype=int)
        w = np.asarray(w, dtype=float)
        out[b] = weighted_spearman(dx[idx], dy[idx], w)
    return out


def check_system_in_steady_state(
    simulation_df,
    gene_list,
    steady_tol=0.01,
    flat_tol=None,
    min_r2=0.80,
    slope_tol=None,
    min_stable_points=5,
):
    """
    Determine whether each population-mean protein trajectory has reached
    steady state.

    Primary detector: maximal stable terminal suffix
    ------------------------------------------------
    Start from the final `min_stable_points` observations and grow the candidate
    terminal window backward. A suffix is stable only while BOTH:

        1. every point is close to the suffix mean:

               max |P(t) - mean(P)| / |mean(P)| <= flat_tol

        2. directional terminal drift is small.

           Fit a line to that suffix, project its slope across the FULL
           observed simulation duration, and weight that projected slope by
           the absolute time-level correlation |r|:

               effective_drift
               = |slope| * total_duration / |mean(P)| * |r|
               <= slope_tol

           This keeps strong protection against monotonic drift while avoiding
           false rejection of small bounded oscillations whose instantaneous
           regression slope depends on phase.

    The largest suffix satisfying both criteria is the empirical terminal
    steady-state region. No monotonicity is assumed, so overshoot, undershoot,
    damped transients, and temporary disturbances are allowed.

    Once a stable suffix is found:

        P_inf = mean protein level in that stable suffix

    and t_steady is the earliest observed time after which ALL later observed
    values remain within steady_tol of P_inf:

        |P(t) - P_inf| / |P_inf| <= steady_tol.

    Fallback relaxation fit
    -----------------------
    If no empirical stable suffix exists, the previous stretched-exponential
    fit is retained for diagnostics / extrapolation:

        P(t) = P_inf + (P0 - P_inf) * exp(-(t/tau)**beta)

    but it does NOT override an unstable observed tail. In other words, a gene
    is classified as having reached steady state only when the observed terminal
    trajectory itself contains a stable suffix. A good global fit cannot turn
    late drift, late spikes, or terminal noise into a steady call.

    Parameters
    ----------
    simulation_df : pd.DataFrame
        Simulation output containing 'time_step' and '{gene}_protein' columns.

    gene_list : list of str
        Ordered list of genes.

    steady_tol : float, default=0.01
        Relative distance from P_inf used to define entry into steady state.

    flat_tol : float or None, default=None
        Maximum relative range allowed across the stable terminal suffix.
        If None, uses steady_tol.

    min_r2 : float, default=0.80
        R2 threshold reported for the fallback relaxation fit. The fallback fit
        is diagnostic and does not by itself create a steady-state call.

    slope_tol : float or None, default=None
        Maximum projected relative terminal drift. If None, uses steady_tol.

    min_stable_points : int, default=5
        Minimum number of terminal observations required to establish an
        empirical stable suffix.

    Returns
    -------
    is_steady : bool
        True only if all genes contain an empirical stable terminal suffix.

    summary_df : pd.DataFrame
        Per-gene steady-state results and diagnostics.
    """
    if flat_tol is None:
        flat_tol = steady_tol
    if slope_tol is None:
        slope_tol = steady_tol

    if "time_step" not in simulation_df.columns:
        raise ValueError("simulation_df must contain a 'time_step' column.")
    if steady_tol <= 0:
        raise ValueError("steady_tol must be greater than 0.")
    if flat_tol <= 0:
        raise ValueError("flat_tol must be greater than 0.")
    if slope_tol <= 0:
        raise ValueError("slope_tol must be greater than 0.")
    if not 0 <= min_r2 <= 1:
        raise ValueError("min_r2 must be between 0 and 1.")

    min_stable_points = int(min_stable_points)
    if min_stable_points < 3:
        raise ValueError("min_stable_points must be at least 3.")

    for gene in gene_list:
        protein_col = f"{gene}_protein"
        if protein_col not in simulation_df.columns:
            raise ValueError(
                f"{protein_col} not found in simulation_df."
            )

    mean_df = (
        simulation_df
        .groupby("time_step", sort=True)[
            [f"{gene}_protein" for gene in gene_list]
        ]
        .mean()
    )

    time_points = mean_df.index.to_numpy(dtype=float)

    if len(time_points) < min_stable_points:
        raise ValueError(
            "Need at least min_stable_points time points for "
            "steady-state checking."
        )
    if np.any(np.diff(time_points) <= 0):
        raise ValueError(
            "time_step values must be strictly increasing."
        )

    total_duration = float(
        time_points[-1] - time_points[0]
    )
    if total_duration <= 0:
        raise ValueError(
            "Observed simulation duration must be positive."
        )

    t_fit_global = time_points - time_points[0]
    results = []

    def _stable_suffix_metrics(t_window, y_window):
        """
        Stability diagnostics for one terminal suffix.

        Boundedness is measured as the largest absolute deviation from the
        suffix mean, which matches the steady-state definition
            |P(t) - P_inf| / |P_inf| <= tolerance.
        Thus a bounded +/-0.6% oscillation is allowed by a 1% tolerance even
        though its peak-to-peak range is 1.2%.

        Drift is separated from bounded oscillation. We still calculate the
        projected linear slope across the full observed duration, but weight it
        by |r| from the time-vs-level regression. A genuinely directional drift
        has |r| near 1; an oscillatory suffix has much weaker linear coherence.
        """
        level = float(np.mean(y_window))
        scale = max(abs(level), 1e-12)

        relative_range = float(
            (np.max(y_window) - np.min(y_window))
            / scale
        )
        max_relative_deviation = float(
            np.max(np.abs(y_window - level))
            / scale
        )

        if len(y_window) < 2:
            projected_relative_slope = np.inf
            trend_strength = 1.0
            effective_relative_drift = np.inf
        elif np.ptp(y_window) <= 1e-14 * scale:
            # linregress returns r=NaN for an exactly constant window.
            # A constant suffix has zero slope and zero directional drift.
            projected_relative_slope = 0.0
            trend_strength = 0.0
            effective_relative_drift = 0.0
        else:
            fit = linregress(t_window, y_window)
            projected_relative_slope = float(
                abs(float(fit.slope))
                * total_duration
                / scale
            )
            trend_strength = float(abs(fit.rvalue))
            if not np.isfinite(trend_strength):
                trend_strength = 1.0
            effective_relative_drift = float(
                projected_relative_slope
                * trend_strength
            )

        return (
            level,
            relative_range,
            max_relative_deviation,
            projected_relative_slope,
            trend_strength,
            effective_relative_drift,
        )

    for gene in gene_list:
        y = mean_df[f"{gene}_protein"].to_numpy(dtype=float)

        if not np.isfinite(y).all():
            results.append({
                "Gene": gene,
                "Method": "invalid trajectory",
                "P_inf": np.nan,
                "Tau": np.nan,
                "Beta": np.nan,
                "R2": np.nan,
                "t_steady": np.nan,
                "Relative Range": np.nan,
                "Final Distance": np.nan,
                "Stable Window Start": np.nan,
                "Stable Points": 0,
                "Stable Relative Range": np.nan,
                "Stable Max Deviation": np.nan,
                "Stable Relative Slope": np.nan,
                "Stable Trend Strength": np.nan,
                "Stable Effective Drift": np.nan,
                "Steady State?": False,
            })
            continue

        mean_level = float(np.mean(y))
        min_level = float(np.min(y))
        max_level = float(np.max(y))
        relative_range_full = float(
            (max_level - min_level)
            / max(abs(mean_level), 1e-12)
        )

        # --------------------------------------------------------------
        # Case 1: empirical maximal stable terminal suffix.
        # --------------------------------------------------------------
        n = len(y)

        # Search ALL terminal suffixes with at least min_stable_points and
        # select the earliest start among those that satisfy the stability
        # criteria. This matters for noisy plateaus: the final 5 points can
        # have an accidental nonzero regression slope even when a longer
        # terminal window is clearly stable.
        stable_candidates = []
        last_metrics = None

        for candidate_start in range(
            0,
            n - min_stable_points + 1,
        ):
            metrics = _stable_suffix_metrics(
                time_points[candidate_start:],
                y[candidate_start:],
            )
            last_metrics = metrics
            (
                candidate_mean,
                candidate_range,
                candidate_max_deviation,
                candidate_slope,
                candidate_trend_strength,
                candidate_effective_drift,
            ) = metrics

            if (
                candidate_max_deviation <= flat_tol
                and candidate_effective_drift <= slope_tol
            ):
                stable_candidates.append((
                    candidate_start,
                    candidate_mean,
                    candidate_range,
                    candidate_max_deviation,
                    candidate_slope,
                    candidate_trend_strength,
                    candidate_effective_drift,
                ))

        suffix_is_stable = bool(stable_candidates)

        if suffix_is_stable:
            (
                stable_start,
                suffix_mean,
                suffix_range,
                suffix_max_deviation,
                suffix_slope,
                suffix_trend_strength,
                suffix_effective_drift,
            ) = stable_candidates[0]

            P_inf = float(
                np.mean(y[stable_start:])
            )
            scale = max(abs(P_inf), 1e-12)
            relative_distance = np.abs(y - P_inf) / scale

            inside = relative_distance <= steady_tol
            stays_inside = np.logical_and.accumulate(
                inside[::-1]
            )[::-1]
            candidates = np.flatnonzero(stays_inside)

            t_steady = (
                float(time_points[int(candidates[0])])
                if len(candidates)
                else np.nan
            )

            final_distance = float(
                abs(y[-1] - P_inf) / scale
            )

            gene_steady = bool(
                np.isfinite(t_steady)
                and t_steady <= time_points[-1]
            )

            results.append({
                "Gene": gene,
                "Method": "stable suffix",
                "P_inf": P_inf,
                "Tau": np.nan,
                "Beta": np.nan,
                "R2": np.nan,
                "t_steady": t_steady,
                "Relative Range": relative_range_full,
                "Final Distance": final_distance,
                "Stable Window Start": float(
                    time_points[stable_start]
                ),
                "Stable Points": int(n - stable_start),
                "Stable Relative Range": float(suffix_range),
                "Stable Max Deviation": float(suffix_max_deviation),
                "Stable Relative Slope": float(suffix_slope),
                "Stable Trend Strength": float(suffix_trend_strength),
                "Stable Effective Drift": float(suffix_effective_drift),
                "Steady State?": gene_steady,
            })
            continue

        # --------------------------------------------------------------
        # Case 2: no stable observed tail. Keep the old fit only as a
        # diagnostic/extrapolation; classification remains False.
        # --------------------------------------------------------------
        if last_metrics is None:
            last_metrics = _stable_suffix_metrics(
                time_points[-min_stable_points:],
                y[-min_stable_points:],
            )
        (
            _,
            suffix_range,
            suffix_max_deviation,
            suffix_slope,
            suffix_trend_strength,
            suffix_effective_drift,
        ) = last_metrics

        P0 = float(y[0])

        def relaxation_model(t_fit, P_inf, tau, beta):
            return (
                P_inf
                + (P0 - P_inf)
                * np.exp(
                    -np.power(
                        np.maximum(t_fit, 0.0) / tau,
                        beta,
                    )
                )
            )

        tail_n = max(3, len(y) // 5)
        tail_mean = float(np.mean(y[-tail_n:]))

        median_dt = float(
            np.median(np.diff(t_fit_global))
        )
        tau_guess = max(
            float(t_fit_global[-1]) / 4.0,
            median_dt,
        )

        observed_scale = max(
            abs(min_level),
            abs(max_level),
            abs(mean_level),
            1.0,
        )

        try:
            popt, _ = curve_fit(
                relaxation_model,
                t_fit_global,
                y,
                p0=[
                    max(tail_mean, 0.0),
                    tau_guess,
                    1.0,
                ],
                bounds=(
                    [0.0, 1e-8, 0.2],
                    [
                        10.0 * observed_scale,
                        100.0 * max(
                            float(t_fit_global[-1]),
                            median_dt,
                        ),
                        5.0,
                    ],
                ),
                maxfev=50000,
            )

            P_inf, tau, beta = map(float, popt)
            fitted = relaxation_model(
                t_fit_global,
                P_inf,
                tau,
                beta,
            )

            ss_res = float(
                np.sum((y - fitted) ** 2)
            )
            ss_tot = float(
                np.sum((y - np.mean(y)) ** 2)
            )
            r2 = (
                1.0 - ss_res / ss_tot
                if ss_tot > 0
                else 1.0
            )

            initial_distance = abs(P0 - P_inf)
            allowed_distance = (
                steady_tol
                * max(abs(P_inf), 1e-12)
            )

            if initial_distance <= allowed_distance:
                fit_t_steady = 0.0
            else:
                ratio = (
                    initial_distance
                    / allowed_distance
                )
                fit_t_steady = float(
                    tau
                    * np.power(
                        np.log(ratio),
                        1.0 / beta,
                    )
                )

            fit_t_steady = float(
                time_points[0] + fit_t_steady
            )

            final_distance = float(
                abs(y[-1] - P_inf)
                / max(abs(P_inf), 1e-12)
            )

            results.append({
                "Gene": gene,
                "Method": "fit fallback (tail unstable)",
                "P_inf": P_inf,
                "Tau": tau,
                "Beta": beta,
                "R2": r2,
                "t_steady": fit_t_steady,
                "Relative Range": relative_range_full,
                "Final Distance": final_distance,
                "Stable Window Start": np.nan,
                "Stable Points": 0,
                "Stable Relative Range": float(suffix_range),
                "Stable Max Deviation": float(suffix_max_deviation),
                "Stable Relative Slope": float(suffix_slope),
                "Stable Trend Strength": float(suffix_trend_strength),
                "Stable Effective Drift": float(suffix_effective_drift),
                "Steady State?": False,
            })

        except (
            RuntimeError,
            ValueError,
            FloatingPointError,
        ):
            results.append({
                "Gene": gene,
                "Method": "fit failed",
                "P_inf": np.nan,
                "Tau": np.nan,
                "Beta": np.nan,
                "R2": np.nan,
                "t_steady": np.nan,
                "Relative Range": relative_range_full,
                "Final Distance": np.nan,
                "Stable Window Start": np.nan,
                "Stable Points": 0,
                "Stable Relative Range": float(suffix_range),
                "Stable Max Deviation": float(suffix_max_deviation),
                "Stable Relative Slope": float(suffix_slope),
                "Stable Trend Strength": float(suffix_trend_strength),
                "Stable Effective Drift": float(suffix_effective_drift),
                "Steady State?": False,
            })

    summary_df = pd.DataFrame(results)
    is_steady = bool(
        summary_df["Steady State?"].all()
    )
    return is_steady, summary_df


def calculate_pairwise_gene_gene_correlation_matrix(
    simulation_data,
    gene_list,
    use_clone=True,
):
    """
    Gene-gene Spearman correlation matrix from the raw one-row-per-cell table.

    use_clone=False
        Ordinary unweighted cell-level Spearman for Step 1.

    use_clone=True
        Clone-weighted Spearman. If clone c has n_c raw cells, every cell in
        that clone receives weight 1/n_c, so the clone's total contribution is
        exactly 1 regardless of clone size.

    This flag is independent of `unit`. `unit` is used only for twin-derived
    statistics in later steps.

    Twin-expanded data must not be passed here. If cell_id is available, this
    function explicitly rejects duplicated cell_id values.
    """
    if not isinstance(use_clone, (bool, np.bool_)):
        raise ValueError("use_clone must be True or False")

    gene_cols = [f"{gene}_mRNA" for gene in gene_list]

    missing = [c for c in gene_cols if c not in simulation_data.columns]
    if missing:
        raise ValueError(f"Could not find gene column(s): {missing}")

    if "cell_id" in simulation_data.columns:
        duplicated = simulation_data["cell_id"].duplicated(keep=False)
        if duplicated.any():
            example = simulation_data.loc[duplicated, "cell_id"].iloc[0]
            raise ValueError(
                "Ordinary gene-gene rho requires one row per physical cell; "
                f"cell_id={example!r} appears more than once."
            )

    values = simulation_data[gene_cols].to_numpy(dtype=float)
    if not np.isfinite(values).all():
        raise ValueError("NaN/Inf values found while calculating gene-gene rho")

    if use_clone:
        if "clone_id" not in simulation_data.columns:
            raise ValueError("use_clone=True requires a 'clone_id' column")
        weights = get_clone_weights(simulation_data)
        correlation_matrix = _weighted_spearman_matrix(values, weights)
        return pd.DataFrame(
            correlation_matrix,
            index=gene_list,
            columns=gene_list,
        )

    correlations = {}
    for gene_1 in gene_list:
        for gene_2 in gene_list:
            gene_gene_corr = spearmanr(
                simulation_data[f"{gene_1}_mRNA"],
                simulation_data[f"{gene_2}_mRNA"],
            ).correlation
            correlations[f"{gene_1}-{gene_2}"] = gene_gene_corr

    return dict_to_matrix(correlations, gene_list)


def get_correlations(correlation_dict, gene_i, gene_j):
   """Look up the correlation for (gene_i, gene_j) in a dict keyed by sorted gene-pair tuples."""
   return correlation_dict[tuple(sorted([gene_i, gene_j]))]



def _prepare_observed_delta_rows(twin_table, gene_list, unit=None):
    """
    Prepare the FIXED observed twin-difference rows used by rho_Delta.

    No raw cells are sampled here. Each row is one already-observed twin:
        Delta_g = g(member_0) - g(member_1).

    Rows are sorted into deterministic clone blocks. Reordering both members
    together does not change the observed statistic.
    """
    unit = _resolve_unit(unit)
    gene_cols = [f"{gene}_mRNA" for gene in gene_list]

    rep_0, rep_1 = split_twins(twin_table)
    rep_0 = rep_0.sort_values(
        ["clone_id", "twin_id"],
        kind="stable",
    ).reset_index(drop=True)
    rep_1 = rep_1.set_index("twin_id").loc[
        rep_0["twin_id"]
    ].reset_index()

    if not rep_0["twin_id"].equals(rep_1["twin_id"]):
        raise ValueError("twin_id alignment was lost")
    if not rep_0["clone_id"].equals(rep_1["clone_id"]):
        raise ValueError("clone_id differs within an observed twin")

    delta = (
        rep_0[gene_cols].to_numpy(dtype=float)
        - rep_1[gene_cols].to_numpy(dtype=float)
    )
    if not np.isfinite(delta).all():
        raise ValueError("Observed Delta rows contain NaN/Inf")

    clone_ids = rep_0["clone_id"].to_numpy(dtype=object)
    weights = get_unit_weights(rep_0, unit=unit)

    groups = _source_slot_indices_by_clone(clone_ids)
    clone_order = np.asarray(list(groups), dtype=object)

    # rep_0 is already sorted by clone_id, so every clone occupies one
    # contiguous row block. Cache integer starts/sizes once for fast null draws.
    block_sizes = np.asarray(
        [len(groups[c]) for c in clone_order],
        dtype=np.int64,
    )
    block_starts = np.empty(len(block_sizes), dtype=np.int64)
    block_starts[0] = 0
    if len(block_sizes) > 1:
        block_starts[1:] = np.cumsum(block_sizes[:-1])

    clone_to_block = {
        clone_id: i
        for i, clone_id in enumerate(clone_order)
    }

    return {
        "delta": delta,
        "clone_ids": clone_ids,
        "weights": weights,
        "groups": groups,
        "clone_order": clone_order,
        "block_sizes": block_sizes,
        "block_starts": block_starts,
        "clone_to_block": clone_to_block,
        "twin_ids": rep_0["twin_id"].to_numpy(dtype=object),
    }


def _clone_block_row_permutation_from_cache(
    prep,
    rng,
    explicit_clone_order=None,
    explicit_block_order=None,
    random_keys=None,
    validate=False,
):
    """
    Fast whole-clone row permutation for fixed-Delta nulls.

    Uses cached contiguous block starts/sizes from _prepare_observed_delta_rows.
    No per-draw clone->row list construction or np.concatenate over clone arrays.
    """
    clone_order = prep["clone_order"]
    block_sizes = prep["block_sizes"]
    block_starts = prep["block_starts"]
    n_blocks = len(clone_order)

    if n_blocks < 2:
        raise ValueError(
            "Need at least 2 biological clones for a clone-block Delta null"
        )

    identity = np.arange(n_blocks, dtype=np.int64)

    if explicit_block_order is not None:
        order_idx = np.asarray(
            explicit_block_order,
            dtype=np.int64,
        )
        if order_idx.shape != (n_blocks,):
            raise ValueError(
                "explicit_block_order must have one entry per local clone"
            )
        if validate:
            if (
                np.any(order_idx < 0)
                or np.any(order_idx >= n_blocks)
                or len(np.unique(order_idx)) != n_blocks
            ):
                raise ValueError(
                    "explicit_block_order must be a permutation of local block indices"
                )
        if np.array_equal(order_idx, identity):
            order_idx = np.roll(order_idx, -1)

    elif explicit_clone_order is not None:
        explicit_clone_order = np.asarray(
            explicit_clone_order,
            dtype=object,
        )
        if len(explicit_clone_order) != n_blocks:
            raise ValueError(
                "explicit_clone_order must contain every local clone exactly once"
            )
        try:
            order_idx = np.asarray(
                [prep["clone_to_block"][c] for c in explicit_clone_order],
                dtype=np.int64,
            )
        except KeyError as exc:
            raise ValueError(
                f"Unknown clone in explicit_clone_order: {exc.args[0]!r}"
            ) from None

        if validate and len(np.unique(order_idx)) != n_blocks:
            raise ValueError(
                "explicit_clone_order must contain every local clone exactly once"
            )
        if np.array_equal(order_idx, identity):
            order_idx = np.roll(order_idx, -1)

    elif random_keys is not None:
        if isinstance(random_keys, dict):
            key_values = np.asarray(
                [random_keys[c] for c in clone_order],
                dtype=float,
            )
        else:
            key_values = np.asarray(random_keys, dtype=float)
            if key_values.shape != (n_blocks,):
                raise ValueError(
                    "random_keys must have one value per local clone"
                )
        order_idx = np.argsort(
            key_values,
            kind="stable",
        ).astype(np.int64, copy=False)
        if np.array_equal(order_idx, identity):
            order_idx = np.roll(order_idx, -1)

    else:
        while True:
            order_idx = rng.permutation(n_blocks)
            if not np.array_equal(order_idx, identity):
                break

    ordered_sizes = block_sizes[order_idx]

    # For each output row, identify its source block and within-block offset.
    repeated_block = np.repeat(order_idx, ordered_sizes)
    output_block_start = np.repeat(
        np.r_[0, np.cumsum(ordered_sizes[:-1])],
        ordered_sizes,
    )
    within_block = (
        np.arange(int(block_sizes.sum()), dtype=np.int64)
        - output_block_start
    )
    perm_idx = (
        block_starts[repeated_block]
        + within_block
    )

    if validate:
        if len(perm_idx) != int(block_sizes.sum()):
            raise AssertionError("clone-block permutation changed row count")
        if len(np.unique(perm_idx)) != len(perm_idx):
            raise AssertionError(
                "clone-block permutation did not use every Delta row exactly once"
            )

    return perm_idx, clone_order[order_idx]


def _clone_block_row_permutation(
    groups,
    clone_order,
    rng,
    random_keys=None,
    explicit_clone_order=None,
):
    """
    Permute Y-Delta rows by WHOLE CLONE BLOCKS.

    Every observed Delta row is used exactly once. The rows belonging to one
    biological clone stay together, and their internal order is unchanged.
    Only the order of clone blocks is randomized.

    Unequal clone sizes are therefore allowed naturally: blocks are moved as
    variable-length segments rather than requiring clone A and clone B to have
    the same number of twin rows.

    `random_keys` may be supplied as {clone_id: float}. This lets t1 and t2 use
    the same clone-level randomization keys for shared clones in the d null.
    """
    clone_order = np.asarray(clone_order, dtype=object)
    if len(clone_order) < 2:
        raise ValueError(
            "Need at least 2 biological clones for a clone-block Delta null"
        )

    if explicit_clone_order is not None:
        permuted_clones = np.asarray(explicit_clone_order, dtype=object)
        if (
            len(permuted_clones) != len(clone_order)
            or set(permuted_clones) != set(clone_order)
        ):
            raise ValueError(
                "explicit_clone_order must contain every local clone exactly once"
            )
        if np.array_equal(permuted_clones, clone_order):
            permuted_clones = np.roll(permuted_clones, -1)

    elif random_keys is None:
        # Reject only the complete identity ordering; ordinary block
        # permutations may otherwise contain fixed block positions.
        while True:
            permuted_clones = rng.permutation(clone_order)
            if not np.array_equal(permuted_clones, clone_order):
                break
    else:
        missing = [c for c in clone_order if c not in random_keys]
        if missing:
            raise ValueError(
                f"Missing random clone key(s): {missing[:5]}"
            )
        permuted_clones = np.asarray(
            sorted(
                clone_order,
                key=lambda c: (random_keys[c], str(c)),
            ),
            dtype=object,
        )

        # If the supplied keys happen to reproduce the identity, rotate one
        # block. This keeps the same shared ordering information but prevents
        # the null realization from being exactly the observed alignment.
        if np.array_equal(permuted_clones, clone_order):
            permuted_clones = np.roll(permuted_clones, -1)

    perm_idx = np.concatenate([
        groups[c] for c in permuted_clones
    ]).astype(int, copy=False)

    n_rows = sum(len(groups[c]) for c in clone_order)
    if len(perm_idx) != n_rows:
        raise AssertionError("clone-block permutation changed row count")
    if len(np.unique(perm_idx)) != n_rows:
        raise AssertionError(
            "clone-block permutation did not use every Delta row exactly once"
        )

    return perm_idx, permuted_clones


def _prepare_delta_rank_permutation_cache(delta, weights):
    """
    Precompute everything that does not change across fixed-Delta null draws.

    The Delta VALUES never change; only which source-row weight is attached to
    each Y-Delta value changes after a row permutation.

    We therefore compute once:
      - each gene's stable argsort;
      - each gene's tie-block boundaries;
      - the fixed X weighted ranks / centered ranks / scale.

    For unit="twin" (all weights equal), Y weighted ranks themselves are also
    invariant and can simply be permuted.

    For unit="clone" (unequal row weights), a draw recomputes weighted midranks
    WITHOUT sorting:
      1. gather the permuted row weights in the precomputed sorted-value order;
      2. cumulative-sum those weights;
      3. collapse exact tie blocks to their weighted midrank;
      4. scatter ranks back to rows.

    This is mathematically identical to calling weighted_rank() after every
    permutation, but avoids O(G * N log N) sorting and Python row loops.
    """
    delta = np.asarray(delta, dtype=float)
    weights = np.asarray(weights, dtype=float)

    if delta.ndim != 2:
        raise ValueError("delta must have shape (n_rows, n_genes)")
    if len(weights) != delta.shape[0]:
        raise ValueError("weights must match delta rows")
    if not np.isfinite(delta).all():
        raise ValueError("delta contains NaN/Inf")
    if (
        np.any(weights < 0)
        or not np.isfinite(weights).all()
        or weights.sum() <= 0
    ):
        raise ValueError("invalid weights")

    n_rows, n_genes = delta.shape

    # G x N: original row indices in ascending value order for each gene.
    order = np.argsort(
        delta,
        axis=0,
        kind="stable",
    ).T
    sorted_values = np.take_along_axis(
        delta.T,
        order,
        axis=1,
    )

    tie_starts = []
    tie_lengths = []
    has_ties = np.zeros(n_genes, dtype=bool)

    for g in range(n_genes):
        starts = np.r_[
            0,
            1 + np.flatnonzero(
                sorted_values[g, 1:] != sorted_values[g, :-1]
            ),
        ].astype(int)
        lengths = np.diff(np.r_[starts, n_rows]).astype(int)
        tie_starts.append(starts)
        tie_lengths.append(lengths)
        has_ties[g] = len(starts) != n_rows

    cache = {
        "delta": delta,
        "weights": weights,
        "order": order,
        "sorted_values": sorted_values,
        "tie_starts": tie_starts,
        "tie_lengths": tie_lengths,
        "has_ties": has_ties,
        "equal_weights": bool(np.allclose(weights, weights[0])),
        "weight_sum": float(weights.sum()),
        "rank_rows": np.arange(n_genes)[:, None],
    }

    # Fixed X ranks use the original source-row weights.
    rx_gn = _weighted_ranks_from_rank_cache(
        cache,
        weights,
    )
    rx = rx_gn.T
    mx = np.sum(weights[:, None] * rx, axis=0) / weights.sum()
    cx = rx - mx
    sx = np.sqrt(
        np.sum(weights[:, None] * cx * cx, axis=0)
    )

    cache["cx"] = cx
    cache["sx"] = sx
    cache["weighted_cx_T"] = (
        weights[:, None] * cx
    ).T

    if cache["equal_weights"]:
        # With equal weights, a value permutation only permutes the already
        # computed centered Y ranks; their marginal scale is unchanged.
        cache["cy_equal"] = cx.copy()
        cache["sy_equal"] = sx.copy()

    return cache


@numba.njit(cache=True, nogil=True)
def _weighted_centered_ranks_and_scale_numba(
    order,
    sorted_values,
    weights_by_original_row,
    half_total_weight,
):
    """
    Exact weighted mid-ranks for fixed values, compiled for the null hot path.

    This deliberately keeps the ordinary per-gene tie scan. It does NOT use
    the flattened-tie optimization. For each gene:
      - scan its already-sorted fixed values;
      - sum the current tie block's reassigned row weights;
      - assign the weighted midrank;
      - center by total_weight / 2;
      - accumulate the weighted squared scale.

    Returns
    -------
    centered_ranks : (n_genes, n_rows)
        Centered ranks indexed by ORIGINAL fixed-value row.
    scale : (n_genes,)
        sqrt(sum w * centered_rank^2) for the reassigned weights.
    """
    n_genes, n_rows = order.shape
    centered = np.empty((n_genes, n_rows), dtype=np.float64)
    scale2 = np.empty(n_genes, dtype=np.float64)

    for g in range(n_genes):
        cumulative = 0.0
        acc = 0.0
        i = 0

        while i < n_rows:
            j = i + 1
            value = sorted_values[g, i]

            orig = order[g, i]
            tie_weight = weights_by_original_row[orig]

            while j < n_rows and sorted_values[g, j] == value:
                orig_j = order[g, j]
                tie_weight += weights_by_original_row[orig_j]
                j += 1

            rank_centered = (
                cumulative
                + 0.5 * tie_weight
                - half_total_weight
            )
            rank_sq = rank_centered * rank_centered

            for k in range(i, j):
                orig_k = order[g, k]
                centered[g, orig_k] = rank_centered
                acc += (
                    weights_by_original_row[orig_k]
                    * rank_sq
                )

            cumulative += tie_weight
            i = j

        scale2[g] = acc

    return centered, np.sqrt(scale2)


@numba.njit(cache=True, nogil=True)
def _weighted_centered_ranks_from_dynamic_order_numba(
    values,
    order,
    weights,
    half_total_weight,
):
    """
    Exact weighted centered midranks for DYNAMIC values.

    Parameters
    ----------
    values : (n_rows, n_genes) float64
        Values for one random-pair null draw.
    order : (n_genes, n_rows) int64
        Per-gene row indices sorted by `values[:, gene]`.
    weights : (n_rows,) float64
        Row weights for this draw.

    Notes
    -----
    Tie handling is exact and gene-by-gene. This deliberately does not use the
    rejected flattened-tie optimization.
    """
    n_genes, n_rows = order.shape
    centered = np.empty(
        (n_genes, n_rows),
        dtype=np.float64,
    )
    scale2 = np.empty(n_genes, dtype=np.float64)

    for g in range(n_genes):
        cumulative = 0.0
        acc = 0.0
        i = 0

        while i < n_rows:
            j = i + 1
            orig = order[g, i]
            value = values[orig, g]
            tie_weight = weights[orig]

            while (
                j < n_rows
                and values[order[g, j], g] == value
            ):
                tie_weight += weights[order[g, j]]
                j += 1

            rank_centered = (
                cumulative
                + 0.5 * tie_weight
                - half_total_weight
            )
            rank_sq = rank_centered * rank_centered

            for k in range(i, j):
                orig_k = order[g, k]
                centered[g, orig_k] = rank_centered
                acc += weights[orig_k] * rank_sq

            cumulative += tie_weight
            i = j

        scale2[g] = acc

    return centered, np.sqrt(scale2)


def _dynamic_weighted_spearman_pairs_from_order(
    values,
    order_gn,
    weights,
    pair_i,
    pair_j,
):
    """
    Exact weighted Spearman values for selected pairs when Delta changes.

    `order_gn` is already sorted, so this function avoids rebuilding the much
    heavier fixed-value rank-cache metadata on every random-pair draw.
    """
    values = np.asarray(values, dtype=float)
    weights = np.asarray(weights, dtype=float)
    order_gn = np.asarray(order_gn, dtype=np.int64)

    centered_gn, scale = (
        _weighted_centered_ranks_from_dynamic_order_numba(
            values,
            order_gn,
            weights,
            0.5 * float(weights.sum()),
        )
    )

    centered = centered_gn.T

    # Full covariance is substantially faster than gathering every requested
    # pair into large temporary matrices, especially for larger panels.
    cov = centered.T @ (
        weights[:, None] * centered
    )

    den = scale[pair_i] * scale[pair_j]
    out = np.full(len(pair_i), np.nan, dtype=float)
    valid = den > 0
    out[valid] = (
        cov[pair_i[valid], pair_j[valid]]
        / den[valid]
    )
    return out


def _weighted_ranks_from_rank_cache(cache, weights_by_original_row):
    """
    Exact weighted ranks of the FIXED Delta values for arbitrary row weights.

    Returns shape (n_genes, n_rows), indexed by ORIGINAL Delta row.
    No argsort is performed here.
    """
    weights_by_original_row = np.asarray(
        weights_by_original_row,
        dtype=float,
    )
    order = cache["order"]
    n_genes, n_rows = order.shape

    if len(weights_by_original_row) != n_rows:
        raise ValueError("weights_by_original_row has wrong length")

    # G x N weights in each gene's already-known sorted-value order.
    #
    # Reuse held buffers instead of allocating several ~G x N arrays on every
    # rank-cache call. The cache is private to this rank problem, so the same
    # workspace can be reused draw after draw.
    buf = cache.get("_buf")
    if buf is None:
        buf = cache["_buf"] = {
            "flat_order": order.ravel(),
            "flat_scatter": (
                order
                + np.arange(n_genes)[:, None] * n_rows
            ).ravel(),
            "sw": np.empty((n_genes, n_rows)),
            "rs": np.empty((n_genes, n_rows)),
            "out": np.empty((n_genes, n_rows)),
        }

    sorted_w = buf["sw"]
    np.take(
        weights_by_original_row,
        buf["flat_order"],
        out=sorted_w.reshape(-1),
    )

    # Fast no-tie formula:
    # weighted midrank = cumulative weight through current row - weight/2.
    rank_sorted = buf["rs"]
    np.cumsum(
        sorted_w,
        axis=1,
        out=rank_sorted,
    )
    rank_sorted -= 0.5 * sorted_w

    # Exact weighted tie handling. Usually this branch is sparse or absent.
    for g in np.flatnonzero(cache["has_ties"]):
        starts = cache["tie_starts"][g]
        lengths = cache["tie_lengths"][g]

        group_w = np.add.reduceat(
            sorted_w[g],
            starts,
        )
        group_mid = (
            np.cumsum(group_w)
            - 0.5 * group_w
        )
        rank_sorted[g] = np.repeat(
            group_mid,
            lengths,
        )

    # Scatter sorted ranks back to ORIGINAL row identity.
    ranks_original = buf["out"]
    ranks_original.reshape(-1)[
        buf["flat_scatter"]
    ] = rank_sorted.reshape(-1)
    return ranks_original


def _weighted_gather_ranks_from_cache(
    cache,
    target_idx,
    source_weights,
):
    """
    Exact weighted ranks for values gathered from fixed rows WITH replacement.

    target_idx[r] gives the original fixed-value row used at source position r.
    Instead of sorting the gathered values again:
      1. aggregate source weights onto original fixed rows with bincount;
      2. compute weighted ranks using the precomputed value sort/tie structure;
      3. gather those ranks back to source positions.

    This is exactly equivalent to
        weighted_rank(values[target_idx, g], source_weights)
    for every gene, including duplicate target rows and exact value ties.
    """
    target_idx = np.asarray(target_idx, dtype=int)
    source_weights = np.asarray(source_weights, dtype=float)
    n_rows = cache["order"].shape[1]

    if target_idx.shape != (n_rows,):
        raise ValueError("target_idx has wrong shape")
    if source_weights.shape != (n_rows,):
        raise ValueError("source_weights has wrong shape")

    weight_by_original_row = np.bincount(
        target_idx,
        weights=source_weights,
        minlength=n_rows,
    )

    ranks_original_gn = _weighted_ranks_from_rank_cache(
        cache,
        weight_by_original_row,
    )
    return ranks_original_gn[:, target_idx].T


def _cross_delta_spearman_from_permutation(
    cache,
    perm_idx,
    validate=False,
):
    """
    Exact fixed-Delta Spearman null for one Y-row permutation.

    The fixed value sort orders are cached once. In clone-weighted mode, exact
    weighted tie ranks are recomputed by a compiled Numba kernel using only the
    reassigned row weights; no argsort occurs in the draw loop.
    """
    perm_idx = np.asarray(perm_idx, dtype=np.int64)
    weights = cache["weights"]
    n_rows = len(weights)

    if perm_idx.shape != (n_rows,):
        raise ValueError("perm_idx has wrong shape")
    if validate and len(np.unique(perm_idx)) != n_rows:
        raise ValueError("perm_idx must be a true row permutation")

    if cache["equal_weights"]:
        cy = cache["cy_equal"][perm_idx, :]
        sy = cache["sy_equal"]

        numer = cache["weighted_cx_T"] @ cy

    else:
        # Original Y row r lands at source position inv_perm[r].
        inv_perm = np.empty(n_rows, dtype=np.int64)
        inv_perm[perm_idx] = np.arange(
            n_rows,
            dtype=np.int64,
        )

        y_weight_by_original_row = weights[inv_perm]

        cy_original_gn, sy = (
            _weighted_centered_ranks_and_scale_numba(
                cache["order"],
                cache["sorted_values"],
                y_weight_by_original_row,
                0.5 * cache["weight_sum"],
            )
        )

        # Re-index the fixed weighted-X columns into ORIGINAL Y-row order.
        # This is algebraically identical to gathering Y ranks into source-row
        # order, but avoids constructing the N x G gathered-Y matrix.
        numer = (
            cache["weighted_cx_T"][:, inv_perm]
            @ cy_original_gn.T
        )

    den = np.outer(cache["sx"], sy)

    with np.errstate(divide="ignore", invalid="ignore"):
        out = numer / den
    out[den == 0] = np.nan
    return out


def _cross_delta_spearman_matrix(delta_x, delta_y, weights):
    """
    Weighted Spearman cross-correlation matrix:
        rows/genes of delta_x versus rows/genes of delta_y.

    Used for the null where X Delta stays fixed and Y Delta rows are permuted.
    """
    delta_x = np.asarray(delta_x, dtype=float)
    delta_y = np.asarray(delta_y, dtype=float)
    weights = np.asarray(weights, dtype=float)

    if delta_x.shape != delta_y.shape:
        raise ValueError("delta_x and delta_y must have identical shape")
    if delta_x.shape[0] != len(weights):
        raise ValueError("weights must match the number of Delta rows")

    n_genes = delta_x.shape[1]

    rx = np.column_stack([
        weighted_rank(delta_x[:, g], weights)
        for g in range(n_genes)
    ])
    ry = np.column_stack([
        weighted_rank(delta_y[:, g], weights)
        for g in range(n_genes)
    ])

    mx = np.sum(weights[:, None] * rx, axis=0) / weights.sum()
    my = np.sum(weights[:, None] * ry, axis=0) / weights.sum()
    cx = rx - mx
    cy = ry - my

    sx = np.sqrt(np.sum(weights[:, None] * cx * cx, axis=0))
    sy = np.sqrt(np.sum(weights[:, None] * cy * cy, axis=0))
    den = np.outer(sx, sy)

    numer = cx.T @ (weights[:, None] * cy)
    with np.errstate(divide="ignore", invalid="ignore"):
        out = numer / den
    out[den == 0] = np.nan
    return out


def _prepare_global_clone_order_maps(t1_twins, t2_twins):
    """
    Build one clone universe for Step-2 / Step-3 null reuse.

    A single random permutation of this union can be filtered to t1 or t2.
    Shared biological clones therefore keep the same relative random order
    across time, exactly the dependence needed by d.
    """
    t1_labels = np.asarray(pd.unique(t1_twins["clone_id"]), dtype=object)
    t2_labels = np.asarray(pd.unique(t2_twins["clone_id"]), dtype=object)
    union_labels = np.asarray(
        list(dict.fromkeys(list(t1_labels) + list(t2_labels))),
        dtype=object,
    )
    lookup = {label: i for i, label in enumerate(union_labels)}

    def _make_filter(local_labels):
        union_to_local = np.full(len(union_labels), -1, dtype=np.int32)
        for local_i, label in enumerate(local_labels):
            union_to_local[lookup[label]] = local_i
        return union_to_local

    return {
        "union_labels": union_labels,
        "t1_labels": t1_labels,
        "t2_labels": t2_labels,
        "t1_filter": _make_filter(t1_labels),
        "t2_filter": _make_filter(t2_labels),
    }


def _local_clone_order_from_seed(seed, union_size, union_to_local):
    """Generate one global clone permutation from seed and filter to a timepoint."""
    rng = np.random.default_rng(int(seed))
    global_order = rng.permutation(int(union_size))
    local_order = union_to_local[global_order]
    return local_order[local_order >= 0]


def _fixed_delta_null_chunk(
    draw_indices,
    prep,
    rank_cache,
    pair_i,
    pair_j,
    shuffle_seeds,
    union_size,
    union_to_local,
    local_to_block,
):
    """Compute one shared-memory chunk of fixed-Delta null draws."""
    draw_indices = np.asarray(draw_indices, dtype=np.int64)
    out = np.empty(
        (len(draw_indices), len(pair_i)),
        dtype=float,
    )

    # Explicit block order means this RNG is not consumed by the block helper.
    dummy_rng = np.random.default_rng(0)

    for q, b in enumerate(draw_indices):
        local_order_idx = _local_clone_order_from_seed(
            shuffle_seeds[b],
            union_size,
            union_to_local,
        )
        block_order = local_to_block[local_order_idx]

        perm_idx, _ = _clone_block_row_permutation_from_cache(
            prep,
            dummy_rng,
            explicit_block_order=block_order,
        )

        null_matrix = _cross_delta_spearman_from_permutation(
            rank_cache,
            perm_idx,
        )
        out[q, :] = null_matrix[pair_i, pair_j]

    return int(draw_indices[0]), out


def _fixed_delta_null_matrix(
    prep,
    rank_cache,
    pair_i,
    pair_j,
    n_shuffles,
    random_state,
    shuffle_seeds=None,
    global_clone_map=None,
    timepoint_key=None,
    n_cores_to_use=1,
):
    """
    Core fixed-Delta null generator.

    With shuffle_seeds, draws are independent and deterministic by draw index,
    so they can be split across shared-memory worker threads without changing
    the null or the t1/t2 shared-clone coupling.
    """
    n_shuffles = int(n_shuffles)
    n_cores_to_use = max(1, int(n_cores_to_use))

    # Compile the Numba rank kernel once on the main thread before workers start.
    if not rank_cache["equal_weights"]:
        tiny_order = np.zeros((1, 1), dtype=np.int64)
        tiny_values = np.zeros((1, 1), dtype=np.float64)
        tiny_weights = np.ones(1, dtype=np.float64)
        _weighted_centered_ranks_and_scale_numba(
            tiny_order,
            tiny_values,
            tiny_weights,
            0.5,
        )

    # Preserve the legacy sequential-RNG path when explicit per-draw seeds are
    # not supplied.
    if shuffle_seeds is None:
        rng = np.random.default_rng(random_state)
        out = np.empty(
            (n_shuffles, len(pair_i)),
            dtype=float,
        )
        for b in range(n_shuffles):
            perm_idx, _ = _clone_block_row_permutation_from_cache(
                prep,
                rng,
            )
            null_matrix = _cross_delta_spearman_from_permutation(
                rank_cache,
                perm_idx,
            )
            out[b, :] = null_matrix[pair_i, pair_j]
        return out

    shuffle_seeds = np.asarray(
        shuffle_seeds,
        dtype=np.int64,
    )
    if len(shuffle_seeds) < n_shuffles:
        raise ValueError("shuffle_seeds is shorter than n_shuffles")
    if global_clone_map is None or timepoint_key not in ("t1", "t2"):
        raise ValueError(
            "global_clone_map and timepoint_key are required with shuffle_seeds"
        )

    union_size = len(global_clone_map["union_labels"])
    union_to_local = global_clone_map[
        f"{timepoint_key}_filter"
    ]
    local_labels = global_clone_map[
        f"{timepoint_key}_labels"
    ]

    # Map global-map local indices directly to the integer block indices used by
    # the prepared Delta table. This is built once, not once per draw.
    local_to_block = np.asarray(
        [
            prep["clone_to_block"][label]
            for label in local_labels
        ],
        dtype=np.int64,
    )

    if n_cores_to_use == 1 or n_shuffles < 2:
        start, out = _fixed_delta_null_chunk(
            np.arange(n_shuffles, dtype=np.int64),
            prep,
            rank_cache,
            pair_i,
            pair_j,
            shuffle_seeds,
            union_size,
            union_to_local,
            local_to_block,
        )
        return out

    n_jobs = min(
        n_cores_to_use,
        n_shuffles,
    )

    # A few chunks per worker improves load balance while keeping joblib
    # scheduling overhead negligible relative to thousands of draws.
    n_chunks = min(
        n_shuffles,
        max(n_jobs, 4 * n_jobs),
    )
    chunks = [
        chunk
        for chunk in np.array_split(
            np.arange(n_shuffles, dtype=np.int64),
            n_chunks,
        )
        if len(chunk)
    ]

    # Each null draw contains a small BLAS matrix multiply. Let outer draw-level
    # parallelism use the cores and force each BLAS call to one thread to avoid
    # nested oversubscription.
    with threadpool_limits(limits=1, user_api="blas"):
        results = Parallel(
            n_jobs=n_jobs,
            prefer="threads",
            require="sharedmem",
        )(
            delayed(_fixed_delta_null_chunk)(
                chunk,
                prep,
                rank_cache,
                pair_i,
                pair_j,
                shuffle_seeds,
                union_size,
                union_to_local,
                local_to_block,
            )
            for chunk in chunks
        )

    out = np.empty(
        (n_shuffles, len(pair_i)),
        dtype=float,
    )
    for start, values in results:
        out[
            start:start + len(values),
            :,
        ] = values

    return out


def _random_pair_null_chunk(
    prep,
    weights,
    pair_i,
    pair_j,
    draw_seeds,
):
    """
    Compute a chunk of fresh random-pair rho_Delta null draws.

    Random-pair sampling and RNG consumption are unchanged draw-by-draw. Delta
    matrices are stored as contiguous G x N arrays and sorted along their
    contiguous last axis with quicksort. Exact tie handling remains gene-by-gene
    in the compiled dynamic-rank kernel, so sort stability is not statistically
    relevant.
    """
    draw_seeds = np.asarray(draw_seeds, dtype=np.int64)

    n_draws = len(draw_seeds)
    n_slots = len(prep["source_clones"])
    n_genes = prep["raw_values"].shape[1]

    out = np.empty((n_draws, len(pair_i)), dtype=float)

    batch_size = min(4, max(1, n_draws))
    # B x G x N with N contiguous: argsort works along the fastest dimension.
    delta_batch_gn = np.empty(
        (batch_size, n_genes, n_slots),
        dtype=float,
    )

    sampling_cache = prep["random_pair_sampling_cache"]
    raw_values = prep["raw_values"]

    for start in range(0, n_draws, batch_size):
        stop = min(start + batch_size, n_draws)
        m = stop - start

        for local, b in enumerate(range(start, stop)):
            rng = np.random.default_rng(int(draw_seeds[b]))
            idx_a, idx_b = _sample_fresh_random_twin_indices(
                sampling_cache,
                rng,
                n_slots,
            )
            delta_batch_gn[local, :, :] = (
                raw_values[idx_a] - raw_values[idx_b]
            ).T

        values_batch_gn = delta_batch_gn[:m]
        order_batch = np.argsort(
            values_batch_gn,
            axis=2,
            kind="quicksort",
        )

        for local, b in enumerate(range(start, stop)):
            out[b, :] = _dynamic_weighted_spearman_pairs_from_order(
                values_batch_gn[local].T,
                order_batch[local],
                weights,
                pair_i,
                pair_j,
            )

    return out



def generate_random_shuffle(
    simulation_data,
    gene_list,
    gene_pairs=None,
    n_shuffles=10000,
    random_state=42,
    unit="clone",
    raw_cells=None,
    shuffle_seeds=None,
    global_clone_map=None,
    timepoint_key=None,
    n_cores_to_use=1,
):
    """
    Random-pair difference-correlation distribution for rho_Delta.

    This is the reference distribution underneath Step 2 / fan-out and the
    rho_Delta component of TwinScore. It is NOT a permutation of the observed
    twin Delta rows.

    For every observed twin slot and every null draw:
      1. choose random clone A uniformly from the raw-cell pool;
      2. choose random clone B uniformly from the remaining clones (B != A);
      3. choose one raw cell uniformly within clone A;
      4. choose one raw cell uniformly within clone B;
      5. form Delta_random = cell_A - cell_B.

    Thus both members of every null pair are freshly sampled and come from
    different biological clones. Clone choice is balanced before within-clone
    cell choice, so large clones are not selected merely because they contain
    more cells.

    The number of random-pair slots matches the observed twin statistic. Under
    unit="clone", the observed source-slot labels are used only to assign the
    same clone-total weights as the observed rho_Delta statistic; the sampled
    random cells themselves are independent of those source labels.

    Parameters retained for backward compatibility:
      - global_clone_map and timepoint_key are ignored here; they belong to the
        separate fixed-Delta Stage-3 d permutation and must not define the
        random-pair rho_Delta reference.
      - shuffle_seeds, when supplied, gives one independent seed per draw.

    `raw_cells` should be the original one-row-per-cell table for this timepoint
    (or the intended raw target pool). If omitted, simulation_data is used and
    duplicate physical cells are collapsed by cell_id when available.
    """
    del global_clone_map, timepoint_key

    unit = _resolve_unit(unit)
    n_shuffles = int(n_shuffles)
    if n_shuffles < 2:
        raise ValueError("n_shuffles must be at least 2")

    active_genes, requested_pairs = _requested_gene_subset(
        gene_list,
        gene_pairs,
    )
    if not requested_pairs:
        return {}

    pair_table = simulation_data
    if "twin_id" not in pair_table.columns:
        pair_table = assign_twin_id(pair_table)

    if raw_cells is None:
        raw_cells = simulation_data

    prep = _prepare_random_twin_null_inputs(
        pair_table,
        raw_cells,
        active_genes,
    )
    weights = get_unit_weights(prep["rep_0"], unit=unit)

    gene_to_idx = {
        gene: i for i, gene in enumerate(active_genes)
    }
    pair_i = np.asarray(
        [gene_to_idx[a] for a, _ in requested_pairs],
        dtype=int,
    )
    pair_j = np.asarray(
        [gene_to_idx[b] for _, b in requested_pairs],
        dtype=int,
    )
    pair_keys = list(requested_pairs)

    if shuffle_seeds is None:
        draw_seeds = _spawn_independent_seeds(
            int(random_state),
            n_shuffles,
        )
    else:
        draw_seeds = np.asarray(shuffle_seeds, dtype=np.int64)
        if len(draw_seeds) < n_shuffles:
            raise ValueError("shuffle_seeds is shorter than n_shuffles")
        draw_seeds = draw_seeds[:n_shuffles]

    n_cores_to_use = max(1, int(n_cores_to_use))

    if n_cores_to_use == 1 or n_shuffles < 2:
        null_values = _random_pair_null_chunk(
            prep,
            weights,
            pair_i,
            pair_j,
            draw_seeds,
        )
    else:
        n_chunks = min(n_cores_to_use, n_shuffles)
        seed_chunks = [
            chunk
            for chunk in np.array_split(draw_seeds, n_chunks)
            if len(chunk)
        ]
        with threadpool_limits(
            limits=1,
            user_api="blas",
        ):
            parts = Parallel(
                n_jobs=len(seed_chunks),
                prefer="threads",
                require="sharedmem",
            )(
                delayed(_random_pair_null_chunk)(
                    prep,
                    weights,
                    pair_i,
                    pair_j,
                    chunk,
                )
                for chunk in seed_chunks
            )
        null_values = np.vstack(parts)

    return {
        key: null_values[:, k]
        for k, key in enumerate(pair_keys)
    }



def generate_divergence_shuffle(
    twin_table,
    gene_list,
    gene_pairs=None,
    n_shuffles=10000,
    random_state=314159,
    unit="clone",
    shuffle_seeds=None,
    n_cores_to_use=1,
):
    """
    Yuval fixed-Delta null for within-twin X/Y coupling.

    The observed twin differences are kept exactly as measured. For every
    requested gene pair (X, Y), Delta_X stays attached to its observed twin
    row while the entire vector of observed Delta_Y values is reassigned
    one-to-one across twin rows.

    The reassignment has two constraints:
      1. every observed Delta_Y row is used exactly once per shuffle;
      2. a source twin row can never receive Delta_Y from its own biological
         clone.

    Thus the null destroys only the observed matching of Delta_X to Delta_Y
    across biological clones. It does not redraw cells, alter the marginal
    Delta distributions, or replace twins with unrelated-cell differences.

    unit="twin" (legacy alias "pair")
        Every enumerated twin row has weight 1.

    unit="clone"
        Every biological clone has total weight 1, split equally across that
        clone's enumerated twin rows.

    Returns
    -------
    dict
        {sorted_gene_pair: array(n_shuffles)} containing rho_Delta values
        under the fixed-Delta cross-clone reassignment null.
    """
    unit = _resolve_unit(unit)
    n_shuffles = int(n_shuffles)
    if n_shuffles < 2:
        raise ValueError("n_shuffles must be at least 2")

    active_genes, requested_pairs = _requested_gene_subset(
        gene_list,
        gene_pairs,
    )
    if not requested_pairs:
        return {}

    if "twin_id" not in twin_table.columns:
        twin_table = assign_twin_id(twin_table)

    prep = _prepare_observed_delta_rows(
        twin_table,
        active_genes,
        unit=unit,
    )
    delta = prep["delta"]
    weights = prep["weights"]
    clone_ids = prep["clone_ids"]

    gene_to_idx = {
        gene: i for i, gene in enumerate(active_genes)
    }
    pair_i = np.asarray(
        [gene_to_idx[a] for a, _ in requested_pairs],
        dtype=int,
    )
    pair_j = np.asarray(
        [gene_to_idx[b] for _, b in requested_pairs],
        dtype=int,
    )

    if shuffle_seeds is None:
        draw_seeds = _spawn_independent_seeds(
            int(random_state),
            n_shuffles,
        )
    else:
        draw_seeds = np.asarray(shuffle_seeds, dtype=np.int64)
        if len(draw_seeds) < n_shuffles:
            raise ValueError("shuffle_seeds is shorter than n_shuffles")
        draw_seeds = draw_seeds[:n_shuffles]

    null_values = _weighted_cross_permutation_null(
        delta,
        delta,
        weights,
        clone_ids,
        draw_seeds,
        pair_i,
        pair_j,
        n_cores_to_use=n_cores_to_use,
    )

    return {
        pair: null_values[:, k]
        for k, pair in enumerate(requested_pairs)
    }


def generate_divergence_difference_shuffle(
    t1_twins,
    t2_twins,
    gene_list,
    gene_pairs=None,
    n_shuffles=10000,
    random_state=271833,
    unit="clone",
    precomputed_t1_null=None,
    precomputed_t2_null=None,
    n_cores_to_use=1,
):
    """
    Yuval fixed-Delta null for the change in within-twin coupling across time.

    The observed statistic is

        d = rho_Delta(t2) - rho_Delta(t1).

    At each time point, every measured Delta value is kept exactly and only the
    matching between Delta_X and Delta_Y is broken by the same cross-clone,
    one-to-one reassignment used by :func:`generate_divergence_shuffle`.

    The t1 and t2 fixed-Delta re-pairings are sampled independently. Therefore
    this null changes neither time point's marginal Delta distribution and does
    not introduce an artificial cross-time pairing between shuffled twins.

    Returns
    -------
    d_null_by_pair : dict
        {sorted_gene_pair: array(n_shuffles)} with
        rho_Delta_div_null(t2) - rho_Delta_div_null(t1).
    meta : dict
        Metadata describing the null.
    """
    unit = _resolve_unit(unit)
    n_shuffles = int(n_shuffles)
    if n_shuffles < 2:
        raise ValueError("n_shuffles must be at least 2")

    _, requested_pairs = _requested_gene_subset(gene_list, gene_pairs)
    if not requested_pairs:
        return {}, {
            "null_type": "fixed_delta_y_cross_clone_permutation",
            "timepoint_repairings_independent": True,
            "n_shuffles": n_shuffles,
            "unit": unit,
        }

    # Use independent deterministic streams for the two time points.
    root = np.random.SeedSequence(int(random_state))
    child_t1, child_t2 = root.spawn(2)
    seed_t1 = int(child_t1.generate_state(1)[0])
    seed_t2 = int(child_t2.generate_state(1)[0])

    if precomputed_t1_null is None:
        t1_null = generate_divergence_shuffle(
            t1_twins,
            gene_list=gene_list,
            gene_pairs=requested_pairs,
            n_shuffles=n_shuffles,
            random_state=seed_t1,
            unit=unit,
            n_cores_to_use=n_cores_to_use,
        )
    else:
        t1_null = {
            key: np.asarray(values, dtype=float)[:n_shuffles]
            for key, values in precomputed_t1_null.items()
        }

    if precomputed_t2_null is None:
        t2_null = generate_divergence_shuffle(
            t2_twins,
            gene_list=gene_list,
            gene_pairs=requested_pairs,
            n_shuffles=n_shuffles,
            random_state=seed_t2,
            unit=unit,
            n_cores_to_use=n_cores_to_use,
        )
    else:
        t2_null = {
            key: np.asarray(values, dtype=float)[:n_shuffles]
            for key, values in precomputed_t2_null.items()
        }

    out = {}
    for pair in requested_pairs:
        key = tuple(sorted(pair))
        if key not in t1_null or key not in t2_null:
            raise ValueError(
                f"Missing fixed-Delta null values for gene pair {key}"
            )
        a = np.asarray(t1_null[key], dtype=float)
        b = np.asarray(t2_null[key], dtype=float)
        if len(a) < n_shuffles or len(b) < n_shuffles:
            raise ValueError(
                f"Precomputed fixed-Delta null for {key} is shorter than n_shuffles"
            )
        out[key] = b[:n_shuffles] - a[:n_shuffles]

    meta = {
        "null_type": "fixed_delta_y_cross_clone_permutation",
        "observed_delta_rows_fixed": True,
        "delta_x_fixed": True,
        "delta_y_repaired_one_to_one_across_clones": True,
        "fresh_cells_sampled": False,
        "timepoint_repairings_independent": True,
        "n_shuffles": n_shuffles,
        "unit": unit,
    }
    return out, meta


def compute_correlation_matrix(gene_matrix_1, gene_matrix_2, gene_list, gene_pairs=None):
   """Compute Spearman correlations between gene expression matrices."""
   n_genes = len(gene_list)
   gene_to_idx = {gene: i for i, gene in enumerate(gene_list)}
   raw_matrix = np.zeros((n_genes, n_genes))
   
   # Determine which pairs to compute
   if gene_pairs is None:
       pairs_to_compute = [(i, j) for i in range(n_genes) for j in range(n_genes)]
   else:
       pairs_to_compute = []
       for gene_1, gene_2 in gene_pairs:
           if gene_1 in gene_to_idx and gene_2 in gene_to_idx:
               i, j = gene_to_idx[gene_1], gene_to_idx[gene_2]
               pairs_to_compute.append((i, j))
   
   # Compute correlations
   for i, j in pairs_to_compute:
       corr = spearmanr(gene_matrix_1[i, :], gene_matrix_2[j, :]).correlation
       raw_matrix[i, j] = corr
   
   return pd.DataFrame(raw_matrix, index=gene_list, columns=gene_list)

def single_cell_shuffle(gene_matrix_1, gene_matrix_2, gene_list, shuffle_pairs, seed=101010):
            """
            One shuffle of the correlation-permutation null: randomly permutes the
            cell order of gene_matrix_2 and recomputes the gene-pair correlation
            matrix against the unshuffled gene_matrix_1.

            Parameters
            ----------
            gene_matrix_1, gene_matrix_2 : np.ndarray
                Shape (n_genes, n_cells); gene_matrix_2's columns (cells) are shuffled.
            gene_list : list of str
                Gene names, in row order matching the matrices.
            shuffle_pairs : list of tuple
                Gene-index pairs to compute correlations for.
            seed : int, default=101010
                Random seed for the cell permutation.

            Returns
            -------
            pd.DataFrame
                Gene x gene correlation matrix for this one shuffle.
            """
            rng = np.random.default_rng(seed)
            n_cells = gene_matrix_1.shape[1]
            shuffled_indices = rng.permutation(n_cells)
            return compute_correlation_matrix(gene_matrix_1, gene_matrix_2[:, shuffled_indices], gene_list, shuffle_pairs)


def _assert_no_nan(gene_matrix, caller_name):
    """
    Raise a clear error if gene_matrix contains NaN, rather than silently computing a wrong
    (not NaN) correlation. scipy.stats.spearmanr degrades gracefully to NaN in the presence of
    NaN inputs; the rank-precompute kernels below do not get this for free, since ranking a
    column that contains NaN does not reliably propagate to a clean NaN downstream.
    """
    if np.isnan(gene_matrix).any():
        raise ValueError(
            f"NaN values found in the gene expression data passed to {caller_name}. "
            "Remove or impute missing values (e.g. via .dropna()) before calling this function."
        )


def _spawn_independent_seeds(seed, n_shuffles):
    """
    Generate n_shuffles seeds for independent parallel shuffles using
    np.random.SeedSequence.spawn -- the numpy-recommended mechanism for statistically
    independent parallel streams. Drawing n_shuffles plain integers from a single
    generator instead has a small but real collision chance (empirically ~2% for
    n_shuffles=10000 drawn from a 2**31 range) that would silently duplicate a null sample;
    SeedSequence.spawn is specifically designed to avoid this.
    """
    children = np.random.SeedSequence(seed).spawn(n_shuffles)
    return np.array([int(c.generate_state(1)[0]) for c in children], dtype=np.int64)


def _rank_center_and_sumsq(gene_matrix):
    """
    Rank each gene's row (axis=1, across cells) with average-tie ranking, center by the constant
    (n_cells+1)/2 -- exact regardless of ties, since average-tie ranks always sum to the same
    total -- and return the per-gene sum of squared centered ranks (the correlation denominator
    is built from this). gene_matrix shape: (n_genes, n_cells).
    """
    n_cells = gene_matrix.shape[1]
    R = rankdata(gene_matrix, axis=1)
    Rc = R - (n_cells + 1) / 2.0
    s2 = np.sum(Rc ** 2, axis=1)
    return Rc, s2


@numba.njit(cache=True)
def _rankdata_numba(a):
    """Average-tie rank of a 1D array; matches scipy.stats.rankdata(method='average') exactly."""
    n = a.size
    order = np.argsort(a)
    ranks = np.empty(n, dtype=np.float64)
    i = 0
    while i < n:
        start = i
        val = a[order[i]]
        while i + 1 < n and a[order[i + 1]] == val:
            i += 1
        end = i
        avg_rank = 0.5 * (start + end) + 1
        for k in range(start, end + 1):
            ranks[order[k]] = avg_rank
        i += 1
    return ranks


@numba.njit(parallel=True, fastmath=True)
def _rank_permutation_null_kernel(Rc1, Rc2, denom, seeds, pair_i, pair_j):
    """
    Null distribution of Spearman correlations where Rc1 (n_genes1 x n_cells) is fixed and
    Rc2 (n_genes2 x n_cells) has its cell-columns permuted each shuffle. Exact under ties,
    because ranks are computed once upstream (in _rank_center_and_sumsq) -- permuting a
    rank vector's columns and then correlating is identical to ranking a permuted array,
    for average-tie ranking. Pass Rc2=Rc1 and a symmetric denom for the undirected
    gene-gene case (check_gene_gene_correlation_threshold); pass distinct matrices for the
    directed cross-time case (identify_actual_directed_edges).
    """
    n_cells = Rc1.shape[1]
    n_shuffles = seeds.shape[0]
    n_twins = pair_i.shape[0]
    out = np.empty((n_shuffles, n_twins), dtype=np.float64)
    for s in numba.prange(n_shuffles):
        np.random.seed(seeds[s])
        idx = np.random.permutation(n_cells)
        Rc2_perm = Rc2[:, idx]
        N = Rc1 @ Rc2_perm.T
        for k in range(n_twins):
            i = pair_i[k]
            j = pair_j[k]
            d = denom[i, j]
            if d > 0:
                out[s, k] = N[i, j] / d
            else:
                out[s, k] = np.nan
    return out


@numba.njit(parallel=True, fastmath=True)
def _two_permutation_diff_null_kernel(expr, seeds, triu_i, triu_j):
    """
    Random-twin difference-correlation null. Replicates generate_random_shuffle's original
    algorithm exactly (two independent permutations per shuffle, self-match pairs filtered
    via idx_1 != idx_2), just executed inside a numba-parallel loop instead of a Python loop
    with np.apply_along_axis(rankdata, ...). Unlike _rank_permutation_null_kernel, the values
    here genuinely change every shuffle (they are differences of permuted cells), so ranking
    must be redone each shuffle -- there is no precompute-once shortcut for this piece.
    expr: (n_cells, n_genes).
    """
    n_cells, n_genes = expr.shape
    n_shuffles = seeds.shape[0]
    n_twins = triu_i.shape[0]
    out = np.full((n_shuffles, n_twins), np.nan, dtype=np.float64)

    for s in numba.prange(n_shuffles):
        np.random.seed(seeds[s])
        idx_1 = np.random.permutation(n_cells)
        idx_2 = np.random.permutation(n_cells)

        n_used = 0
        keep = np.empty(n_cells, dtype=np.int64)
        for k in range(n_cells):
            if idx_1[k] != idx_2[k]:
                keep[n_used] = k
                n_used += 1

        if n_used < 3:
            raise ValueError("Could not create random references of cells to generate null distribution.")
            continue

        deltas = np.empty((n_used, n_genes), dtype=np.float64)
        for k in range(n_used):
            kk = keep[k]
            a_idx = idx_1[kk]
            b_idx = idx_2[kk]
            for g in range(n_genes):
                deltas[k, g] = expr[a_idx, g] - expr[b_idx, g]

        R = np.empty((n_used, n_genes), dtype=np.float64)
        for g in range(n_genes):
            R[:, g] = _rankdata_numba(deltas[:, g])

        m = (n_used + 1) / 2.0
        Rc = R - m
        s2 = np.empty(n_genes, dtype=np.float64)
        for g in range(n_genes):
            acc = 0.0
            for k in range(n_used):
                acc += Rc[k, g] * Rc[k, g]
            s2[g] = acc

        for p_idx in range(n_twins):
            i = triu_i[p_idx]
            j = triu_j[p_idx]
            num = 0.0
            for k in range(n_used):
                num += Rc[k, i] * Rc[k, j]
            d = np.sqrt(s2[i] * s2[j])
            if d > 0:
                out[s, p_idx] = num / d
    return out


@numba.njit(parallel=True, fastmath=True)
def _half_split_diff_null_kernel(expr, clone_codes, seeds, triu_i, triu_j, n_twins_target):
    """
    Random-twin difference-correlation null sized to n_twins_target (the true twin-pair
    count, passed in by the caller), not the ~2N pairs _two_permutation_diff_null_kernel
    draws via two independent permutations of the full pool. Each shuffle draws a SINGLE
    permutation and splits it into two parts of size n_twins_target, pairing them
    positionally -- every cell used is used at most once per part, so there's no
    near-self-match to filter, and no assumption about which two labels distinguish the
    twins (unlike splitting by a 'replicate' column). Positions where the split happens to
    pair a cell with its own twin (same clone_codes value) are dropped instead, since that
    would leak the real twin correlation into the "random" null.
    """
    n_cells, n_genes = expr.shape
    if n_twins_target > n_cells:
        raise ValueError("n_twins_target cannot exceed the number of cells in expr")
    half = n_twins_target
    # Tolerance for how many of the `half` drawn positions may be dropped as
    # same-twin clashes before a shuffle is discarded as unrepresentative.
    # 2% matches the original literal band (1470-1500) at half=1500 exactly;
    # generalized here so the kernel isn't silently all-NaN for any half != 1500
    # (e.g. this dataset's half=6000, where the old fixed band rejected every draw).
    tol = max(1, int(0.02 * half))
    n_shuffles = seeds.shape[0]
    n_twins = triu_i.shape[0]
    out = np.full((n_shuffles, n_twins), np.nan, dtype=np.float64)

    for s in numba.prange(n_shuffles):
        np.random.seed(seeds[s])
        # Draw two independent random parts from the full cell pool.
        # Each part contains unique cells internally, but the two parts may overlap.
        perm_a = np.random.permutation(n_cells)
        perm_b = np.random.permutation(n_cells)
        idx_a = perm_a[:half]
        idx_b = perm_b[:half]

        n_used = 0
        keep = np.empty(half, dtype=np.int64)
        for k in range(half):
            a_idx = idx_a[k]
            b_idx = idx_b[k]
            #if clone_codes[idx_a[k]] != clone_codes[idx_b[k]]:
            if a_idx != b_idx and clone_codes[a_idx] != clone_codes[b_idx]:
                keep[n_used] = k
                n_used += 1

        if n_used < half - tol or n_used > half:
            continue

        deltas = np.empty((n_used, n_genes), dtype=np.float64)
        for k in range(n_used):
            kk = keep[k]
            a_idx = idx_a[kk]
            b_idx = idx_b[kk]
            for g in range(n_genes):
                deltas[k, g] = expr[a_idx, g] - expr[b_idx, g]

        R = np.empty((n_used, n_genes), dtype=np.float64)
        for g in range(n_genes):
            R[:, g] = _rankdata_numba(deltas[:, g])

        m = (n_used + 1) / 2.0
        Rc = R - m
        s2 = np.empty(n_genes, dtype=np.float64)
        for g in range(n_genes):
            acc = 0.0
            for k in range(n_used):
                acc += Rc[k, g] * Rc[k, g]
            s2[g] = acc

        for p_idx in range(n_twins):
            i = triu_i[p_idx]
            j = triu_j[p_idx]
            num = 0.0
            for k in range(n_used):
                num += Rc[k, i] * Rc[k, j]
            d = np.sqrt(s2[i] * s2[j])
            if d > 0:
                out[s, p_idx] = num / d
    return out

