def _cell_permutation_spearman_null(
    values,
    n_shuffles,
    random_state,
    pair_i,
    pair_j,
):
    """
    Ordinary cell-level Spearman permutation null.

    One target-row permutation is shared across all genes within a draw, so
    each permuted target remains a coherent multigene cell. Fixed ranks are
    cached once; the draw loop performs no argsort. The permutation gather is
    done along the contiguous row dimension of a G x N rank matrix.
    """
    values = np.asarray(values, dtype=float)
    pair_i = np.asarray(pair_i, dtype=int)
    pair_j = np.asarray(pair_j, dtype=int)

    if values.ndim != 2:
        raise ValueError("values must be a 2-D cell x gene matrix")
    if not np.isfinite(values).all():
        raise ValueError("Step-1 permutation null does not accept NaN/Inf")
    if int(n_shuffles) < 2:
        raise ValueError("n_shuffles must be at least 2")

    n_rows = values.shape[0]
    if n_rows < 2:
        raise ValueError("Need at least 2 cells for a Step-1 permutation null")

    weights = np.ones(n_rows, dtype=float)
    rank_cache = _prepare_delta_rank_permutation_cache(values, weights)
    cx_T = np.ascontiguousarray(rank_cache["cx"].T)
    sx = rank_cache["sx"]

    out = np.full(
        (int(n_shuffles), len(pair_i)),
        np.nan,
        dtype=float,
    )
    rng = np.random.default_rng(random_state)

    den = sx[pair_i] * sx[pair_j]
    valid = den > 0

    for b in range(int(n_shuffles)):
        perm = rng.permutation(n_rows)
        # G x N column gather is contiguous in the source layout.
        cy_T = cx_T[:, perm]
        numer_matrix = cx_T @ cy_T.T
        out[b, valid] = (
            numer_matrix[pair_i[valid], pair_j[valid]]
            / den[valid]
        )

    return out



def generate_step1_permutation_null(
    measurements,
    gene_list,
    gene_pairs=None,
    use_clone=True,
    n_shuffles=10000,
    random_state=101010,
):
    """
    Generate raw Step-1 permutation-null draws for selected gene pairs.

    This helper exists for TwinScore, whose definition requires every
    component to first be expressed in units of its own permutation null.

    Returns
    -------
    dict
        {sorted_gene_pair: ndarray[n_shuffles]}.
    """
    if not isinstance(use_clone, (bool, np.bool_)):
        raise ValueError("use_clone must be True or False")

    gene_list = list(gene_list)

    if gene_pairs is None:
        requested_pairs = list(combinations(gene_list, 2))
    else:
        requested_pairs = []
        seen = set()
        for a, b in gene_pairs:
            if a == b:
                continue
            if a not in gene_list or b not in gene_list:
                raise ValueError(f"Unknown Step-1 gene pair: {(a, b)}")
            key = tuple(sorted((a, b)))
            if key not in seen:
                seen.add(key)
                requested_pairs.append(key)

    if not requested_pairs:
        return {}

    active = [
        gene
        for gene in gene_list
        if any(gene in pair for pair in requested_pairs)
    ]
    gene_cols = [f"{gene}_mRNA" for gene in active]
    missing = [c for c in gene_cols if c not in measurements.columns]
    if missing:
        raise ValueError(f"Could not find gene column(s): {missing}")

    values = measurements[gene_cols].to_numpy(dtype=float)
    gene_to_idx = {gene: i for i, gene in enumerate(active)}
    pair_i = np.asarray(
        [gene_to_idx[a] for a, _ in requested_pairs],
        dtype=int,
    )
    pair_j = np.asarray(
        [gene_to_idx[b] for _, b in requested_pairs],
        dtype=int,
    )

    if use_clone:
        if "clone_id" not in measurements.columns:
            raise ValueError("use_clone=True requires a 'clone_id' column")
        null_matrix = _clone_block_sampled_spearman_null(
            values,
            measurements["clone_id"].to_numpy(),
            n_shuffles=int(n_shuffles),
            random_state=random_state,
            pair_i=pair_i,
            pair_j=pair_j,
        )
    else:
        null_matrix = _cell_permutation_spearman_null(
            values,
            n_shuffles=int(n_shuffles),
            random_state=random_state,
            pair_i=pair_i,
            pair_j=pair_j,
        )

    return {
        pair: null_matrix[:, k]
        for k, pair in enumerate(requested_pairs)
    }


def _rho_change_time_shuffle_chunk(
    values,
    clone_codes,
    n_clones,
    n_t1,
    pair_i,
    pair_j,
    draw_seeds,
    use_clone,
):
    """Compute one ordered chunk of cell-level time-label null draws."""
    values = np.asarray(values, dtype=float)
    clone_codes = np.asarray(clone_codes, dtype=int)
    draw_seeds = np.asarray(draw_seeds, dtype=np.int64)

    n_total = values.shape[0]
    out = np.full(
        (len(draw_seeds), len(pair_i)),
        np.nan,
        dtype=float,
    )

    for b, draw_seed in enumerate(draw_seeds):
        rng = np.random.default_rng(int(draw_seed))
        permuted_rows = rng.permutation(n_total)
        pseudo_t1 = permuted_rows[:n_t1]
        pseudo_t2 = permuted_rows[n_t1:]

        correlations = []
        for row_idx in (pseudo_t1, pseudo_t2):
            group_values = values[row_idx, :]

            if use_clone:
                group_clone_codes = clone_codes[row_idx]
                group_clone_counts = np.bincount(
                    group_clone_codes,
                    minlength=n_clones,
                ).astype(float)
                # Recompute weights inside this pseudo-time group: each clone
                # represented in the group has total weight exactly 1.
                weights = (
                    1.0 / group_clone_counts[group_clone_codes]
                )
            else:
                weights = np.ones(len(row_idx), dtype=float)

            order_gn = np.argsort(
                group_values,
                axis=0,
                kind="stable",
            ).T
            correlations.append(
                _dynamic_weighted_spearman_pairs_from_order(
                    group_values,
                    order_gn,
                    weights,
                    pair_i,
                    pair_j,
                )
            )

        out[b, :] = correlations[1] - correlations[0]

    return out


def generate_rho_change_time_shuffle_null(
    measurements_t1,
    measurements_t2,
    gene_list,
    gene_pairs=None,
    use_clone=True,
    n_shuffles=10000,
    random_state=101010,
    n_cores_to_use=1,
):
    """
    Generate the time-label permutation null for change in ordinary rho.

    The complete raw-cell rows from t1 and t2 are pooled. Each draw randomly
    reassigns exactly n_t1 rows to pseudo-t1 and the remaining n_t2 rows to
    pseudo-t2, so every gene value and clone_id stays attached to its cell.
    The returned draw is rho_pseudo(t2) - rho_pseudo(t1).

    Returns
    -------
    dict
        {sorted_gene_pair: ndarray[n_shuffles]} containing signed Delta-rho
        draws. The absolute-change Z-score must take abs of these same draws.
    """
    if not isinstance(use_clone, (bool, np.bool_)):
        raise ValueError("use_clone must be True or False")
    if not isinstance(measurements_t1, pd.DataFrame):
        raise TypeError("measurements_t1 must be a pandas DataFrame")
    if not isinstance(measurements_t2, pd.DataFrame):
        raise TypeError("measurements_t2 must be a pandas DataFrame")
    if int(n_shuffles) < 2:
        raise ValueError("n_shuffles must be at least 2")
    n_cores_to_use = max(1, int(n_cores_to_use))
    if len(measurements_t1) < 2 or len(measurements_t2) < 2:
        raise ValueError(
            "Need at least 2 raw cells at both t1 and t2 for the "
            "rho-change null"
        )

    active_genes, requested_pairs = _requested_gene_subset(
        gene_list,
        gene_pairs,
    )
    if not requested_pairs:
        return {}

    gene_cols = [f"{gene}_mRNA" for gene in active_genes]
    for name, frame in (
        ("measurements_t1", measurements_t1),
        ("measurements_t2", measurements_t2),
    ):
        missing = [column for column in gene_cols if column not in frame.columns]
        if missing:
            raise ValueError(f"{name} is missing gene column(s): {missing}")
        if use_clone and "clone_id" not in frame.columns:
            raise ValueError(
                f"use_clone=True requires a 'clone_id' column in {name}"
            )

    pooled_values = np.vstack([
        measurements_t1[gene_cols].to_numpy(dtype=float),
        measurements_t2[gene_cols].to_numpy(dtype=float),
    ])
    if not np.isfinite(pooled_values).all():
        raise ValueError("rho-change null does not accept NaN/Inf gene values")

    gene_to_idx = {
        gene: i for i, gene in enumerate(active_genes)
    }
    pair_i = np.asarray(
        [gene_to_idx[a] for a, _ in requested_pairs],
        dtype=int,
    )
    pair_j = np.asarray(
        [gene_to_idx[b] for _, b in requested_pairs],
        dtype=int,
    )

    if use_clone:
        pooled_clone_ids = np.concatenate([
            measurements_t1["clone_id"].to_numpy(),
            measurements_t2["clone_id"].to_numpy(),
        ])
        clone_codes, clone_labels = pd.factorize(
            pooled_clone_ids,
            sort=False,
        )
        if np.any(clone_codes < 0):
            raise ValueError("clone_id contains missing values")
        n_clones = len(clone_labels)
    else:
        clone_codes = np.zeros(len(pooled_values), dtype=int)
        n_clones = 1

    # ---------------------------------------------------------------------
    # Official name: Change in gene-expression correlation across time
    # LaTeX: \Delta\rho = \rho(t_2) - \rho(t_1)
    # Z-scores: z_rho_change and z_abs_rho_change
    # Permutation method: pool the complete raw-cell rows from t1 and t2, then
    # shuffle only their time labels while preserving the observed n_t1 and
    # n_t2. Recompute both correlations and subtract pseudo-t1 from pseudo-t2.
    # Twin mode (use_clone=False): every raw-cell row has weight 1, so ordinary
    # unweighted Spearman rho is recomputed within each pseudo-time group.
    # Clone mode (use_clone=True): keep each cell's clone_id attached to its
    # complete expression row and recompute within-group weights so every clone
    # represented in that pseudo-time group has total weight 1.
    # The signed Z-score uses the returned draws directly; the absolute Z-score
    # takes abs of the observed value and these same draws. No twin-expanded
    # rows and no Step-1 gene-scramble draws are used for this change null.
    master_rng = np.random.default_rng(random_state)
    draw_seeds = master_rng.integers(
        0,
        np.iinfo(np.int64).max,
        size=int(n_shuffles),
        dtype=np.int64,
    )

    n_jobs = min(n_cores_to_use, int(n_shuffles))
    if n_jobs == 1:
        null_matrix = _rho_change_time_shuffle_chunk(
            pooled_values,
            clone_codes,
            n_clones,
            len(measurements_t1),
            pair_i,
            pair_j,
            draw_seeds,
            use_clone,
        )
    else:
        # Run one draw before starting worker threads so the dynamic weighted-
        # rank kernel is compiled once, rather than concurrently by workers.
        first_result = _rho_change_time_shuffle_chunk(
            pooled_values,
            clone_codes,
            n_clones,
            len(measurements_t1),
            pair_i,
            pair_j,
            draw_seeds[:1],
            use_clone,
        )
        chunks = [
            chunk
            for chunk in np.array_split(
                draw_seeds[1:],
                min(n_jobs, len(draw_seeds) - 1),
            )
            if len(chunk)
        ]
        with threadpool_limits(limits=1, user_api="blas"):
            chunk_results = Parallel(
                n_jobs=n_jobs,
                prefer="threads",
                require="sharedmem",
            )(
                delayed(_rho_change_time_shuffle_chunk)(
                    pooled_values,
                    clone_codes,
                    n_clones,
                    len(measurements_t1),
                    pair_i,
                    pair_j,
                    chunk,
                    use_clone,
                )
                for chunk in chunks
            )
        null_matrix = np.vstack([first_result, *chunk_results])

    return {
        pair: null_matrix[:, k]
        for k, pair in enumerate(requested_pairs)
    }


def calculate_signed_rho_change_z(
    rho_t1,
    rho_t2,
    rho_change_null,
    use_clone=True,
):
    """
    Calculate the signed change in gene-expression correlation across time.

    Observed:
        delta_rho = rho(t2) - rho(t1)

    Null:
        delta_rho_null[b]
            = rho_pseudo(t2)[b] - rho_pseudo(t1)[b]

    Z-score:
        z_rho_change
            = (delta_rho - mean(delta_rho_null))
              / SD(delta_rho_null)

    No absolute value is taken, so positive values indicate an increase in
    signed correlation and negative values indicate a decrease relative to
    the cell-level time-label permutation null.

    Ordinary rho(t) is always calculated from raw cells; twin-expanded rows
    are not used here. rho_change_null must come from
    generate_rho_change_time_shuffle_null under the same use_clone setting.
    """
    if not isinstance(use_clone, (bool, np.bool_)):
        raise ValueError("use_clone must be True or False")

    # ---------------------------------------------------------------------
    # Official name: Signed change in gene-expression correlation
    # LaTeX: \Delta\rho = \rho(t_2) - \rho(t_1)
    # Z-score: z_rho_change
    # Permutation method: pool the complete raw-cell rows from t1 and t2 and
    # shuffle only their time labels, preserving n_t1 and n_t2 exactly. For
    # each draw, recompute rho in both pseudo-time groups and retain signed
    # rho_pseudo(t2)-rho_pseudo(t1).
    # Twin mode (use_clone=False): give every raw-cell row weight 1 and
    # recompute ordinary unweighted Spearman rho in each pseudo-time group.
    # Clone mode (use_clone=True): keep clone_id attached to each complete cell
    # row and recompute the weights within each pseudo-time group so every
    # represented clone has total weight 1.
    # (same time-label null as z(|rho(t2)-rho(t1)|), without abs)
    rho_t1 = float(rho_t1)
    rho_t2 = float(rho_t2)
    null_change = np.asarray(rho_change_null, dtype=float)

    if null_change.ndim != 1:
        raise ValueError("rho_change_null must be one-dimensional")

    null_change = null_change[np.isfinite(null_change)]
    if len(null_change) < 2:
        return {
            "rho_t1": rho_t1,
            "rho_t2": rho_t2,
            "rho_change": float(rho_t2 - rho_t1),
            "null_mean": np.nan,
            "null_std": np.nan,
            "z_rho_change": np.nan,
            "n_null": int(len(null_change)),
            "use_clone": bool(use_clone),
            "null_type": (
                "clone_weighted_cell_time_label_permutation_t2_minus_t1"
                if use_clone
                else "unweighted_cell_time_label_permutation_t2_minus_t1"
            ),
        }

    rho_change = float(rho_t2 - rho_t1)

    if null_change.size < 2:
        null_mean = np.nan
        null_std = np.nan
        z_rho_change = np.nan
    else:
        null_mean = float(np.mean(null_change))
        null_std = float(np.std(null_change, ddof=1))
        z_rho_change = (
            float((rho_change - null_mean) / null_std)
            if np.isfinite(rho_change) and null_std > 0
            else np.nan
        )

    return {
        "rho_t1": rho_t1,
        "rho_t2": rho_t2,
        "rho_change": rho_change,
        "null_mean": null_mean,
        "null_std": null_std,
        "z_rho_change": z_rho_change,
        "n_null": int(null_change.size),
        "use_clone": bool(use_clone),
        "null_type": (
            "clone_weighted_cell_time_label_permutation_t2_minus_t1"
            if use_clone
            else "unweighted_cell_time_label_permutation_t2_minus_t1"
        ),
    }


def check_gene_gene_correlation_threshold(
    measurements,
    pairwise_gene_gene_correlation_matrix,
    gene_list,
    threshold=0.04,
    use_scramble=True,
    z_score_threshold=2.5,
    verbose=False,
    n_cores_to_use=4,
    base_seed=101010,
    use_clone=True,
    n_shuffles=10000,
    return_null_matrix=False,
):
    """
    Step I gene-gene existence test.

    use_clone=False
        Ordinary cell-level analytic Spearman null:

            E[rho] = 0
            SD(rho) = 1 / sqrt(N_cells - 1).

    use_clone=True
        Clone-weighted rho point estimate plus a clone-aware random-matching
        null.

    `use_clone` controls Step 1 only and is independent of `unit`.

        For every shuffle, biological clones are deranged. If source clone c
        is matched to target clone d, each source cell in c receives ONE target
        cell drawn uniformly from d. Target-cell draws are with replacement,
        so unequal clone sizes are allowed.

        Each source cell keeps weight 1/n_c, so clone c still contributes total
        weight 1. The null therefore has exactly N rows and retains the
        within-clone random-matching variance instead of averaging over all
        n_c*n_d Cartesian pairings.

        For each gene pair:

            Z_rho = (rho_observed - mean(rho_null)) / SD(rho_null).

    When use_scramble=False, the fixed effect-size rule abs(rho) > abs(threshold)
    is retained.
    """
    del n_cores_to_use

    if not isinstance(use_clone, (bool, np.bool_)):
        raise ValueError("use_clone must be True or False")

    gene_cols = [f"{gene}_mRNA" for gene in gene_list]
    missing = [c for c in gene_cols if c not in measurements.columns]
    if missing:
        raise ValueError(f"Could not find gene column(s): {missing}")

    if "cell_id" in measurements.columns:
        duplicated = measurements["cell_id"].duplicated(keep=False)
        if duplicated.any():
            example = measurements.loc[duplicated, "cell_id"].iloc[0]
            raise ValueError(
                "Step I requires the raw one-row-per-cell table; "
                f"cell_id={example!r} appears more than once."
            )

    gene_matrix = measurements[gene_cols].to_numpy(dtype=float)
    if not np.isfinite(gene_matrix).all():
        raise ValueError("NaN/Inf values found in Step I gene expression data")

    all_pairs = list(combinations(gene_list, 2))
    gene_to_idx = {gene: i for i, gene in enumerate(gene_list)}
    pair_correlations = {
        (gi, gj): float(pairwise_gene_gene_correlation_matrix.loc[gi, gj])
        for gi, gj in all_pairs
    }

    no_regulation = []
    potential_regulation = []
    null_stats = {}
    z_score_calc = {}
    null_matrix = None

    if use_scramble and use_clone:
        if "clone_id" not in measurements.columns:
            raise ValueError("use_clone=True requires a 'clone_id' column")

        n_clones = int(measurements["clone_id"].nunique())
        if n_clones < 2:
            raise ValueError(
                f"Need at least 2 biological clones for clone-aware Step I; got {n_clones}"
            )

        pair_i = np.asarray([gene_to_idx[gi] for gi, _ in all_pairs], dtype=int)
        pair_j = np.asarray([gene_to_idx[gj] for _, gj in all_pairs], dtype=int)

        null_matrix = _clone_block_sampled_spearman_null(
            gene_matrix,
            measurements["clone_id"].to_numpy(),
            n_shuffles=int(n_shuffles),
            random_state=base_seed,
            pair_i=pair_i,
            pair_j=pair_j,
        )

        for gene_pair_idx, (gi, gj) in enumerate(all_pairs):
            rho = pair_correlations[(gi, gj)]
            finite = null_matrix[:, gene_pair_idx]
            finite = finite[np.isfinite(finite)]

            if finite.size < 2:
                null_mean = np.nan
                null_std = np.nan
                z_score = np.nan
                is_significant = False
            else:
                null_mean = float(np.mean(finite))
                null_std = float(np.std(finite, ddof=1))
                # Gene co-expression at time t (TwINFER Stage I)
                # LaTeX: \rho(t)
                # Permutation method: keep gene X and the source-cell weights fixed,
                # randomly derange the biological clones, and for each source cell
                # sample one cell from its assigned different clone to supply gene Y.
                # Recompute the clone-weighted Spearman \rho(t) for every shuffle; the
                # Z-score compares the observed \rho(t) with that shuffled distribution.
                z_score = (
                    float((rho - null_mean) / null_std)
                    if np.isfinite(rho) and null_std > 0
                    else np.nan
                )
                is_significant = bool(
                    np.isfinite(z_score)
                    and abs(z_score) > abs(z_score_threshold)
                )

            null_stats[(gi, gj)] = (null_mean, null_std)
            z_score_calc[(gi, gj)] = z_score

            if is_significant:
                potential_regulation.append((gi, gj))
            else:
                no_regulation.append((gi, gj))

            if verbose:
                print(
                    f"Step I {gi}-{gj}: clone-weighted rho={rho:.6f}, "
                    f"clone-sampled null mean={null_mean:.6f}, "
                    f"null SD={null_std:.6f}, z={z_score:.4f}, "
                    f"N_clones={n_clones}, n_shuffles={int(n_shuffles)}, "
                    f"use_clone=True, |z|>{abs(z_score_threshold):.4f}: "
                    f"{is_significant}"
                )

    elif use_scramble:
        n_units = int(len(measurements))
        if n_units <= 1:
            raise ValueError(
                f"Need at least 2 cells for analytic Step I; got N={n_units}"
            )

        null_mean = 0.0
        null_std = float(1.0 / np.sqrt(n_units - 1.0))

        for gi, gj in all_pairs:
            rho = pair_correlations[(gi, gj)]
            # Gene co-expression at time t (TwINFER Stage I)
            # LaTeX: \rho(t)
            # Null method (no permutation here): for N unweighted cells, use the
            # analytic no-correlation reference with mean 0 and SD 1/sqrt(N-1).
            # The Z-score compares the observed \rho(t) with that analytic null.
            z_score = (
                float((rho - null_mean) / null_std)
                if np.isfinite(rho)
                else np.nan
            )
            is_significant = bool(
                np.isfinite(z_score)
                and abs(z_score) > abs(z_score_threshold)
            )

            null_stats[(gi, gj)] = (null_mean, null_std)
            z_score_calc[(gi, gj)] = z_score

            if is_significant:
                potential_regulation.append((gi, gj))
            else:
                no_regulation.append((gi, gj))

            if verbose:
                print(
                    f"Step I {gi}-{gj}: rho={rho:.6f}, z={z_score:.4f}, "
                    f"N_cells={n_units}, analytic_null_sd={null_std:.6f}, "
                    f"use_clone=False, |z|>{abs(z_score_threshold):.4f}: "
                    f"{is_significant}"
                )

    else:
        for gi, gj in all_pairs:
            rho = pair_correlations[(gi, gj)]
            is_significant = bool(
                np.isfinite(rho) and abs(rho) > abs(threshold)
            )
            null_stats[(gi, gj)] = float(threshold)
            z_score_calc[(gi, gj)] = None

            if is_significant:
                potential_regulation.append((gi, gj))
            else:
                no_regulation.append((gi, gj))

            if verbose:
                print(
                    f"Step I {gi}-{gj}: rho={rho:.6f}, "
                    f"|rho|>{abs(threshold):.6f}: {is_significant}"
                )

    base_return = (
        no_regulation,
        potential_regulation,
        null_stats,
        z_score_calc,
    )
    if return_null_matrix:
        return base_return + (null_matrix,)
    return base_return


def calculate_pair_correlation(
    rep_0,
    rep_1,
    gene_list,
    type_comparison="twin",
    unit="clone",
):
    """
    Correlation of within-twin expression differences under twin/clone units.

    The Delta matrix is constructed once for all genes, then all gene-pair
    correlations are obtained from one batched weighted-Spearman matrix.
    """
    unit = _resolve_unit(unit)
    rep_0 = rep_0.reset_index(drop=True)
    rep_1 = rep_1.reset_index(drop=True)

    if len(rep_0) != len(rep_1):
        raise ValueError(
            "rep_0 and rep_1 must have the same number of twin rows"
        )

    if type_comparison == "twin":
        for name, frame in (("rep_0", rep_0), ("rep_1", rep_1)):
            missing = {"twin_id", "clone_id"} - set(frame.columns)
            if missing:
                raise ValueError(
                    f"{name} is missing required columns: {sorted(missing)}"
                )

        rep_0 = rep_0.sort_values("twin_id").reset_index(drop=True)
        rep_1 = rep_1.sort_values("twin_id").reset_index(drop=True)

        if not rep_0["twin_id"].equals(rep_1["twin_id"]):
            raise ValueError(
                "twin_id values in rep_0 and rep_1 do not match"
            )
        if not rep_0["clone_id"].equals(rep_1["clone_id"]):
            raise ValueError(
                "The two rows of each twin_id must have the same clone_id"
            )
    elif type_comparison != "random":
        raise ValueError("type_comparison must be 'twin' or 'random'")

    gene_cols = [f"{gene}_mRNA" for gene in gene_list]
    missing = [
        col for col in gene_cols
        if col not in rep_0.columns or col not in rep_1.columns
    ]
    if missing:
        raise ValueError(
            f"Missing gene-expression column(s): {missing}"
        )

    delta = (
        rep_0[gene_cols].to_numpy(dtype=float)
        - rep_1[gene_cols].to_numpy(dtype=float)
    )
    weights = get_unit_weights(rep_0, unit=unit)
    corr_matrix = _weighted_spearman_matrix(delta, weights)

    return {
        f"{gene_1}-{gene_2}": float(corr_matrix[i, j])
        for i, gene_1 in enumerate(gene_list)
        for j, gene_2 in enumerate(gene_list)
    }


def assign_twin_id(df):
    """
    Build the within-time twin-expanded table from raw cells.

    Each unordered pair of cells inside one biological clone is one twin
    observation and receives twin_id = twin_0, twin_1, ...

    Simulation: each clone contains the two sibling cells, so clone == twin
    and each clone contributes one twin.

    Real data: a clone with n cells contributes C(n, 2) twins.

    The expansion uses positional index arithmetic and one final iloc gather,
    rather than copying two pandas rows for every twin.
    """
    if "clone_id" not in df.columns:
        raise ValueError("assign_twin_id requires a 'clone_id' column")
    if df["clone_id"].isna().any():
        raise ValueError("clone_id contains missing values")

    if "twin_id" in df.columns:
        out = df.copy()
        if out["twin_id"].isna().any():
            raise ValueError("twin_id contains missing values")

        twin_sizes = out.groupby("twin_id", sort=False).size()
        bad_sizes = twin_sizes[twin_sizes != 2]
        if not bad_sizes.empty:
            twin_id = bad_sizes.index[0]
            raise ValueError(
                f"twin_id={twin_id!r} has {int(bad_sizes.iloc[0])} rows; expected 2"
            )

        twin_clone_counts = out.groupby(
            "twin_id", sort=False
        )["clone_id"].nunique()
        bad_clone = twin_clone_counts[twin_clone_counts != 1]
        if not bad_clone.empty:
            twin_id = bad_clone.index[0]
            raise ValueError(
                f"twin_id={twin_id!r} contains cells from multiple clones"
            )

        out["n_twins"] = out.groupby(
            "clone_id"
        )["twin_id"].transform("nunique")
        return out

    clone_codes, clone_labels = pd.factorize(
        df["clone_id"].to_numpy(dtype=object),
        sort=False,
    )
    if np.any(clone_codes < 0):
        raise ValueError("clone_id contains missing values")

    gather_parts = []
    twin_id_parts = []
    n_twins_parts = []
    twin_counter = 0

    for code in range(len(clone_labels)):
        rows = np.flatnonzero(clone_codes == code)
        n = len(rows)
        if n < 2:
            continue

        left_local, right_local = np.triu_indices(n, k=1)
        n_twins = len(left_local)
        left = rows[left_local]
        right = rows[right_local]

        gather = np.empty(2 * n_twins, dtype=np.int64)
        gather[0::2] = left
        gather[1::2] = right
        gather_parts.append(gather)

        ids = np.arange(
            twin_counter,
            twin_counter + n_twins,
            dtype=np.int64,
        )
        twin_id_parts.append(
            np.repeat(
                np.asarray([f"twin_{i}" for i in ids], dtype=object),
                2,
            )
        )
        n_twins_parts.append(
            np.full(2 * n_twins, n_twins, dtype=np.int64)
        )
        twin_counter += n_twins

    if not gather_parts:
        raise ValueError(
            "No clone has at least 2 cells; cannot form within-time twins"
        )

    gather = np.concatenate(gather_parts)
    out = df.iloc[gather].copy().reset_index(drop=True)
    out["twin_id"] = np.concatenate(twin_id_parts)
    out["n_twins"] = np.concatenate(n_twins_parts)
    return out



def split_twins(single_time_cells):
    """
    Return aligned first/second-member frames, one row per twin.

    Vectorized implementation:
      - factorize twin_id once in first-occurrence order;
      - use groupby(...).cumcount() once to label member 0/1;
      - use two masks plus integer group codes to align the two frames.

    This avoids one iloc call per twin.
    """
    twin_table = assign_twin_id(single_time_cells).copy()

    if twin_table.empty:
        raise ValueError("No valid twins found")

    twin_ids = twin_table["twin_id"]
    codes, unique_twins = pd.factorize(
        twin_ids,
        sort=False,
    )

    if np.any(codes < 0):
        raise ValueError("twin_id contains missing values")

    counts = np.bincount(
        codes,
        minlength=len(unique_twins),
    )
    bad = np.flatnonzero(counts != 2)
    if len(bad):
        code = int(bad[0])
        raise ValueError(
            f"twin_id={unique_twins[code]!r} has "
            f"{int(counts[code])} rows; expected exactly 2"
        )

    clone_counts = twin_table.groupby(
        "twin_id",
        sort=False,
    )["clone_id"].nunique().to_numpy()
    bad_clone = np.flatnonzero(clone_counts != 1)
    if len(bad_clone):
        code = int(bad_clone[0])
        raise ValueError(
            f"twin_id={unique_twins[code]!r} contains cells from different clones"
        )

    member_index = twin_table.groupby(
        "twin_id",
        sort=False,
    ).cumcount().to_numpy()

    idx0 = np.flatnonzero(member_index == 0)
    idx1 = np.flatnonzero(member_index == 1)

    # idx0 is already in first-occurrence twin order. idx1 is explicitly
    # reordered by the factorized twin code so both frames align identically
    # even if an already-expanded input interleaves second members.
    order0 = np.argsort(codes[idx0], kind="stable")
    order1 = np.argsort(codes[idx1], kind="stable")

    twin_0 = twin_table.iloc[
        idx0[order0]
    ].reset_index(drop=True)
    twin_1 = twin_table.iloc[
        idx1[order1]
    ].reset_index(drop=True)

    if not twin_0["twin_id"].equals(twin_1["twin_id"]):
        raise AssertionError("internal error: twin_id alignment was lost")
    if not twin_0["clone_id"].equals(twin_1["clone_id"]):
        raise AssertionError("internal error: clone_id differs within a twin")

    return twin_0, twin_1


def calculate_twin_random_correlations(
    raw_cells,
    twin_table,
    gene_list,
    n_random=None,
    random_state=None,
    unit=None,
):
    """
    Return observed twin rho_Delta and one random-pair reference draw.

    Observed rho_Delta uses the actual within-clone twin differences. The
    reference uses freshly sampled random cell pairs from different clones,
    with clone-first then cell-within-clone sampling. It does not permute the
    observed twin Delta rows.

    `n_random` is retained for API compatibility. The random reference uses the
    same number of slots as the observed twin statistic so its weighting/sample
    geometry matches the statistic being displayed.
    """
    del n_random

    unit = _resolve_unit(unit)

    observed_prep = _prepare_observed_delta_rows(
        twin_table,
        gene_list,
        unit=unit,
    )
    twin_corr = _weighted_spearman_matrix(
        observed_prep["delta"],
        observed_prep["weights"],
    )
    twin_corr_matrix = pd.DataFrame(
        twin_corr,
        index=gene_list,
        columns=gene_list,
    )

    random_prep = _prepare_random_twin_null_inputs(
        twin_table,
        raw_cells,
        gene_list,
    )
    random_weights = get_unit_weights(
        random_prep["rep_0"],
        unit=unit,
    )
    rng = np.random.default_rng(random_state)
    idx_a, idx_b, _, _ = _sample_fresh_random_twin_cells(
        random_prep["source_clones"],
        random_prep["raw_clones"],
        rng,
        raw_groups=random_prep["raw_groups"],
        sampling_cache=random_prep["random_pair_sampling_cache"],
    )
    random_delta = (
        random_prep["raw_values"][idx_a]
        - random_prep["raw_values"][idx_b]
    )
    random_corr = _weighted_spearman_matrix(
        random_delta,
        random_weights,
    )
    random_corr_matrix = pd.DataFrame(
        random_corr,
        index=gene_list,
        columns=gene_list,
    )

    return twin_corr_matrix, random_corr_matrix


def differentiate_single_state_reg_and_multiple_states(
    measurements,
    potential_regulation,
    twin_correlation_matrix,
    random_correlation_matrix,
    gene_list,
    z_score_threshold=10,
    verbose=True,
    unit=None,
    n_shuffles=None,
    null_alpha=0.01,
    expected_null_rejections=50,
    minimum_null_draws=2000,
    precomputed_null=None,
    n_cores_to_use=1,
    divergence_random_state=314159,
    precomputed_divergence_null=None,
    return_divergence_details=False,
):
    """
    Separate multiple-state from single-state regulation using the existing
    fresh-random-pair heterogeneity null, and additionally calculate Yuval's
    fixed-Delta divergence score ``z_div``.

    Canonical naming:
      - z_het: the earlier fresh random-pair null that replaces twins with
        unrelated cells. This remains the score used by the existing Step-2
        classification.
      - z_div: Yuval's fixed-Delta shuffle that keeps every measured Delta_X
        and Delta_Y and only breaks their within-twin matching.

    ``z_score_calc`` is retained as a backward-compatible return name for
    z_het. ``z_score_div`` is retained as an alias for z_div in details.

    ``z_div`` is a separate within-time-point diagnostic:
        z_div
            = (rho_Delta_observed - mean(rho_Delta_fixed_Delta_shuffle))
              / SD(rho_Delta_fixed_Delta_shuffle)

    In the fixed-Delta shuffle, every observed Delta_X and Delta_Y value is
    retained exactly, Delta_X stays fixed, and Delta_Y rows are reassigned
    one-to-one across biological clones. No source row can receive Delta_Y
    from its own clone.

    With unit="twin" (legacy "pair"), every twin has weight 1. With
    unit="clone", every biological clone has total weight 1.
    """
    del random_correlation_matrix
    unit = _resolve_unit(unit)

    multiple_states_gene_pairs = []
    single_state_regulation = []
    null_stats = {}
    z_score_calc = {}
    divergence_details = {}

    n_shuffles_used = get_conservative_null_draw_count(
        n_shuffles=n_shuffles,
        alpha=null_alpha,
        expected_rejections=expected_null_rejections,
        minimum=minimum_null_draws,
    )

    if precomputed_null is None:
        pair_table = (
            measurements
            if "twin_id" in measurements.columns
            else assign_twin_id(measurements)
        )
        random_delta_reference_distribution = generate_random_shuffle(
            pair_table,
            gene_list=gene_list,
            gene_pairs=potential_regulation,
            n_shuffles=n_shuffles_used,
            unit=unit,
            raw_cells=measurements,
            n_cores_to_use=n_cores_to_use,
        )
    else:
        random_delta_reference_distribution = {
            key: np.asarray(values)[:n_shuffles_used]
            for key, values in precomputed_null.items()
        }

    pair_table_for_divergence = (
        measurements
        if "twin_id" in measurements.columns
        else assign_twin_id(measurements)
    )
    if precomputed_divergence_null is None:
        divergence_null_distribution = generate_divergence_shuffle(
            pair_table_for_divergence,
            gene_list=gene_list,
            gene_pairs=potential_regulation,
            n_shuffles=n_shuffles_used,
            random_state=divergence_random_state,
            unit=unit,
            n_cores_to_use=n_cores_to_use,
        )
    else:
        divergence_null_distribution = {
            key: np.asarray(values)[:n_shuffles_used]
            for key, values in precomputed_divergence_null.items()
        }

    for gene_i, gene_j in potential_regulation:
        try:
            t_corr = float(twin_correlation_matrix.loc[gene_i, gene_j])
            r_corr = np.asarray(
                get_correlations(random_delta_reference_distribution, gene_i, gene_j),
                dtype=float,
            )
            finite = r_corr[np.isfinite(r_corr)]
            if finite.size == 0:
                raise ValueError(f"No finite random-reference correlations for {gene_i}-{gene_j}")
            r_corr_mean = float(np.mean(finite))
            r_corr_std = float(np.std(finite))
            r_corr_median = float(np.median(finite))

            if r_corr_std == 0:
                print(f"Warning: Zero variance in random correlations for {gene_i}-{gene_j}")
                single_state_regulation.append((gene_i, gene_j))
                null_stats[(gene_i, gene_j)] = (r_corr_mean, 0.0, r_corr_median)
                z_score_calc[(gene_i, gene_j)] = None

                div_corr = np.asarray(
                    get_correlations(
                        divergence_null_distribution,
                        gene_i,
                        gene_j,
                    ),
                    dtype=float,
                )
                div_finite = div_corr[np.isfinite(div_corr)]
                if div_finite.size < 2:
                    div_mean = np.nan
                    div_std = np.nan
                    div_median = np.nan
                    z_div = np.nan
                else:
                    div_mean = float(np.mean(div_finite))
                    div_std = float(np.std(div_finite))
                    div_median = float(np.median(div_finite))
                    # Twin difference correlation at time t -- divergence Z-score
                    # LaTeX: \hat{\rho}_{\Delta}(t)
                    # Permutation method: keep every observed \Delta X and \Delta Y value
                    # unchanged, hold the \Delta X rows fixed, and reassign the complete
                    # \Delta Y rows one-to-one across twin rows, never to a row from the
                    # same biological clone. Every \Delta Y row is used exactly once in
                    # each shuffle; recompute weighted Spearman after re-pairing, and
                    # Z-score the observed \hat{\rho}_{\Delta}(t) against those values.
                    # (same with z_d_div at each time point)
                    z_div = (
                        float((t_corr - div_mean) / div_std)
                        if div_std > 0
                        else np.nan
                    )
                divergence_details[(gene_i, gene_j)] = {
                    "rho_delta_observed": t_corr,
                    "null_mean": div_mean,
                    "null_std": div_std,
                    "null_median": div_median,
                    "z_div": z_div,
                    "z_score_div": z_div,
                    "n_shuffles": int(n_shuffles_used),
                    "unit": unit,
                    "null_type": "fixed_delta_y_cross_clone_permutation",
                }
                continue

            # Twin difference correlation at time t -- heterogeneity Z-score
            # LaTeX: observed twins \hat{\rho}_{\Delta}(t); random-pair
            # reference \rho_{\Delta}(t).
            # Permutation method: for every observed twin slot, draw a fresh unrelated
            # pair by choosing clone A uniformly, choosing a different clone B uniformly,
            # then choosing one cell uniformly from each clone. Use that same random cell
            # pair to form \Delta X and \Delta Y, recompute weighted Spearman across all
            # slots, and repeat to form the random-pair \rho_{\Delta}(t) distribution.
            # The Z-score compares \hat{\rho}_{\Delta}(t) with that distribution; in
            # clone mode, source twin labels affect only the weights (clone total = 1).
            # (same with the fan-out check; same random-pair construction as z_d_het at each time point)
            z_score = float((t_corr - r_corr_mean) / r_corr_std)
            null_stats[(gene_i, gene_j)] = (r_corr_mean, r_corr_std, r_corr_median)
            z_score_calc[(gene_i, gene_j)] = z_score

            div_corr = np.asarray(
                get_correlations(
                    divergence_null_distribution,
                    gene_i,
                    gene_j,
                ),
                dtype=float,
            )
            div_finite = div_corr[np.isfinite(div_corr)]
            if div_finite.size < 2:
                div_mean = np.nan
                div_std = np.nan
                div_median = np.nan
                z_div = np.nan
            else:
                div_mean = float(np.mean(div_finite))
                div_std = float(np.std(div_finite))
                div_median = float(np.median(div_finite))
                # Twin difference correlation at time t -- divergence Z-score
                # LaTeX: \hat{\rho}_{\Delta}(t)
                # Permutation method: keep every observed \Delta X and \Delta Y value
                # unchanged, hold the \Delta X rows fixed, and reassign the complete
                # \Delta Y rows one-to-one across twin rows, never to a row from the
                # same biological clone. Every \Delta Y row is used exactly once in
                # each shuffle; recompute weighted Spearman after re-pairing, and
                # Z-score the observed \hat{\rho}_{\Delta}(t) against those values.
                # (same with z_d_div at each time point)
                z_div = (
                    float((t_corr - div_mean) / div_std)
                    if div_std > 0
                    else np.nan
                )

            divergence_details[(gene_i, gene_j)] = {
                "rho_delta_observed": t_corr,
                "null_mean": div_mean,
                "null_std": div_std,
                "null_median": div_median,
                "z_div": z_div,
                "z_score_div": z_div,
                "n_shuffles": int(n_shuffles_used),
                "unit": unit,
                "null_type": "fixed_delta_y_cross_clone_permutation",
            }

            if verbose:
                plt.hist(finite)
                plt.axvline(
                    t_corr,
                    linestyle="--",
                    c="red",
                    label=r"twin difference correlation $\hat{\rho}_\Delta(t_1)$",
                )
                plt.xlabel(r"random-pair difference correlation $\rho_\Delta(t_1)$")
                plt.ylabel("number of scrambles")
                plt.title(
                    f"Random twin difference correlations vs twin difference correlation\n"
                    f"between {gene_i} and {gene_j}\nz_het = {z_score:.4f}, unit={unit}"
                )
                plt.legend()
                plt.show()

            if abs(z_score) > abs(z_score_threshold):
                multiple_states_gene_pairs.append((gene_i, gene_j))
            else:
                single_state_regulation.append((gene_i, gene_j))
            # 2026-09-29: unconditional per-pair print (not gated by `verbose`) was the
            # dominant wall-clock cost at thousand-pair scale -- ~10k+ print() calls per
            # stage. Commented out, not the math; see identify_actual_directed_edges for
            # the matching fix.
            # print(
            #     f"gene 1: {gene_i}, gene 2: {gene_j}, z_het: {z_score}, "
            #     f"z_div: {z_div} "
            #     f"with threshold {z_score_threshold}, unit={unit}"
            # )
        except KeyError:
            raise ValueError(f"Missing gene pair ({gene_i}, {gene_j}) in correlation matrices.")

    base_return = (
        multiple_states_gene_pairs,
        single_state_regulation,
        null_stats,
        z_score_calc,
    )
    if return_divergence_details:
        return base_return + (divergence_details,)
    return base_return


def calculate_gated_regulation_statistic(
    twin_table,
    gene_i,
    gene_j,
    z_het,
    n_shuffles=5000,
    random_state=None,
    unit=None,
):
    """
    Heterogeneity-gated regulation statistic.

    For twin pair k = 1..n let x^a_k, x^b_k be gene_i counts and y^a_k, y^b_k
    gene_j counts in the two siblings. Define, over the pooled 2n cells:

        rho_same  = Spearman(x, y)        same-cell pairs   (x^a,y^a),(x^b,y^b)
        rho_cross = Spearman(x, y')       cross-sibling pairs (x^a,y^b),(x^b,y^a)

    rho_reg(lambda) = rho_same - lambda * rho_cross,
        lambda = min(1, |z_het| / 2.33)

    At lambda=0 this is gene-gene rho on the pooled 2n twin-member rows. With
    unit="clone" and the complete within-clone twin expansion, this is exactly
    the existing clone-weighted raw-cell rho: each cell in a clone of size m
    appears in m-1 twins and consequently has total effective weight 1/m.

    At lambda=1 this is the pooled-rank same-minus-cross contrast. It is the
    rank-space analogue motivating rho_Delta, but is not generally identical
    to Spearman(x^a-x^b, y^a-y^b), which ranks the n raw differences.

    Null: keep each X sibling block fixed and reassign complete Y sibling
    blocks one-to-one across twins, excluding assignments from the same
    biological clone. The same reassignment is used for rho_same_null and
    rho_cross_null, preserving their covariance before they are combined with
    the observed lambda. Because within-time twins are unordered, the assigned
    Y block is independently flipped with probability 1/2.

    Twin mode gives every enumerated twin weight 1. Clone mode gives every
    biological clone total weight 1: if clone c contributes K_c twins, each
    twin receives weight 1/K_c and each of its two pooled member rows receives
    weight 1/(2 K_c).

    twin_table: post-assign_twin_id table (2 rows per twin_id; simulation ->
    one twin per clone) restricted to the population the caller wants scored
    (e.g. the t1 or t2 twin subset used elsewhere in Step 2).

    z_het must be calculated under the same unit as this statistic.

    Returns a dict containing lambda, rho_reg_gated, rho_gene_gene_2n,
    rho_cross_2n, z_reg_gated, the null summary, and null metadata.
    """
    unit = _resolve_unit(unit)
    n_shuffles = int(n_shuffles)
    if n_shuffles < 2:
        raise ValueError("n_shuffles must be at least 2")

    twin_0, twin_1 = split_twins(twin_table)
    col_i = f"{gene_i}_mRNA" if f"{gene_i}_mRNA" in twin_table.columns else gene_i
    col_j = f"{gene_j}_mRNA" if f"{gene_j}_mRNA" in twin_table.columns else gene_j
    xa = twin_0[col_i].to_numpy(dtype=float)
    xb = twin_1[col_i].to_numpy(dtype=float)
    ya = twin_0[col_j].to_numpy(dtype=float)
    yb = twin_1[col_j].to_numpy(dtype=float)
    n = xa.shape[0]
    if n < 2:
        return {"lambda": None, "rho_reg_gated": None, "rho_gene_gene_2n": None,
                "rho_cross_2n": None, "z_reg_gated": None, "null_mean": None,
                "null_std": None, "n_shuffles": 0, "unit": unit,
                "null_type": "y_sibling_block_cross_clone_permutation"}

    values = np.concatenate([xa, xb, ya, yb])
    if not np.isfinite(values).all():
        raise ValueError(
            "NaN/Inf values found while calculating z_reg_gated"
        )

    # ---------------------------------------------------------------------
    # Official name: Heterogeneity-gated regulation statistic
    # LaTeX:
    # \hat{\rho}_{reg}(\lambda)
    #     = \rho_{same} - \lambda \rho_{cross},
    # \lambda = \min(1, |z_{het}| / 2.33).
    # Z-score: z_reg_gated
    # Twin mode gives every enumerated twin weight 1.
    # Clone mode gives every biological clone total weight 1: if clone c
    # contributes K_c twins, each twin receives weight 1/K_c and each of its
    # two pooled member rows receives weight 1/(2 K_c).
    twin_weights = get_unit_weights(twin_0, unit=unit)
    member_weights = 0.5 * np.concatenate([
        twin_weights,
        twin_weights,
    ])

    x_values = np.concatenate([xa, xb])
    y_same = np.concatenate([ya, yb])

    rank_x = weighted_rank(x_values, member_weights)
    rank_x_mean = float(
        np.sum(member_weights * rank_x)
        / member_weights.sum()
    )
    rank_x_centered = rank_x - rank_x_mean
    rank_x_scale = float(np.sqrt(
        np.sum(
            member_weights
            * rank_x_centered
            * rank_x_centered
        )
    ))
    weighted_rank_x = member_weights * rank_x_centered

    def _rho_from_y_ranks(rank_y):
        """Weighted Pearson correlation of fixed X ranks with supplied Y ranks."""
        rank_y = np.asarray(rank_y, dtype=float)
        rank_y_mean = float(
            np.sum(member_weights * rank_y)
            / member_weights.sum()
        )
        rank_y_centered = rank_y - rank_y_mean
        rank_y_scale = float(np.sqrt(
            np.sum(
                member_weights
                * rank_y_centered
                * rank_y_centered
            )
        ))
        denominator = rank_x_scale * rank_y_scale
        if denominator <= 0:
            return np.nan
        return float(
            np.dot(weighted_rank_x, rank_y_centered)
            / denominator
        )

    # The two positions belonging to one twin have the same member weight.
    # Therefore swapping the two Y members swaps their already-computed
    # weighted ranks without changing either value's weight.
    observed_rank_y = weighted_rank(y_same, member_weights)
    observed_rank_ya = observed_rank_y[:n]
    observed_rank_yb = observed_rank_y[n:]

    obs_same = _rho_from_y_ranks(observed_rank_y)
    obs_cross = _rho_from_y_ranks(np.concatenate([
        observed_rank_yb,
        observed_rank_ya,
    ]))

    lam = min(1.0, abs(z_het) / 2.33) if (z_het is not None and np.isfinite(z_het)) else 0.0
    obs_reg = obs_same - lam * obs_cross

    # ---------------------------------------------------------------------
    # Official name: Heterogeneity-gated regulation null
    # Permutation method: keep every X sibling block fixed and reassign the
    # complete Y sibling blocks (y^a, y^b) one-to-one across twin rows, never
    # to a row from the same biological clone. Randomly flip the two members
    # of each assigned Y block because within-time twin orientation is
    # arbitrary. Use the SAME reassignment and orientation for rho_same_null
    # and rho_cross_null, then calculate
    # rho_reg_null = rho_same_null - lambda * rho_cross_null.
    # Twin mode uses equal weights, so the fixed Y ranks can be re-gathered.
    # Clone mode keeps the source-clone weights fixed and recomputes the exact
    # weighted Y ranks after every reassignment. The cached value ordering
    # avoids a fresh O(n log n) sort in each shuffle.
    # (same cross-clone reassignment principle as the z_div fixed-Delta null)
    rng = np.random.default_rng(random_state)
    clone_ids = twin_0["clone_id"].to_numpy(dtype=object)
    clone_cache = _prepare_cross_clone_integer_cache(clone_ids)

    # Cache the ordering and tie structure of the fixed Y values. In clone
    # mode, only the source weights attached to those values change by draw.
    y_rank_cache = _prepare_delta_rank_permutation_cache(
        y_same[:, None],
        member_weights,
    )

    null_same = np.empty(n_shuffles, dtype=float)
    null_cross = np.empty(n_shuffles, dtype=float)

    original_ya_rows = np.arange(n, dtype=np.int64)
    original_yb_rows = original_ya_rows + n

    for b in range(n_shuffles):
        perm = _cross_clone_permutation_indices(
            clone_ids,
            rng,
            integer_cache=clone_cache,
        )

        # A twin is an unordered sibling relationship in the real-data
        # construction. Random orientation makes the null invariant to which
        # physical cell happened to be stored as member a or member b.
        flip = rng.random(n) < 0.5
        perm_ya_rows = original_ya_rows[perm]
        perm_yb_rows = original_yb_rows[perm]

        same_first = np.where(
            flip,
            perm_yb_rows,
            perm_ya_rows,
        )
        same_second = np.where(
            flip,
            perm_ya_rows,
            perm_yb_rows,
        )
        y_row_permutation = np.concatenate([
            same_first,
            same_second,
        ])

        # Twin mode has equal weights, so a permutation only re-gathers the
        # already-computed Y ranks. Clone mode must recompute exact weighted
        # midranks because the source weights attached to Y values change, but
        # the cached value ordering avoids re-sorting Y.
        if unit == "twin":
            shuffled_rank_y = observed_rank_y[
                y_row_permutation
            ]
        else:
            shuffled_rank_y = _weighted_gather_ranks_from_cache(
                y_rank_cache,
                y_row_permutation,
                member_weights,
            )[:, 0].copy()

        null_same[b] = _rho_from_y_ranks(shuffled_rank_y)
        null_cross[b] = _rho_from_y_ranks(np.concatenate([
            shuffled_rank_y[n:],
            shuffled_rank_y[:n],
        ]))

    null_combo = null_same - lam * null_cross
    finite_null = null_combo[np.isfinite(null_combo)]

    if finite_null.size < 2:
        null_mean = np.nan
        null_std = np.nan
        z_reg_gated = np.nan
    else:
        null_mean = float(np.mean(finite_null))
        null_std = float(np.std(finite_null, ddof=1))
        z_reg_gated = (
            float((obs_reg - null_mean) / null_std)
            if np.isfinite(obs_reg) and null_std > 0
            else np.nan
        )

    return {
        "lambda": lam,
        "rho_reg_gated": obs_reg,
        "rho_gene_gene_2n": obs_same,
        "rho_cross_2n": obs_cross,
        "z_reg_gated": z_reg_gated,
        "null_mean": null_mean,
        "null_std": null_std,
        "n_shuffles": int(n_shuffles),
        "n_finite_null": int(finite_null.size),
        "unit": unit,
        "null_type": "y_sibling_block_cross_clone_permutation",
        "source_clone_excluded": True,
        "y_blocks_used_one_to_one": True,
        "sibling_orientation_randomized": True,
    }


def _prepare_random_twin_null_inputs(pair_table, raw_table, gene_list):
    """
    Prepare observed twin slots/weights plus a de-duplicated raw-cell pool for
    the random-pair rho_Delta reference.

    The observed twin values are retained only to define the number of slots and
    their clone labels for weighting. Null Delta values are built from freshly
    sampled raw cells, not from the observed twin differences.
    """
    gene_cols = [f"{gene}_mRNA" for gene in gene_list]

    rep_0, rep_1 = split_twins(pair_table)
    rep_0 = rep_0.sort_values("twin_id").reset_index(drop=True)
    rep_1 = rep_1.sort_values("twin_id").reset_index(drop=True)

    if not rep_0["twin_id"].equals(rep_1["twin_id"]):
        raise ValueError("twin_id values do not align")
    if not rep_0["clone_id"].equals(rep_1["clone_id"]):
        raise ValueError("clone_id differs within an observed twin")

    x0 = rep_0[gene_cols].to_numpy(dtype=float)
    x1 = rep_1[gene_cols].to_numpy(dtype=float)
    source_clones = rep_0["clone_id"].to_numpy(dtype=object)

    raw_cols = ["clone_id"] + gene_cols
    if "cell_id" in raw_table.columns:
        raw_cols = ["cell_id"] + raw_cols

    raw_pool = raw_table[raw_cols].dropna(
        subset=["clone_id"] + gene_cols
    ).copy()

    if "cell_id" in raw_pool.columns:
        clone_per_cell = raw_pool.groupby(
            "cell_id", sort=False
        )["clone_id"].nunique()
        bad_cells = clone_per_cell[clone_per_cell != 1]
        if not bad_cells.empty:
            raise ValueError(
                f"cell_id={bad_cells.index[0]!r} maps to more than one clone_id"
            )
        raw_pool = raw_pool.drop_duplicates(
            subset="cell_id",
            keep="first",
        )

    raw_values = raw_pool[gene_cols].to_numpy(dtype=float)
    raw_clones = raw_pool["clone_id"].to_numpy(dtype=object)

    if not (
        np.isfinite(x0).all()
        and np.isfinite(x1).all()
        and np.isfinite(raw_values).all()
    ):
        raise ValueError(
            "NaN/Inf values found while preparing the random-pair rho_Delta reference"
        )

    raw_groups = _build_raw_clone_index(raw_clones)
    if len(raw_groups) < 2:
        raise ValueError(
            "Need at least two biological clones in the raw random-pair pool"
        )

    clone_labels = np.asarray(list(raw_groups), dtype=object)
    clone_sizes = np.asarray(
        [len(raw_groups[c]) for c in clone_labels],
        dtype=np.int64,
    )
    max_size = int(np.max(clone_sizes))
    padded_groups = np.full(
        (len(clone_labels), max_size),
        -1,
        dtype=np.int64,
    )
    for code, clone_id in enumerate(clone_labels):
        rows = raw_groups[clone_id]
        padded_groups[code, :len(rows)] = rows

    return {
        "rep_0": rep_0,
        "rep_1": rep_1,
        "x0": x0,
        "x1": x1,
        "source_clones": source_clones,
        "raw_values": raw_values,
        "raw_clones": raw_clones,
        "raw_groups": raw_groups,
        "random_pair_sampling_cache": {
            "clone_labels": clone_labels,
            "clone_sizes": clone_sizes,
            "padded_groups": padded_groups,
            "n_clones": int(len(clone_labels)),
        },
    }


def _sample_fresh_random_twin_cells(
    source_clones,
    raw_clones,
    rng,
    raw_groups=None,
    sampling_cache=None,
):
    """
    Draw one fresh random cell pair for every observed twin slot.

    The source-clone labels determine only how many null slots are needed (and,
    elsewhere, their weights). They do NOT constrain which random clones can be
    sampled.

    For each slot:
      1. choose clone A uniformly from all biological clones;
      2. choose clone B uniformly from all clones except A;
      3. choose one cell uniformly within A;
      4. choose one cell uniformly within B.

    This implements two-step clone-balanced random pairing and guarantees that
    the two random cells come from different biological clones. Both cells are
    freshly sampled; no observed twin member is anchored into the null pair.
    """
    source_clones = np.asarray(source_clones, dtype=object)
    raw_clones = np.asarray(raw_clones, dtype=object)
    n_slots = len(source_clones)

    if raw_groups is None:
        raw_groups = _build_raw_clone_index(raw_clones)

    if sampling_cache is None:
        clone_labels = np.asarray(list(raw_groups), dtype=object)
        clone_sizes = np.asarray(
            [len(raw_groups[c]) for c in clone_labels],
            dtype=np.int64,
        )
        max_size = int(np.max(clone_sizes))
        padded_groups = np.full(
            (len(clone_labels), max_size),
            -1,
            dtype=np.int64,
        )
        for code, clone_id in enumerate(clone_labels):
            rows = raw_groups[clone_id]
            padded_groups[code, :len(rows)] = rows
        sampling_cache = {
            "clone_labels": clone_labels,
            "clone_sizes": clone_sizes,
            "padded_groups": padded_groups,
            "n_clones": int(len(clone_labels)),
        }

    clone_labels = sampling_cache["clone_labels"]
    clone_sizes = sampling_cache["clone_sizes"]
    padded_groups = sampling_cache["padded_groups"]
    n_clones = int(sampling_cache["n_clones"])

    if n_clones < 2:
        raise ValueError(
            "A random rho_Delta pair requires at least two biological clones"
        )

    if n_slots == 0:
        empty_i = np.empty(0, dtype=np.int64)
        empty_o = np.empty(0, dtype=object)
        return empty_i, empty_i.copy(), empty_o, empty_o.copy()

    clone_a_code = rng.integers(
        0,
        n_clones,
        size=n_slots,
        dtype=np.int64,
    )
    clone_b_base = rng.integers(
        0,
        n_clones - 1,
        size=n_slots,
        dtype=np.int64,
    )
    clone_b_code = clone_b_base + (
        clone_b_base >= clone_a_code
    )

    pos_a = (
        rng.random(n_slots) * clone_sizes[clone_a_code]
    ).astype(np.int64)
    pos_b = (
        rng.random(n_slots) * clone_sizes[clone_b_code]
    ).astype(np.int64)

    idx_a = padded_groups[clone_a_code, pos_a]
    idx_b = padded_groups[clone_b_code, pos_b]

    if np.any(idx_a < 0) or np.any(idx_b < 0):
        raise AssertionError(
            "internal error: sampled outside a clone's populated rows"
        )
    if np.any(raw_clones[idx_a] == raw_clones[idx_b]):
        raise AssertionError(
            "internal error: random-pair members came from the same clone"
        )

    return (
        idx_a,
        idx_b,
        clone_labels[clone_a_code],
        clone_labels[clone_b_code],
    )



def _sample_fresh_random_twin_indices(
    sampling_cache,
    rng,
    n_slots,
):
    """
    Fast hot-path version of _sample_fresh_random_twin_cells.

    Returns only raw-cell row indices. Clone labels are not materialized because
    Step 2 and Stage 3 do not use them after sampling.
    """
    clone_sizes = sampling_cache["clone_sizes"]
    padded_groups = sampling_cache["padded_groups"]
    n_clones = int(sampling_cache["n_clones"])

    if n_clones < 2:
        raise ValueError(
            "A random rho_Delta pair requires at least two biological clones"
        )

    n_slots = int(n_slots)
    if n_slots == 0:
        empty = np.empty(0, dtype=np.int64)
        return empty, empty.copy()

    clone_a_code = rng.integers(
        0,
        n_clones,
        size=n_slots,
        dtype=np.int64,
    )
    clone_b_base = rng.integers(
        0,
        n_clones - 1,
        size=n_slots,
        dtype=np.int64,
    )
    clone_b_code = clone_b_base + (
        clone_b_base >= clone_a_code
    )

    pos_a = (
        rng.random(n_slots)
        * clone_sizes[clone_a_code]
    ).astype(np.int64)
    pos_b = (
        rng.random(n_slots)
        * clone_sizes[clone_b_code]
    ).astype(np.int64)

    idx_a = padded_groups[clone_a_code, pos_a]
    idx_b = padded_groups[clone_b_code, pos_b]

    return idx_a, idx_b

def _sample_two_step_targets_from_clone_choices(
    source_clones,
    raw_clones,
    raw_groups,
    rng,
    chosen_target_clones=None,
):
    """
    Draw target cells after target-clone choices have been made.

    If chosen_target_clones is None, target clones are drawn uniformly from
    eligible clones. Otherwise the supplied target-clone sequence is used and
    only the within-clone cell draw is random.
    """
    source_clones = np.asarray(source_clones, dtype=object)
    raw_clones_unique = np.asarray(list(raw_groups), dtype=object)

    if chosen_target_clones is None:
        chosen_target_clones = np.empty(len(source_clones), dtype=object)

        for i, source_clone in enumerate(source_clones):
            candidates = raw_clones_unique[
                raw_clones_unique != source_clone
            ]
            if len(candidates) == 0:
                raise ValueError(
                    f"No target clone outside source clone {source_clone!r}"
                )
            chosen_target_clones[i] = rng.choice(candidates)
    else:
        chosen_target_clones = np.asarray(
            chosen_target_clones, dtype=object
        )
        if len(chosen_target_clones) != len(source_clones):
            raise ValueError(
                "chosen_target_clones must match the number of source slots"
            )

    target_idx = np.empty(len(source_clones), dtype=int)

    for i, (source_clone, target_clone) in enumerate(
        zip(source_clones, chosen_target_clones)
    ):
        if target_clone == source_clone:
            raise ValueError(
                "A random target clone cannot equal the source clone"
            )
        if target_clone not in raw_groups:
            raise ValueError(
                f"Target clone {target_clone!r} is absent from the raw pool"
            )
        target_idx[i] = rng.choice(raw_groups[target_clone])

    if np.any(source_clones == raw_clones[target_idx]):
        raise AssertionError(
            "internal error: sampled a same-clone random target"
        )

    return target_idx, chosen_target_clones


def _source_slot_indices_by_clone(source_clones):
    """Map source clone -> ordered pair-slot indices."""
    groups = {}
    for idx, clone_id in enumerate(np.asarray(source_clones, dtype=object)):
        groups.setdefault(clone_id, []).append(idx)
    return {
        clone_id: np.asarray(indices, dtype=int)
        for clone_id, indices in groups.items()
    }



def _prepare_stage3_source_resampling_cache(
    prep_t1,
    prep_t2,
    unit,
):
    """
    Cache source-clone block geometry for repeated Stage-3 bootstrap draws.

    The old implementation rebuilt clone dictionaries, shared/unique clone
    sets, row-index arrays, and per-block weight arrays for every null draw.
    None of that structure changes between draws.
    """
    unit = _resolve_unit(unit)

    groups_t1 = _source_slot_indices_by_clone(
        prep_t1["source_clones"]
    )
    groups_t2 = _source_slot_indices_by_clone(
        prep_t2["source_clones"]
    )

    clones_t1 = set(groups_t1)
    clones_t2 = set(groups_t2)

    shared = np.asarray(
        sorted(
            clones_t1 & clones_t2,
            key=lambda x: str(x),
        ),
        dtype=object,
    )
    t1_only = np.asarray(
        sorted(
            clones_t1 - clones_t2,
            key=lambda x: str(x),
        ),
        dtype=object,
    )
    t2_only = np.asarray(
        sorted(
            clones_t2 - clones_t1,
            key=lambda x: str(x),
        ),
        dtype=object,
    )

    def _weights_for_groups(groups):
        if unit == "twin":
            return {
                clone_id: np.ones(
                    len(ix),
                    dtype=float,
                )
                for clone_id, ix in groups.items()
            }
        return {
            clone_id: np.full(
                len(ix),
                1.0 / len(ix),
                dtype=float,
            )
            for clone_id, ix in groups.items()
        }

    return {
        "groups_t1": groups_t1,
        "groups_t2": groups_t2,
        "weights_t1": _weights_for_groups(
            groups_t1
        ),
        "weights_t2": _weights_for_groups(
            groups_t2
        ),
        "shared": shared,
        "t1_only": t1_only,
        "t2_only": t2_only,
        "meta": {
            "n_shared_source_clones": int(
                len(shared)
            ),
            "n_t1_only_source_clones": int(
                len(t1_only)
            ),
            "n_t2_only_source_clones": int(
                len(t2_only)
            ),
        },
    }

def _resample_source_clone_blocks(
    prep_t1,
    prep_t2,
    rng,
    unit,
    source_cache=None,
):
    """
    Jointly resample SOURCE clone blocks for the Stage-3 d null.

    `source_cache` stores the immutable clone/block geometry so repeated null
    draws only perform the actual bootstrap sampling and concatenation.
    """
    unit = _resolve_unit(unit)

    if source_cache is None:
        source_cache = (
            _prepare_stage3_source_resampling_cache(
                prep_t1,
                prep_t2,
                unit,
            )
        )

    groups_t1 = source_cache["groups_t1"]
    groups_t2 = source_cache["groups_t2"]
    weights_t1_cache = source_cache["weights_t1"]
    weights_t2_cache = source_cache["weights_t2"]

    shared = source_cache["shared"]
    t1_only = source_cache["t1_only"]
    t2_only = source_cache["t2_only"]

    sampled_shared = (
        rng.choice(
            shared,
            size=len(shared),
            replace=True,
        )
        if len(shared)
        else np.asarray([], dtype=object)
    )
    sampled_t1_only = (
        rng.choice(
            t1_only,
            size=len(t1_only),
            replace=True,
        )
        if len(t1_only)
        else np.asarray([], dtype=object)
    )
    sampled_t2_only = (
        rng.choice(
            t2_only,
            size=len(t2_only),
            replace=True,
        )
        if len(t2_only)
        else np.asarray([], dtype=object)
    )

    idx_t1_parts = []
    idx_t2_parts = []
    w_t1_parts = []
    w_t2_parts = []

    for clone_id in sampled_shared:
        idx_t1_parts.append(groups_t1[clone_id])
        idx_t2_parts.append(groups_t2[clone_id])
        w_t1_parts.append(
            weights_t1_cache[clone_id]
        )
        w_t2_parts.append(
            weights_t2_cache[clone_id]
        )

    for clone_id in sampled_t1_only:
        idx_t1_parts.append(groups_t1[clone_id])
        w_t1_parts.append(
            weights_t1_cache[clone_id]
        )

    for clone_id in sampled_t2_only:
        idx_t2_parts.append(groups_t2[clone_id])
        w_t2_parts.append(
            weights_t2_cache[clone_id]
        )

    if not idx_t1_parts or not idx_t2_parts:
        raise ValueError(
            "Stage-3 source-clone resampling "
            "produced an empty timepoint"
        )

    return (
        np.concatenate(idx_t1_parts),
        np.concatenate(idx_t2_parts),
        np.concatenate(w_t1_parts),
        np.concatenate(w_t2_parts),
        dict(source_cache["meta"]),
    )


def _randomized_delta_for_selected_twin_slots(
    prep,
    selected_idx,
    rng,
):
    """
    Build fresh random-pair differences for selected Stage-3 source slots.

    The selected source slots define only the number of observations and the
    separately supplied source-clone weights. Random-pair identities remain
    independent of the observed source clone.
    """
    n_slots = len(selected_idx)
    idx_a, idx_b = _sample_fresh_random_twin_indices(
        prep["random_pair_sampling_cache"],
        rng,
        n_slots,
    )

    return (
        prep["raw_values"][idx_a]
        - prep["raw_values"][idx_b]
    )


def _joint_shared_clone_random_twin_deltas(
    prep_t1,
    prep_t2,
    rng,
    unit,
    source_cache=None,
):
    """
    Generate one Stage-3 random-pair null realization.

    Shared source-clone blocks are bootstrapped jointly across t1/t2. Fresh
    random cell pairs are then drawn independently within each timepoint.
    """
    (
        idx_t1,
        idx_t2,
        w_t1,
        w_t2,
        meta,
    ) = _resample_source_clone_blocks(
        prep_t1,
        prep_t2,
        rng,
        unit=unit,
        source_cache=source_cache,
    )

    delta_t1 = _randomized_delta_for_selected_twin_slots(
        prep_t1,
        idx_t1,
        rng,
    )
    delta_t2 = _randomized_delta_for_selected_twin_slots(
        prep_t2,
        idx_t2,
        rng,
    )

    return (
        delta_t1,
        delta_t2,
        w_t1,
        w_t2,
        meta,
    )


def _stage3_random_pair_d_chunk(
    prep_t1,
    prep_t2,
    unit,
    pair_i,
    pair_j,
    draw_seeds,
    source_cache,
):
    """
    Compute a deterministic chunk of fresh-random-pair Stage-3 d-null draws.

    The source-clone geometry and RNG stream are unchanged. Each newly sampled
    Delta matrix is transposed once into contiguous G x N layout, then sorted
    along the contiguous row axis with quicksort. Exact ties are still handled
    gene-by-gene by the compiled weighted-rank kernel.
    """
    draw_seeds = np.asarray(draw_seeds, dtype=np.int64)
    out = np.empty((len(draw_seeds), len(pair_i)), dtype=float)
    last_meta = None

    for b, seed in enumerate(draw_seeds):
        rng = np.random.default_rng(int(seed))

        (
            delta_t1,
            delta_t2,
            weights_t1,
            weights_t2,
            last_meta,
        ) = _joint_shared_clone_random_twin_deltas(
            prep_t1,
            prep_t2,
            rng,
            unit=unit,
            source_cache=source_cache,
        )

        delta_t1_gn = np.ascontiguousarray(delta_t1.T)
        delta_t2_gn = np.ascontiguousarray(delta_t2.T)
        order_t1 = np.argsort(
            delta_t1_gn,
            axis=1,
            kind="quicksort",
        )
        order_t2 = np.argsort(
            delta_t2_gn,
            axis=1,
            kind="quicksort",
        )

        corr_t1 = _dynamic_weighted_spearman_pairs_from_order(
            delta_t1_gn.T,
            order_t1,
            weights_t1,
            pair_i,
            pair_j,
        )
        corr_t2 = _dynamic_weighted_spearman_pairs_from_order(
            delta_t2_gn.T,
            order_t2,
            weights_t2,
            pair_i,
            pair_j,
        )

        out[b, :] = corr_t2 - corr_t1

    return out, last_meta



def generate_difference_shuffle(
    t1_twins,
    t2_twins,
    gene_list,
    gene_pairs=None,
    t1_raw=None,
    t2_raw=None,
    n_shuffles=10000,
    random_state=101010,
    unit=None,
    precomputed_t1_null=None,
    shuffle_seeds=None,
    global_clone_map=None,
    n_cores_to_use=1,
):
    """
    Shared-clone-aware fresh-random-pair null for

        d = rho_Delta(t2) - rho_Delta(t1).

    The observed statistic is unchanged:

        d_obs = observed rho_Delta(t2) - observed rho_Delta(t1).

    For every null replicate:
      1. resample source clone-slot blocks; clones present at both t1 and t2 are
         resampled jointly so their contribution to t1/t2 covariance is kept;
      2. independently within t1, replace every selected twin slot by a fresh
         random pair: clone A uniformly -> cell A uniformly, then a different
         clone B uniformly -> cell B uniformly;
      3. independently repeat the same fresh random-pair construction at t2;
      4. compute rho_Delta_random(t1) and rho_Delta_random(t2);
      5. store

             d_null = rho_Delta_random(t2) - rho_Delta_random(t1).

    Both random-pair members are newly sampled from the raw-cell pool; no
    observed twin member is held fixed or anchored into the null. Random pair identities are not coupled across t1/t2; the only intended
    cross-time dependence is the shared source-clone block bootstrap.

    `precomputed_t1_null` and `global_clone_map` are retained only for backward
    API compatibility with the superseded fixed-Delta implementation and are
    ignored. `shuffle_seeds`, if supplied, is used only as one deterministic
    seed per complete Stage-3 null draw.
    """
    del precomputed_t1_null, global_clone_map

    unit = _resolve_unit(unit)
    n_shuffles = int(n_shuffles)
    if n_shuffles < 2:
        raise ValueError("n_shuffles must be at least 2")

    active_genes, requested_pairs = _requested_gene_subset(
        gene_list,
        gene_pairs,
    )
    if not requested_pairs:
        return {}, {
            "null_type": "fresh_random_cell_pairs_clone_first",
            "active_genes": [],
            "active_gene_pairs": [],
            "n_shuffles": n_shuffles,
            "unit": unit,
        }

    if t1_raw is None:
        t1_raw = t1_twins
    if t2_raw is None:
        t2_raw = t2_twins

    prep_t1 = _prepare_random_twin_null_inputs(
        t1_twins,
        t1_raw,
        active_genes,
    )
    prep_t2 = _prepare_random_twin_null_inputs(
        t2_twins,
        t2_raw,
        active_genes,
    )

    gene_to_idx = {
        gene: i for i, gene in enumerate(active_genes)
    }
    pair_i = np.asarray(
        [gene_to_idx[a] for a, _ in requested_pairs],
        dtype=int,
    )
    pair_j = np.asarray(
        [gene_to_idx[b] for _, b in requested_pairs],
        dtype=int,
    )
    pair_keys = list(requested_pairs)

    if shuffle_seeds is None:
        seed_rng = np.random.default_rng(random_state)
        draw_seeds = seed_rng.integers(
            0,
            np.iinfo(np.int64).max,
            size=n_shuffles,
            dtype=np.int64,
        )
    else:
        draw_seeds = np.asarray(shuffle_seeds, dtype=np.int64)
        if len(draw_seeds) < n_shuffles:
            raise ValueError("shuffle_seeds is shorter than n_shuffles")
        draw_seeds = draw_seeds[:n_shuffles]

    n_cores_to_use = max(1, int(n_cores_to_use))

    source_cache = (
        _prepare_stage3_source_resampling_cache(
            prep_t1,
            prep_t2,
            unit,
        )
    )

    if n_cores_to_use == 1 or n_shuffles < 2:
        d_values, last_meta = _stage3_random_pair_d_chunk(
            prep_t1,
            prep_t2,
            unit,
            pair_i,
            pair_j,
            draw_seeds,
            source_cache,
        )
    else:
        n_chunks = min(n_cores_to_use, n_shuffles)
        seed_chunks = [
            chunk
            for chunk in np.array_split(draw_seeds, n_chunks)
            if len(chunk)
        ]
        with threadpool_limits(
            limits=1,
            user_api="blas",
        ):
            parts = Parallel(
                n_jobs=len(seed_chunks),
                prefer="threads",
                require="sharedmem",
            )(
                delayed(_stage3_random_pair_d_chunk)(
                    prep_t1,
                    prep_t2,
                    unit,
                    pair_i,
                    pair_j,
                    chunk,
                    source_cache,
                )
                for chunk in seed_chunks
            )
        d_values = np.vstack(
            [values for values, _ in parts]
        )
        last_meta = next(
            (
                meta
                for _, meta in reversed(parts)
                if meta is not None
            ),
            None,
        )

    shared = (
        set(prep_t1["source_clones"])
        & set(prep_t2["source_clones"])
    )

    out = {
        key: d_values[:, k]
        for k, key in enumerate(pair_keys)
    }

    meta = {
        **(last_meta or {}),
        "null_type": "fresh_random_cell_pairs_clone_first",
        "observed_delta_rows_fixed": False,
        "fresh_cells_sampled": True,
        "both_random_pair_members_fresh": True,
        "random_pair_members_different_clones": True,
        "source_clone_excluded_from_random_pair": False,
        "clone_first_then_cell_within_clone": True,
        "shared_source_clone_blocks_resampled_jointly": True,
        "random_pairs_coupled_across_time": False,
        "cells_swapped_across_time": False,
        "n_shared_clones": int(len(shared)),
        "active_genes": list(active_genes),
        "active_gene_pairs": list(requested_pairs),
        "n_shuffles": n_shuffles,
        "unit": unit,
    }

    return out, meta


def identify_reg_if_multiple_states(
    twin_correlation_matrix_t1,
    twin_correlation_matrix_t2,
    random_correlation_matrix_t1,
    random_correlation_matrix_t2,
    multiple_states_gene_pairs,
    gene_list,
    t1_twins,
    t2_twins,
    t1_raw=None,
    t2_raw=None,
    alpha=0.01,
    n_shuffles=None,
    shuffle_seed=101010,
    unit=None,
    expected_null_rejections=50,
    minimum_null_draws=2000,
    precomputed_t1_null=None,
    shuffle_seeds=None,
    global_clone_map=None,
    n_cores_to_use=1,
    divergence_shuffle_seed=271833,
    precomputed_divergence_t1_null=None,
    precomputed_divergence_t2_null=None,
    return_raw_nulls=False,
):
    """
    Step 3: evaluate the same observed d under both canonical rho_Delta nulls.

    Observed:
        d_obs = rho_Delta(t2) - rho_Delta(t1).

    Heterogeneity null (existing / earlier):
      - replace twins by fresh unrelated-cell pairs at each time point;
      - jointly resample source clone blocks across t1/t2 when appropriate;
      - compute z_d_het from that d-null.

    Divergence null (Yuval fixed-Delta):
      - keep all measured Delta values at each time point exactly;
      - keep Delta_X fixed and re-pair Delta_Y one-to-one across clones;
      - perform the t1 and t2 re-pairings independently;
      - compute z_d_div from the resulting d-null.

    The existing Step-3 regulation classification remains intentionally based
    on z_d_het, so adding z_d_div does not silently change pipeline calls.

    Both scores use
        z = (d_obs - mean(d_null)) / SD(d_null).

    return_raw_nulls (default False, purely additive -- omitting it changes
    nothing): if True, a 4th return value is appended -- a dict with keys
    "d_het" and "d_div", each {sorted_gene_pair: array(n_shuffles)} -- the
    same d_null_by_pair / d_div_null_by_pair arrays used above to compute
    z_d_het/z_d_div, which would otherwise be discarded once this function
    returns.
    """
    del random_correlation_matrix_t1, random_correlation_matrix_t2

    unit = _resolve_unit(unit)

    # 2026-09-23: alpha == 1.0 is now allowed (z_critical = norm.ppf(0) = -inf, i.e. the one-sided
    # regulation call never rejects a pair; ci_critical = norm.ppf(0.5) = 0). Used by the FateMap
    # "include every pair" inference rerun; default behaviour for alpha < 1 is unchanged.
    # if not 0 < alpha < 1:
    #     raise ValueError("alpha must be between 0 and 1")
    if not 0 < alpha <= 1:
        raise ValueError("alpha must be in (0, 1]")

    multiple_states_no_reg = []
    multiple_states_and_reg = []
    stage3_details = {}

    rep_0_t1, _ = split_twins(t1_twins)
    rep_0_t2, _ = split_twins(t2_twins)
    n1 = get_number_of_units(rep_0_t1, unit=unit)
    n2 = get_number_of_units(rep_0_t2, unit=unit)

    n_shuffles_used = get_conservative_null_draw_count(
        n_shuffles=n_shuffles,
        alpha=alpha,
        expected_rejections=expected_null_rejections,
        minimum=minimum_null_draws,
    )

    d_null_by_pair, null_meta = generate_difference_shuffle(
        t1_twins,
        t2_twins,
        gene_list,
        gene_pairs=multiple_states_gene_pairs,
        t1_raw=t1_raw,
        t2_raw=t2_raw,
        n_shuffles=n_shuffles_used,
        random_state=shuffle_seed,
        unit=unit,
        precomputed_t1_null=precomputed_t1_null,
        shuffle_seeds=shuffle_seeds,
        global_clone_map=global_clone_map,
        n_cores_to_use=n_cores_to_use,
    )

    d_div_null_by_pair, div_null_meta = generate_divergence_difference_shuffle(
        t1_twins,
        t2_twins,
        gene_list,
        gene_pairs=multiple_states_gene_pairs,
        n_shuffles=n_shuffles_used,
        random_state=divergence_shuffle_seed,
        unit=unit,
        precomputed_t1_null=precomputed_divergence_t1_null,
        precomputed_t2_null=precomputed_divergence_t2_null,
        n_cores_to_use=n_cores_to_use,
    )

    z_critical = float(stats.norm.ppf(1.0 - alpha))
    ci_critical = float(stats.norm.ppf(1.0 - alpha / 2.0))

    for gene_i, gene_j in multiple_states_gene_pairs:
        try:
            corr_t1 = float(
                twin_correlation_matrix_t1.loc[gene_i, gene_j]
            )
            corr_t2 = float(
                twin_correlation_matrix_t2.loc[gene_i, gene_j]
            )
        except KeyError:
            raise ValueError(
                f"Missing gene pair ({gene_i}, {gene_j}) in correlation matrices."
            )

        d_obs = float(corr_t2 - corr_t1)
        key = tuple(sorted((gene_i, gene_j)))

        d_het_null = np.asarray(
            d_null_by_pair[key],
            dtype=float,
        )
        het_finite = d_het_null[np.isfinite(d_het_null)]

        if het_finite.size < 2:
            het_null_mean = np.nan
            het_null_std = np.nan
            z_d_het = np.nan
            het_empirical_p = np.nan
            het_interval = (np.nan, np.nan)
            call = "no regulation"
        else:
            het_null_mean = float(np.mean(het_finite))
            het_null_std = float(np.std(het_finite, ddof=1))

            if het_null_std > 0:
                # Change in twin difference correlation across time -- heterogeneity Z-score
                # LaTeX: d = \hat{\rho}_{\Delta}(t_2)
                #                                - \hat{\rho}_{\Delta}(t_1)
                # Permutation method: for each null draw, resample source-clone blocks;
                # if a biological clone appears at both times, resample that clone jointly
                # at t1 and t2. Then, independently at each time point, replace every
                # selected twin slot with a fresh unrelated pair: choose clone A uniformly,
                # choose clone B != A uniformly, then choose one cell uniformly within each.
                # Compute weighted \rho_{\Delta,\mathrm{rand}} at t1 and t2 and store
                # \rho_{\Delta,\mathrm{rand}}(t_2)-\rho_{\Delta,\mathrm{rand}}(t_1).
                # Twin mode gives every twin weight 1; clone mode gives each source clone
                # total weight 1. Z-score the observed d against this difference null.
                # (same with z_het at each time point)
                z_d_het = float(
                    (d_obs - het_null_mean) / het_null_std
                )
                het_interval = (
                    float(d_obs - ci_critical * het_null_std),
                    float(d_obs + ci_critical * het_null_std),
                )
            else:
                z_d_het = np.nan
                het_interval = (np.nan, np.nan)

            het_empirical_p = float(
                (1.0 + np.sum(het_finite >= d_obs))
                / (het_finite.size + 1.0)
            )

            call = (
                "regulation"
                if np.isfinite(z_d_het) and z_d_het > z_critical
                else "no regulation"
            )

        d_div_null = np.asarray(
            d_div_null_by_pair[key],
            dtype=float,
        )
        div_finite = d_div_null[np.isfinite(d_div_null)]
        if div_finite.size < 2:
            div_null_mean = np.nan
            div_null_std = np.nan
            z_d_div = np.nan
            div_empirical_p = np.nan
            div_interval = (np.nan, np.nan)
        else:
            div_null_mean = float(np.mean(div_finite))
            div_null_std = float(np.std(div_finite, ddof=1))
            if div_null_std > 0:
                # Change in twin difference correlation across time -- divergence Z-score
                # LaTeX: d = \hat{\rho}_{\Delta}(t_2)
                #                                - \hat{\rho}_{\Delta}(t_1)
                # Permutation method: at each time point, keep every observed \Delta X
                # and \Delta Y value unchanged, hold \Delta X fixed, and reassign the
                # complete \Delta Y rows one-to-one across other biological clones.
                # Recompute weighted Spearman at t1 and t2, then store the shuffled
                # t2 correlation minus the shuffled t1 correlation. Z-score the observed
                # d against that difference distribution.
                # (same with z_div at each time point)
                z_d_div = float(
                    (d_obs - div_null_mean) / div_null_std
                )
                div_interval = (
                    float(d_obs - ci_critical * div_null_std),
                    float(d_obs + ci_critical * div_null_std),
                )
            else:
                z_d_div = np.nan
                div_interval = (np.nan, np.nan)
            div_empirical_p = float(
                (1.0 + np.sum(div_finite >= d_obs))
                / (div_finite.size + 1.0)
            )

        # 2026-09-29: unconditional per-pair print, same fix as
        # differentiate_single_state_reg_and_multiple_states -- commented out, not the math.
        # print(
        #     f"gene 1: {gene_i}, gene 2: {gene_j}, "
        #     f"rho_delta_t1={corr_t1:.6f}, "
        #     f"rho_delta_t2={corr_t2:.6f}, "
        #     f"d={d_obs:.6f}, "
        #     f"z_d_het={z_d_het:.4f}, "
        #     f"z_d_div={z_d_div:.4f}, "
        #     f"critical={z_critical:.4f}, "
        #     f"call={call}"
        # )

        details = {
            # The observed d is the same quantity under both nulls.
            "d": d_obs,
            "d_het": d_obs,
            "d_div": d_obs,

            # Canonical heterogeneity fields (fresh random-pair null).
            "het_null_mean": het_null_mean,
            "het_null_std": het_null_std,
            "z_d_het": z_d_het,
            "het_empirical_p_one_sided": het_empirical_p,
            "het_interval": het_interval,

            # Canonical divergence fields (Yuval fixed-Delta null).
            "div_null_mean": div_null_mean,
            "div_null_std": div_null_std,
            "z_d_div": z_d_div,
            "div_empirical_p_one_sided": div_empirical_p,
            "div_interval": div_interval,

            # Backward-compatible aliases: the old generic Stage-3 fields are
            # the heterogeneity/random-pair version.
            "null_mean": het_null_mean,
            "null_std": het_null_std,
            "standard_err": het_null_std,
            "z_d": z_d_het,
            "z_critical": z_critical,
            "empirical_p_one_sided": het_empirical_p,
            "interval": het_interval,
            "call": call,
            "n_shuffles": int(n_shuffles_used),
            "n1": int(n1),
            "n2": int(n2),
            "unit": unit,
            "heterogeneity_null_meta": dict(null_meta),
            "divergence_null_meta": dict(div_null_meta),
            **null_meta,
        }

        stage3_details[(gene_i, gene_j)] = details

        if call == "regulation":
            multiple_states_and_reg.append((gene_i, gene_j))
        else:
            multiple_states_no_reg.append((gene_i, gene_j))

    if return_raw_nulls:
        return (
            multiple_states_no_reg,
            multiple_states_and_reg,
            stage3_details,
            {"d_het": d_null_by_pair, "d_div": d_div_null_by_pair},
        )

    return (
        multiple_states_no_reg,
        multiple_states_and_reg,
        stage3_details,
    )


def get_cross_correlations(
    rep_0_t1,
    rep_1_t2,
    gene_pairs,
    type_comparison="twin",
    unit=None,
):
    """
    Directional cross-time weighted Spearman correlations.

    Each active gene is ranked once at t1 and once at t2; all requested
    cross-correlations are then read from one cross-covariance matrix.
    """
    unit = _resolve_unit(unit)
    gene_pairs = list(gene_pairs)

    if type_comparison == "twin":
        for name, frame in (
            ("rep_0_t1", rep_0_t1),
            ("rep_1_t2", rep_1_t2),
        ):
            missing = {"twin_id", "clone_id"} - set(frame.columns)
            if missing:
                raise ValueError(
                    f"{name} is missing required columns: {sorted(missing)}"
                )

        rep_0_t1 = rep_0_t1.sort_values("twin_id").reset_index(drop=True)
        rep_1_t2 = rep_1_t2.sort_values("twin_id").reset_index(drop=True)

        if not rep_0_t1["twin_id"].equals(rep_1_t2["twin_id"]):
            raise ValueError(
                "Mismatch in twin_id between cross-time frames. "
                "Cross-time pairing must be established before calling "
                "get_cross_correlations."
            )
        if not rep_0_t1["clone_id"].equals(rep_1_t2["clone_id"]):
            raise ValueError(
                "Matched cross-time twin_id rows have different clone_id values"
            )
    elif type_comparison == "random":
        rep_0_t1 = rep_0_t1.reset_index(drop=True)
        rep_1_t2 = rep_1_t2.reset_index(drop=True)
    else:
        raise ValueError("type_comparison must be 'twin' or 'random'")

    if len(rep_0_t1) != len(rep_1_t2):
        raise ValueError(
            "Cross-time frames must have the same number of twin rows"
        )

    gene_list = sorted({
        gene
        for pair in gene_pairs
        for gene in pair
    })
    all_pairs = list(gene_pairs)
    for gene in gene_list:
        if (gene, gene) not in all_pairs:
            all_pairs.append((gene, gene))

    gene_cols = [f"{gene}_mRNA" for gene in gene_list]
    missing = [
        col for col in gene_cols
        if col not in rep_0_t1.columns
        or col not in rep_1_t2.columns
    ]
    if missing:
        raise ValueError(
            f"Missing cross-time gene-expression column(s): {missing}"
        )

    x = rep_0_t1[gene_cols].to_numpy(dtype=float)
    y = rep_1_t2[gene_cols].to_numpy(dtype=float)
    weights = get_unit_weights(rep_0_t1, unit=unit)

    x_cache = _prepare_delta_rank_permutation_cache(x, weights)
    y_cache = _prepare_delta_rank_permutation_cache(y, weights)

    cx = x_cache["cx"]
    cy = y_cache["cx"]
    sx = x_cache["sx"]
    sy = y_cache["sx"]

    numer = cx.T @ (weights[:, None] * cy)
    den = np.outer(sx, sy)

    with np.errstate(divide="ignore", invalid="ignore"):
        cross = numer / den
    cross[den == 0] = np.nan

    gene_to_idx = {
        gene: i for i, gene in enumerate(gene_list)
    }
    raw_matrix = pd.DataFrame(
        np.nan,
        index=gene_list,
        columns=gene_list,
        dtype=float,
    )

    for gene_1, gene_2 in all_pairs:
        raw_matrix.loc[gene_1, gene_2] = cross[
            gene_to_idx[gene_1],
            gene_to_idx[gene_2],
        ]

    return raw_matrix


def identify_actual_directed_edges(
    rep_0_t1,
    rep_1_t2,
    direction_raw_matrix,
    gene_pairs,
    z_score_threshold=2.5,
    use_scramble=True,
    corr_threshold=0.049,
    n_shuffles=10000,
    n_cores_to_use=4,
    verbose=False,
    base_seed=101010,
    multiple_states_gene_pairs=None,
    return_z_scores=False,
    return_direction_diff=False,
    return_rho_cross_null=False,
    prepare_rho_cross_null=True,
    unit=None,
):
    """
    Identify directed edges from rho-dagger.

    The raw signed rho_cross null is kept separately for every directed pair:

        rho_cross_null = {rho_xy^(b)}.

    No absolute value is applied to this stored null. With
    prepare_rho_cross_null=True, it is generated even if use_scramble=False,
    so it is available for later use without controlling the present edge call.

    Every rho_cross null shuffle excludes the source biological clone.

    gamma remains a separate magnitude statistic:

        gamma = |rho_xy| - |rho_yx|

        gamma_null = |rho_xy_null| - |rho_yx_null|.

    Thus abs() is applied only when constructing gamma, never to the separately
    stored rho_cross null.
    """
    unit = _resolve_unit(unit)

    needed_genes = {
        gene
        for pair in gene_pairs
        for gene in pair
    }
    gene_list = [
        gene
        for gene in direction_raw_matrix.index
        if gene in needed_genes
    ]

    for name, frame in (("rep_0_t1", rep_0_t1), ("rep_1_t2", rep_1_t2)):
        missing = {"twin_id", "clone_id"} - set(frame.columns)
        if missing:
            raise ValueError(f"{name} is missing required columns: {sorted(missing)}")

    rep_0_t1 = rep_0_t1.sort_values("twin_id").reset_index(drop=True)
    rep_1_t2 = rep_1_t2.sort_values("twin_id").reset_index(drop=True)
    if len(rep_0_t1) != len(rep_1_t2):
        raise ValueError("Cross-time frames must have the same number of twin rows")
    if not rep_0_t1["twin_id"].equals(rep_1_t2["twin_id"]):
        raise ValueError("Mismatch in twin_id between cross-time frames")
    if not rep_0_t1["clone_id"].equals(rep_1_t2["clone_id"]):
        raise ValueError("Matched cross-time twin_id rows have different clone_id values")

    need_rho_cross_null = bool(
        use_scramble or prepare_rho_cross_null
    )
    null_matrix = None

    if need_rho_cross_null:
        gene_matrix_t1 = []
        gene_matrix_t2 = []
        for gene in gene_list:
            gene_col_t1 = f"{gene}_mRNA" if f"{gene}_mRNA" in rep_0_t1.columns else None
            gene_col_t2 = f"{gene}_mRNA" if f"{gene}_mRNA" in rep_1_t2.columns else None
            if not gene_col_t1:
                matching_cols = [col for col in rep_0_t1.columns if gene in col and 'mRNA' in col]
                gene_col_t1 = matching_cols[0] if matching_cols else None
            if not gene_col_t2:
                matching_cols = [col for col in rep_1_t2.columns if gene in col and 'mRNA' in col]
                gene_col_t2 = matching_cols[0] if matching_cols else None
            if gene_col_t1 and gene_col_t2:
                gene_matrix_t1.append(rep_0_t1[gene_col_t1].values)
                gene_matrix_t2.append(rep_1_t2[gene_col_t2].values)
            else:
                raise ValueError(f"Could not find mRNA columns for gene {gene}")

        gene_matrix_t1 = np.asarray(gene_matrix_t1, dtype=float)
        gene_matrix_t2 = np.asarray(gene_matrix_t2, dtype=float)
        _assert_no_nan(gene_matrix_t1, "identify_actual_directed_edges (rep_0_t1)")
        _assert_no_nan(gene_matrix_t2, "identify_actual_directed_edges (rep_1_t2)")

        gene_to_idx = {g: i for i, g in enumerate(gene_list)}
        pair_i = np.array([gene_to_idx[g1] for g1, g2 in gene_pairs], dtype=np.int64)
        pair_j = np.array([gene_to_idx[g2] for g1, g2 in gene_pairs], dtype=np.int64)
        seeds = _spawn_independent_seeds(base_seed, n_shuffles)

        weights = get_unit_weights(rep_0_t1, unit=unit)
        null_matrix = _weighted_cross_permutation_null(
            gene_matrix_t1.T,
            gene_matrix_t2.T,
            weights,
            rep_0_t1["clone_id"].to_numpy(),
            seeds,
            pair_i,
            pair_j,
            n_cores_to_use=n_cores_to_use,
        )

    significant_edges = []
    z_score_calc = {}
    is_significant_map = {}
    rho_cross_null_details = {}
    print(f"number of gene pairs = {len(gene_pairs)}; unit={unit}")

    for pos, (gene_1, gene_2) in enumerate(gene_pairs):
        actual_corr = float(
            direction_raw_matrix.loc[gene_1, gene_2]
        )
        gene_pair_name = f"{gene_1} -> {gene_2}"
        is_relatively_normal = True

        # ---------------------------------------------------------
        # Separate RAW SIGNED rho_cross null.
        # ---------------------------------------------------------
        if need_rho_cross_null:
            shuffled_vals = np.asarray(
                null_matrix[:, pos],
                dtype=float,
            )
            finite = shuffled_vals[np.isfinite(shuffled_vals)]

            if finite.size < 2:
                rho_null_mean = np.nan
                rho_null_std = np.nan
                rho_null_z = np.nan
            else:
                rho_null_mean = float(np.mean(finite))
                rho_null_std = float(np.std(finite, ddof=1))
                # Twin cross-correlation for direction x -> y (TwINFER direction step)
                # LaTeX: \hat{\rho}^{\dagger}_{x(t_1)\to y(t_2)}
                # Permutation method: keep the t1 rows fixed and reassign the complete
                # t2 rows one-to-one across the cross-time twin table, with the rule that
                # a t1 row can never receive a t2 row from the same biological clone.
                # Recompute the weighted x(t1)-to-y(t2) Spearman correlation for every
                # shuffle; the Z-score compares the observed twin cross-correlation with
                # this random-pair cross-correlation distribution.
                # (same with the reverse direction and gamma)
                rho_null_z = (
                    float(
                        (actual_corr - rho_null_mean)
                        / rho_null_std
                    )
                    if rho_null_std > 0
                    else np.nan
                )

            rho_cross_null_details[(gene_1, gene_2)] = {
                "observed_rho_cross": actual_corr,
                "null_values": shuffled_vals.copy(),
                "null_mean": rho_null_mean,
                "null_std": rho_null_std,
                "z_rho_cross": rho_null_z,
                "n_shuffles": int(len(shuffled_vals)),
                "source_clone_excluded": True,
                "unit": unit,
            }
        else:
            shuffled_vals = None
            finite = np.asarray([], dtype=float)
            rho_null_z = np.nan

        # ---------------------------------------------------------
        # Edge decision.
        # ---------------------------------------------------------
        if use_scramble:
            z_val = rho_null_z
            is_significant = bool(
                np.isfinite(z_val)
                and abs(z_val) > z_score_threshold
            )
            z_score_calc[(gene_1, gene_2)] = z_val

            # 2026-09-29: unconditional per-pair prints (not gated by `verbose`) were the
            # dominant wall-clock cost at thousand-pair scale. Commented out, not the math.
            # print(
            #     f"Observed correlation for {gene_1} -> {gene_2}: "
            #     f"{actual_corr:.4f}, z-score: {z_val:.4f}, "
            #     f"unit={unit}"
            # )
            # print(
            #     f"Significant at |z|>{z_score_threshold}: "
            #     f"{is_significant}"
            # )

            if is_significant:
                is_relatively_normal = plot_qq_distribution(
                    shuffled_vals,
                    actual_corr,
                    gene_pair_name,
                    verbose=verbose,
                )
                # print(
                #     f"{gene_pair_name}: normality of null: "
                #     f"{is_relatively_normal}"
                # )

            if verbose:
                plt.figure(figsize=(6, 4))
                plt.hist(
                    finite,
                    bins=40,
                    color="lightgray",
                    edgecolor="black",
                )
                plt.axvline(
                    actual_corr,
                    color="blue",
                    linestyle="-",
                    linewidth=2,
                    label=f"actual = {actual_corr:.4g}",
                )
                plt.xlabel("Shuffled signed rho_cross")
                plt.ylabel("number of scrambles")
                plt.title(
                    f"rho_cross null: {gene_1} → {gene_2}"
                )
                plt.legend(frameon=False)
                plt.tight_layout()
                plt.show()

        else:
            is_significant = bool(
                np.isfinite(actual_corr)
                and abs(actual_corr) > corr_threshold
            )
            # This stays None because this z-score was not used for the
            # current edge decision. The prepared z is still available as
            # rho_cross_null_details[pair]["z_rho_cross"].
            z_score_calc[(gene_1, gene_2)] = None

            # 2026-09-29: unconditional per-pair print, commented out (see above).
            # print(
            #     f"Observed correlation for {gene_1} -> {gene_2}: "
            #     f"{actual_corr:.4f}, |corr| > {corr_threshold}: "
            #     f"{is_significant}, unit={unit}"
            # )

        is_significant_map[(gene_1, gene_2)] = is_significant
        if is_significant and is_relatively_normal:
            significant_edges.append((gene_1, gene_2))

    direction_diff_details = {}
    if return_direction_diff and need_rho_cross_null:
        pair_pos = {(g1, g2): pos for pos, (g1, g2) in enumerate(gene_pairs)}
        multi_state_pairs_set = set(frozenset(p) for p in (multiple_states_gene_pairs or []))
        seen = set()
        for gene_1, gene_2 in gene_pairs:
            if gene_1 == gene_2:
                continue
            key = frozenset((gene_1, gene_2))
            if key in seen or (gene_2, gene_1) not in pair_pos:
                continue
            seen.add(key)
            if not (
                is_significant_map.get((gene_1, gene_2), False)
                and is_significant_map.get((gene_2, gene_1), False)
            ):
                continue

            pos_ab = pair_pos[(gene_1, gene_2)]
            pos_ba = pair_pos[(gene_2, gene_1)]
            corr_ab = float(direction_raw_matrix.loc[gene_1, gene_2])
            corr_ba = float(direction_raw_matrix.loc[gene_2, gene_1])

            # Direction-strength asymmetry:
            #
            #     gamma = |rho_xy| - |rho_yx|
            #
            # Absolute values are taken BEFORE subtraction. gamma compares
            # directional magnitudes, not correlation signs.
            gamma_actual = abs(corr_ab) - abs(corr_ba)

            # The null must use the exact same statistic.
            gamma_null = (
                np.abs(null_matrix[:, pos_ab])
                - np.abs(null_matrix[:, pos_ba])
            )
            finite_gamma = gamma_null[np.isfinite(gamma_null)]

            gamma_null_mean = (
                float(np.mean(finite_gamma))
                if finite_gamma.size else np.nan
            )
            gamma_null_std = (
                float(np.std(finite_gamma, ddof=1))
                if finite_gamma.size > 1 else np.nan
            )

            # Directional asymmetry between the two twin cross-correlations
            # LaTeX: \gamma =
            # |\hat{\rho}^{\dagger}_{x(t_1)\to y(t_2)}|
            # - |\hat{\rho}^{\dagger}_{y(t_1)\to x(t_2)}|
            # Permutation method: use the paired cross-clone permutation draws already
            # generated for the two directional twin cross-correlations. For each draw,
            # take |\rho^{\dagger}_{x\to y,null}|-|\rho^{\dagger}_{y\to x,null}| to form
            # the gamma null, then Z-score the observed signed gamma against it.
            # (same with z_rho_cross in both directions)
            z_gamma = (
                (gamma_actual - gamma_null_mean) / gamma_null_std
                if np.isfinite(gamma_null_std) and gamma_null_std > 0
                else np.nan
            )
            gamma_significant = bool(
                np.isfinite(z_gamma)
                and abs(z_gamma) > z_score_threshold
            )

            z_ab = rho_cross_null_details[
                (gene_1, gene_2)
            ]["z_rho_cross"]
            z_ba = rho_cross_null_details[
                (gene_2, gene_1)
            ]["z_rho_cross"]

            # If gamma is significant, its sign determines which directional
            # correlation has the larger magnitude.
            if gamma_significant and gamma_actual > 0:
                dominant = (gene_1, gene_2)
                verdict = f"directed: {gene_1}->{gene_2} dominates"
            elif gamma_significant and gamma_actual < 0:
                dominant = (gene_2, gene_1)
                verdict = f"directed: {gene_2}->{gene_1} dominates"
            else:
                dominant = None
                verdict = "bidirectional / mutual regulation"

            direction_diff_details[key] = {
                "pair": (gene_1, gene_2),
                "rho_ab": corr_ab,
                "rho_ba": corr_ba,
                "gamma": float(gamma_actual),
                "z_ab": float(z_ab),
                "z_ba": float(z_ba),
                "gamma_null_mean": gamma_null_mean,
                "gamma_null_std": gamma_null_std,
                "z_gamma": float(z_gamma),
                "gamma_significant": gamma_significant,
                "dominant_direction": dominant,
                "verdict": verdict,
                "multi_state_flagged": key in multi_state_pairs_set,
                "unit": unit,

                # Backward-compatible aliases.
                "corr_ab": corr_ab,
                "corr_ba": corr_ba,
                "diff": float(gamma_actual),
                "diff_null_mean": gamma_null_mean,
                "diff_null_std": gamma_null_std,
                "z_diff": float(z_gamma),
                "diff_significant": gamma_significant,
            }

            print(
                f"Direction gamma {gene_1}<->{gene_2}: "
                f"gamma={gamma_actual:.4f}, z_gamma={z_gamma:.4f}, "
                f"verdict={verdict}"
                + (
                    " [multi-state flagged]"
                    if key in multi_state_pairs_set and dominant is None
                    else ""
                )
            )

    if return_z_scores and return_direction_diff and return_rho_cross_null:
        return (
            significant_edges,
            z_score_calc,
            direction_diff_details,
            rho_cross_null_details,
        )
    if return_z_scores and return_direction_diff:
        return significant_edges, z_score_calc, direction_diff_details
    if return_z_scores and return_rho_cross_null:
        return significant_edges, z_score_calc, rho_cross_null_details
    if return_direction_diff and return_rho_cross_null:
        return (
            significant_edges,
            direction_diff_details,
            rho_cross_null_details,
        )
    if return_z_scores:
        return significant_edges, z_score_calc
    if return_direction_diff:
        return significant_edges, direction_diff_details
    if return_rho_cross_null:
        return significant_edges, rho_cross_null_details
    return significant_edges



def separate_fan_outs_from_mutual_regulation(all_t1_measurements, twin_correlation_matrix_t1, gene_list,
                                              final_directed_edges, directed_z_scores, direction_matrix,
                                              z_score_threshold=8, unit=None, precomputed_null=None,
                                              n_shuffles=10000,
                                              n_cores_to_use=1):
    """
    Distinguishes true mutual regulation (A<->B) from a fan-out artifact, for gene pairs
    that share a common upstream regulator C (C->A and C->B both present in
    final_directed_edges). Both A->B and B->A being directed edges could either reflect real
    reciprocal regulation, or simply be an artifact of A and B being co-driven by C with no
    direct A-B interaction. The two are told apart with the same twin-vs-random z-score
    already used in differentiate_single_state_reg_and_multiple_states (Step 3): a pair whose
    undirected correlation is far outside the random-reference null (|z| large) is behaving like it
    is driven by a shared hidden driver (i.e. C) rather than a direct link between A and B.

    Four cases per (A, B) pair with >=1 common regulator:
      1. Neither A->B nor B->A present: no cross-correlation, left untouched.
      2. Exactly one of A->B / B->A present: feed-forward loop, left untouched.
      3/4. Both present: |z| > z_score_threshold -> fan-out, both edges removed;
           |z| <= z_score_threshold -> mutual regulation, both edges kept.
           Exception: if direction_matrix shows BOTH A->B and B->A are negative (mutual
           repression / toggle-switch motif), the pair is always kept as mutual regulation,
           overriding the z-score call -- a genuine double-negative feedback loop can drive
           A and B into a large undirected z-score the same way a shared-regulator fan-out
           would, so the sign pattern takes precedence. This override does NOT apply to
           mutual activation (both positive): those still go through the z-score check as
           before.

    Parameters
    ----------
    all_t1_measurements : pd.DataFrame
        Single-timepoint (t1) cell-gene dataframe, same data used to build
        twin_correlation_matrix_t1, used as the raw-cell pool for the random-pair rho_Delta reference.
    twin_correlation_matrix_t1 : pd.DataFrame
        Twin correlation matrix at t1 (same one used in Step 3).
    gene_list : list of str
        Gene names in matrix order.
    final_directed_edges : set of tuple
        Directed edges (gene_src, gene_tgt) inferred so far.
    directed_z_scores : dict
        Mapping {(gene_src, gene_tgt): z_score} for directed edges (from
        identify_actual_directed_edges' per-direction test).
    direction_matrix : pd.DataFrame
        Directional correlation matrix, thresholded to final_directed_edges.
    z_score_threshold : float, default=8
        |z| above this value on the undirected (A,B) pair marks it a fan-out.

    Returns
    -------
    final_directed_edges : set of tuple
        Updated in place: fan-out (A,B)/(B,A) edges removed.
    directed_z_scores : dict
        Updated in place: fan-out (A,B)/(B,A) entries removed.
    direction_matrix : pd.DataFrame
        Updated in place: fan-out (A,B)/(B,A) cells zeroed.
    fan_out_log : list of dict
        One entry per (A, B) pair that had a common regulator, recording the shared
        regulator(s), the z-score, and the decision made.
    """
    unit = _resolve_unit(unit)
    regulators_of = {gene: set() for gene in gene_list}
    for src, tgt in final_directed_edges:
        if src != tgt:
            regulators_of.setdefault(tgt, set()).add(src)

    if precomputed_null is None:
        pair_table = (
            all_t1_measurements
            if "twin_id" in all_t1_measurements.columns
            else assign_twin_id(all_t1_measurements)
        )
        random_delta_reference_distribution = generate_random_shuffle(
            pair_table,
            gene_list=gene_list,
            n_shuffles=n_shuffles,
            unit=unit,
            raw_cells=all_t1_measurements,
            n_cores_to_use=n_cores_to_use,
        )
    else:
        random_delta_reference_distribution = precomputed_null

    fan_out_log = []
    for idx_a, gene_a in enumerate(gene_list):
        for gene_b in gene_list[idx_a + 1:]:
            common_regulators = (regulators_of.get(gene_a, set()) & regulators_of.get(gene_b, set())) - {gene_a, gene_b}
            if not common_regulators:
                continue

            a_to_b = (gene_a, gene_b) in final_directed_edges
            b_to_a = (gene_b, gene_a) in final_directed_edges

            if not a_to_b and not b_to_a:
                continue  # Case 1: no cross-correlation between A and B
            if a_to_b != b_to_a:
                continue  # Case 2: feed-forward loop, leave as is

            # Case 3 / 4: A->B and B->A both present -- check the undirected (A,B) z-score
            t_corr = twin_correlation_matrix_t1.loc[gene_a, gene_b]
            r_corr = get_correlations(random_delta_reference_distribution, gene_a, gene_b)
            r_corr_std = np.std(r_corr)
            # Twin difference correlation at time t -- fan-out / mutual-regulation check
            # LaTeX: observed twins \hat{\rho}_{\Delta}(t); random-pair
            # reference \rho_{\Delta}(t).
            # Permutation method: for every observed twin slot, draw a fresh unrelated
            # pair by choosing clone A uniformly, choosing a different clone B uniformly,
            # then choosing one cell uniformly from each clone. Use that same random cell
            # pair to form \Delta X and \Delta Y, recompute weighted Spearman across all
            # slots, and repeat to form the random-pair \rho_{\Delta}(t) distribution.
            # The Z-score compares \hat{\rho}_{\Delta}(t) with that distribution; in
            # clone mode, source twin labels affect only the weights (clone total = 1).
            # (same with z_het)
            z_score = np.inf if r_corr_std == 0 else (t_corr - np.mean(r_corr)) / r_corr_std

            regulators_str = ", ".join(sorted(common_regulators))
            mutual_repression = (
                direction_matrix.loc[gene_a, gene_b] < 0 and direction_matrix.loc[gene_b, gene_a] < 0
            )
            if abs(z_score) > z_score_threshold and not mutual_repression:
                print(f"Inference: fan-out detected -- {regulators_str} regulate(s) both {gene_a} and {gene_b} "
                      f"(|z|={abs(z_score):.2f} > {z_score_threshold}); removing direct edge between {gene_a} and {gene_b}.")
                final_directed_edges.discard((gene_a, gene_b))
                final_directed_edges.discard((gene_b, gene_a))
                directed_z_scores.pop((gene_a, gene_b), None)
                directed_z_scores.pop((gene_b, gene_a), None)
                if gene_a in direction_matrix.index and gene_b in direction_matrix.columns:
                    direction_matrix.loc[gene_a, gene_b] = 0
                    direction_matrix.loc[gene_b, gene_a] = 0
                decision = "fan_out"
            elif mutual_repression and abs(z_score) > z_score_threshold:
                print(f"Inference: mutual regulation confirmed -- {gene_a} and {gene_b} share regulator(s) "
                      f"{regulators_str}, but {gene_a}->{gene_b} and {gene_b}->{gene_a} are both negative "
                      f"(mutual repression); overriding the fan-out z-score call "
                      f"(|z|={abs(z_score):.2f} > {z_score_threshold}); keeping both edges.")
                decision = "mutual_regulation"
            else:
                print(f"Inference: mutual regulation confirmed -- {gene_a} and {gene_b} share regulator(s) "
                      f"{regulators_str} but their direct correlation is not explained by it "
                      f"(|z|={abs(z_score):.2f} <= {z_score_threshold}); keeping both edges.")
                decision = "mutual_regulation"

            fan_out_log.append({
                "gene_a": gene_a,
                "gene_b": gene_b,
                "common_regulators": sorted(common_regulators),
                "z_score": z_score,
                "decision": decision,
                "mutual_repression_override": bool(mutual_repression and abs(z_score) > z_score_threshold),
            })

    return final_directed_edges, directed_z_scores, direction_matrix, fan_out_log


