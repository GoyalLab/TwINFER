def calculate_twin_score(inference_output):
    """
    Calculate the current TwinScore from an infer_with_twinfer result.

    For every tested direction x -> y:

        TwinScore(x->y)
          = s(z(|rho(t1)|))
          + s(z(|rho(t2)|))
          - s(z(|rho(t2) - rho(t1)|))
          + pi
          - |z_div| * I(z_het < -2.326)
          - z_het * I(z_d_het > 0)
          + 1/2 * sign(gamma) * I(|s(z(gamma))| >= 1)

    Canonical names
    ---------------
    z_div
        Yuval's fixed-Delta shuffle: keep every measured Delta_X and Delta_Y
        exactly, keep Delta_X fixed, and re-pair Delta_Y across clones.

    z_het
        The earlier fresh-random-pair null that replaces twins by unrelated
        cells sampled clone-first.

    z_d_het
        The Stage-3 change score under the heterogeneity / fresh-random-pair
        d null. This is the z_d appearing in the TwinScore equation.

    gamma
        |rho_cross(x->y)| - |rho_cross(y->x)|. gamma is signed.

    Standardization
    ---------------
    infer_with_twinfer first computes permutation-null Z-scores and stores
    them in result["twin_score_inputs"] as:

        z_abs_rho_t1
        z_abs_rho_t2
        z_abs_rho_change
        z_rho_change
        z_gamma

    This function then applies s, a second standardization across the specific
    directed candidate panel, and returns the corresponding s_z_* columns.
    z_div, z_het, and z_d_het are already Z-scores against their own nulls and
    enter the formula directly; s is NOT applied to them. z_rho_change and
    s_z_rho_change are additional signed diagnostics and do not alter the
    current TwinScore formula.

    Notes
    -----
    - pi is the literal mathematical constant np.pi from the supplied formula.
      It shifts all TwinScores equally and therefore does not change ranking.
    - z_div and z_het are within-time t1 scores and are symmetric for x/y.
    - z_d_het is also symmetric for x/y; if it was not evaluated for a pair,
      its indicator is false and the corresponding penalty is zero.
    - Rows are ranked by signed TwinScore descending. Negative scores are kept.
    """
    if not isinstance(inference_output, dict):
        raise TypeError(
            "inference_output must be the dict returned by infer_with_twinfer"
        )

    inputs = inference_output.get("twin_score_inputs")
    if inputs is None:
        raise ValueError(
            "This inference output has no 'twin_score_inputs'. "
            "Run infer_with_twinfer(..., ranked_list=True)."
        )

    if not isinstance(inputs, pd.DataFrame):
        inputs = pd.DataFrame(inputs)

    # Accept inference outputs produced before the z(...), s(z(...)) naming
    # convention, but expose only the current names in the returned table.
    legacy_names = {
        "u_abs_rho_t1": "z_abs_rho_t1",
        "u_abs_rho_t2": "z_abs_rho_t2",
        "u_abs_rho_change": "z_abs_rho_change",
        "u_rho_change": "z_rho_change",
        "u_gamma": "z_gamma",
    }
    rename_legacy = {
        old: new
        for old, new in legacy_names.items()
        if old in inputs.columns and new not in inputs.columns
    }
    inputs = inputs.rename(columns=rename_legacy)

    required = [
        "gene_1",
        "gene_2",
        "z_abs_rho_t1",
        "z_abs_rho_t2",
        "z_abs_rho_change",
        "z_div",
        "z_het",
        "z_d_het",
        "gamma",
        "z_gamma",
    ]
    missing = [c for c in required if c not in inputs.columns]
    if missing:
        raise ValueError(
            f"twin_score_inputs is missing required column(s): {missing}"
        )

    out = inputs.copy()
    out = out.drop(
        columns=[name for name in legacy_names if name in out.columns],
        errors="ignore",
    )
    # Backward compatibility for inference results created before the signed
    # rho-change diagnostic was added.
    if "z_rho_change" not in out.columns:
        out["z_rho_change"] = np.nan

    if out.empty:
        out["s_z_abs_rho_t1"] = pd.Series(dtype=float)
        out["s_z_abs_rho_t2"] = pd.Series(dtype=float)
        out["s_z_abs_rho_change"] = pd.Series(dtype=float)
        out["s_z_rho_change"] = pd.Series(dtype=float)
        out["s_z_gamma"] = pd.Series(dtype=float)
        out["pi_term"] = pd.Series(dtype=float)
        out["divergence_penalty_active"] = pd.Series(dtype=bool)
        out["divergence_penalty"] = pd.Series(dtype=float)
        out["heterogeneity_penalty_active"] = pd.Series(dtype=bool)
        out["heterogeneity_penalty"] = pd.Series(dtype=float)
        out["gamma_bonus"] = pd.Series(dtype=float)
        out["twinScore"] = pd.Series(dtype=float)
        return out

    def _panel_z(values):
        values = np.asarray(values, dtype=float)
        result = np.full(values.shape, np.nan, dtype=float)
        finite = np.isfinite(values)

        if not np.any(finite):
            return result

        x = values[finite]
        mu = float(np.mean(x))
        sd = float(np.std(x, ddof=0))

        if not np.isfinite(sd) or sd == 0:
            result[finite] = 0.0
        else:
            result[finite] = (x - mu) / sd
        return result

    # TwinScore co-expression magnitude at t1
    # LaTeX: s(z(|\rho(t_1)|))
    # Null method: z first compares |\rho(t_1)| with its Stage-I null; s then
    # standardizes those Z-scores across the specific candidate-edge panel.
    # (same with s(z(|\rho(t_2)|)))
    out["s_z_abs_rho_t1"] = _panel_z(out["z_abs_rho_t1"])

    # TwinScore co-expression magnitude at t2
    # LaTeX: s(z(|\rho(t_2)|))
    # Null method: z first compares |\rho(t_2)| with its Stage-I null; s then
    # standardizes those Z-scores across the specific candidate-edge panel.
    # (same with s(z(|\rho(t_1)|)))
    out["s_z_abs_rho_t2"] = _panel_z(out["z_abs_rho_t2"])

    # Official name: Absolute change in gene-expression correlation
    # LaTeX: s(z(|\rho(t_2) - \rho(t_1)|))
    # Z-score: z_abs_rho_change, then s_z_abs_rho_change
    # Permutation method: pool complete raw-cell rows across t1 and t2, shuffle
    # only their time labels while preserving n_t1 and n_t2, and recompute
    # signed Delta rho for each draw. Compare |Delta rho observed| with
    # |Delta rho null|; s then standardizes z across the candidate-edge panel.
    # Twin mode (use_clone=False): every raw-cell row has weight 1.
    # Clone mode (use_clone=True): keep clone_id attached to each complete cell
    # row and recompute weights within each pseudo-time group so every clone
    # represented in that group has total weight 1.
    out["s_z_abs_rho_change"] = _panel_z(out["z_abs_rho_change"])

    # Official name: Panel-standardized signed change in gene correlation
    # LaTeX: s(z(rho(t_2) - rho(t_1)))
    # Z-score: z_rho_change, then s_z_rho_change
    # Permutation method: use the same cell-level time-label draws as
    # z_abs_rho_change, but retain signed Delta rho without abs; s then
    # standardizes z across the specific candidate-edge panel.
    # Twin mode (use_clone=False): every raw-cell row has weight 1.
    # Clone mode (use_clone=True): keep clone_id attached to each complete cell
    # row and recompute weights within each pseudo-time group so every clone
    # represented in that group has total weight 1.
    out["s_z_rho_change"] = _panel_z(out["z_rho_change"])

    # TwinScore directional-asymmetry term
    # LaTeX: s(z(\gamma)), where \gamma =
    # |\hat{\rho}^{\dagger}_{x(t_1)\to y(t_2)}|
    # - |\hat{\rho}^{\dagger}_{y(t_1)\to x(t_2)}|
    # Permutation method: use the same paired cross-clone permutation draws as
    # the direction-step gamma test, calculate the difference of absolute
    # directional correlations for every draw, convert observed gamma to its
    # own null Z-score, and then apply s across the specific candidate panel.
    # (same with z_rho_cross and the direction-step z_gamma)
    out["s_z_gamma"] = _panel_z(out["z_gamma"])

    # Twin difference correlation at time t -- divergence Z-score
    # LaTeX: \hat{\rho}_{\Delta}(t)
    # Permutation method: keep every observed \Delta X and \Delta Y value
    # unchanged, hold the \Delta X rows fixed, and reassign the complete
    # \Delta Y rows one-to-one across twin rows, never to a row from the
    # same biological clone. Every \Delta Y row is used exactly once in
    # each shuffle; recompute weighted Spearman after re-pairing, and
    # Z-score the observed \hat{\rho}_{\Delta}(t) against those values.
    # (same with z_div above and z_d_div at each time point)
    z_div = out["z_div"].to_numpy(dtype=float)

    # Twin difference correlation at time t -- heterogeneity Z-score
    # LaTeX: observed twins \hat{\rho}_{\Delta}(t); random-pair
    # reference \rho_{\Delta}(t).
    # Permutation method: for every observed twin slot, draw a fresh unrelated
    # pair by choosing clone A uniformly, choosing a different clone B uniformly,
    # then choosing one cell uniformly from each clone. Use that same random cell
    # pair to form \Delta X and \Delta Y, recompute weighted Spearman across all
    # slots, and repeat to form the random-pair \rho_{\Delta}(t) distribution.
    # The Z-score compares \hat{\rho}_{\Delta}(t) with that distribution; in
    # clone mode, source twin labels affect only the weights (clone total = 1).
    # (same with z_het above, the fan-out check, and z_d_het at each time point)
    z_het = out["z_het"].to_numpy(dtype=float)

    # Change in twin difference correlation across time -- heterogeneity Z-score
    # LaTeX: d = \hat{\rho}_{\Delta}(t_2)
    #                                - \hat{\rho}_{\Delta}(t_1)
    # Permutation method: for each null draw, resample source-clone blocks;
    # if a biological clone appears at both times, resample that clone jointly
    # at t1 and t2. Then, independently at each time point, replace every
    # selected twin slot with a fresh unrelated pair: choose clone A uniformly,
    # choose clone B != A uniformly, then choose one cell uniformly within each.
    # Compute weighted \rho_{\Delta,\mathrm{rand}} at t1 and t2 and store
    # \rho_{\Delta,\mathrm{rand}}(t_2)-\rho_{\Delta,\mathrm{rand}}(t_1).
    # Twin mode gives every twin weight 1; clone mode gives each source clone
    # total weight 1. Z-score the observed d against this difference null.
    # (same with z_d_het above and z_het at each time point)
    z_d_het = out["z_d_het"].to_numpy(dtype=float)

    divergence_gate = np.isfinite(z_het) & (z_het < -2.326)
    divergence_penalty = np.zeros(len(out), dtype=float)
    usable_div = divergence_gate & np.isfinite(z_div)
    divergence_penalty[usable_div] = np.abs(z_div[usable_div])

    heterogeneity_gate = np.isfinite(z_d_het) & (z_d_het > 0.0)
    heterogeneity_penalty = np.zeros(len(out), dtype=float)
    usable_het = heterogeneity_gate & np.isfinite(z_het)
    heterogeneity_penalty[usable_het] = z_het[usable_het]

    out["pi_term"] = float(np.pi)
    out["divergence_penalty_active"] = divergence_gate
    out["divergence_penalty"] = divergence_penalty
    out["heterogeneity_penalty_active"] = heterogeneity_gate
    out["heterogeneity_penalty"] = heterogeneity_penalty

    out["gamma_bonus"] = (
        0.5
        * np.sign(out["gamma"].to_numpy(dtype=float))
        * (
            np.abs(out["s_z_gamma"].to_numpy(dtype=float)) >= 1.0
        ).astype(float)
    )

    out["twinScore"] = (
        out["s_z_abs_rho_t1"]
        + out["s_z_abs_rho_t2"]
        - out["s_z_abs_rho_change"]
        + out["pi_term"]
        - out["divergence_penalty"]
        - out["heterogeneity_penalty"]
        + out["gamma_bonus"]
    )

    out = (
        out.sort_values(
            "twinScore",
            ascending=False,
            kind="stable",
        )
        .reset_index(drop=True)
    )
    return out

def extract_param_index(filename: str) -> str:
    """
    Extracts the parameter row index (e.g., '0_1') from a simulation filename.

    Handles both 'df_row_' and 'df_rows_' prefixes. The extraction stops before
    an 8-digit date stamp (ddmmyyyy) if present.

    Args:
        filename (str): The simulation filename.

    Returns:
        str: The row identifier (e.g., '0_1'), or 'unknown' if the pattern is not found.
    """
    try:
        # Match df_row_ or df_rows_
        match = re.search(r"df_rows?_(\d+(?:_\d+)*)", filename)
        if not match:
            return "unknown"

        core = match.group(1)
        # Remove trailing date if mistakenly included
        parts = core.split("_")
        cleaned = []
        for part in parts:
            if part.isdigit() and len(part) == 8:  # ddmmyyyy date
                break
            cleaned.append(part)

        return "_".join(cleaned) if cleaned else "unknown"
    except Exception:
        return "unknown"

def get_param_data(param_df, param_index, n_genes):
    """
    Extracts and flattens parameters for a given simulation from a parameter DataFrame.

    This function:
      1. Selects specific rows from `param_df` based on `param_index`.
      2. Flattens gene-specific parameters so keys are labeled as `<term>_gene_<id>`.
      3. Calculates degradation rates (`k_deg_mRNA_gene_X`, `k_deg_protein_gene_X`)
         from the corresponding half-life values.
      4. Adds interaction parameters (non-gene-specific) from the first selected row.

    Args:
        param_df (pd.DataFrame):
            Parameter DataFrame containing both gene-level and interaction-level parameters.
            Must contain columns for each gene term in `gene_terms` and optionally extra metadata.
        param_index (str):
            Underscore-separated string of row indices in `param_df` to use.
            Example: "12_13" will select rows 12 and 13.
        n_genes (int):
            Number of genes expected in the simulation; must match the number of selected rows.

    Returns:
        dict:
            A flat dictionary mapping parameter names to values, e.g.:
            {
                "k_on_gene_1": ...,
                "k_off_gene_1": ...,
                "mrna_half_life_gene_1": ...,
                "k_deg_mRNA_gene_1": ...,
                ...
                "<interaction_param>": ...
            }

    Raises:
        AssertionError:
            If the number of selected rows does not match `n_genes`.
    """
    gene_terms = ["k_on", "k_off", "mrna_half_life", "protein_half_life", 
                  "k_prod_protein", "k_prod_mRNA"]
    extra_terms = ["twin_id", "gene_id"]

    rows = [int(i) for i in param_index.split("_")]
    assert len(rows) == n_genes, f"Mismatch in number of input genes and parameter rows. \n Rows = {rows} and n_genes = {n_genes}"

    selected_rows = param_df.iloc[rows]
    param_dict = {}

    # Gene-specific parameters
    for gene_id, row in enumerate(selected_rows.itertuples(index=False), start=1):
        for term in gene_terms:
            key = f"{term}_gene_{gene_id}"
            param_dict[key] = getattr(row, term)

        # Add degradation terms from half_life
        param_dict[f"k_deg_mRNA_gene_{gene_id}"] = np.log(2) / param_dict[f"mrna_half_life_gene_{gene_id}"]
        param_dict[f"k_deg_protein_gene_{gene_id}"] = np.log(2) / param_dict[f"protein_half_life_gene_{gene_id}"]

    # Interaction parameters (from first row)
    interaction_cols = [col for col in param_df.columns if col not in gene_terms + extra_terms]
    interaction_values = param_df.loc[rows[0], interaction_cols]
    for col in interaction_cols:
        param_dict[col] = interaction_values[col]

    return param_dict


def split_and_merge_simulations(simulation_paths):
    """
    Split clone IDs evenly across multiple simulations and merge selected clones.
    
    This function loads N simulation CSV files, determines the complete set of
    unique clone IDs in the *first* simulation, splits those clone IDs as evenly
    as possible across all N simulations, and merges together the corresponding
    subsets taken from each simulation file.

    Parameters
    ----------
    simulation_paths : list of str
        List of file paths to simulation CSV files.
        - All files must contain a "clone_id" column.
        - Assumes the same clone IDs appear in each simulation, but possibly 
          assigned to different states or having different observations.

    Returns
    -------
    pd.DataFrame
        A concatenated DataFrame containing:
        - The first 1/N of clone IDs from simulation 1,
        - The second 1/N of clone IDs from simulation 2,
        - ...
        - The last 1/N of clone IDs from simulation N.
        The order is determined by sorted clone IDs.

    Notes
    -----
    - Clone IDs are split *evenly* using integer division. 
      If the total number of clones is not exactly divisible by N, 
      the final chunk will contain the remainder.
    - The function returns a simulation file wherein each part of it contains data from a single simulation (not evenly mixed)
    """
    
    # Load all simulations
    sims = [pd.read_csv(path) for path in simulation_paths]
    num_sims = len(sims)

    # Extract clone IDs from first simulation (assumed consistent)
    clone_ids = sorted(sims[0]["clone_id"].unique())
    total_clones = len(clone_ids)
    
    # Compute chunk size
    chunk_size = total_clones // num_sims
    remainder = total_clones % num_sims

    # Determine clone ID chunks for each simulation
    clone_chunks = []
    start = 0
    for i in range(num_sims):
        # distribute the remainder one-by-one to early chunks
        extra = 1 if i < remainder else 0
        end = start + chunk_size + extra
        clone_chunks.append(clone_ids[start:end])
        start = end

    # Merge the subsets
    merged_df = pd.concat(
        [
            sims[i][sims[i]["clone_id"].isin(clone_chunks[i])]
            for i in range(num_sims)
        ],
        ignore_index=True
    )

    return merged_df


def read_input_matrix(path_to_matrix: str) -> tuple[int, np.ndarray]:
    """
    Reads an input matrix from a specified file path and returns its dimensions and content.

    Args:
        path_to_matrix (str): The file path to the matrix file. The file should contain
                              a comma-separated matrix of integers.

    Returns:
        tuple: A tuple containing:
            - int: The number of rows in the matrix.
            - np.ndarray: The matrix as a NumPy array. If the matrix is a single value,
                          it is reshaped into a 1x1 array.

    Raises:
        ValueError: If the file cannot be loaded.
    """
    try:
        matrix = np.loadtxt(path_to_matrix, dtype=int, delimiter=',')
        if matrix.ndim == 0:
            matrix = matrix.reshape((1,1))
        return matrix.shape[0], matrix
    except Exception as e:
        raise ValueError(f"Error loading matrix from {path_to_matrix}: {e}")

def dict_to_matrix(correlation_dict, gene_list):
    """
    Reshapes a "gene1-gene2" -> value dict into a gene x gene DataFrame.

    Parameters
    ----------
    correlation_dict : dict
        Keys formatted as "{gene_1}-{gene_2}" (e.g. from calculate_pairwise_gene_gene_correlation_matrix).
    gene_list : list of str
        Gene names; used as both the row and column index.

    Returns
    -------
    pd.DataFrame
        Gene x gene matrix; entries not present in correlation_dict are NaN.
    """
    matrix = pd.DataFrame(index=gene_list, columns=gene_list, dtype=float)
    for key, value in correlation_dict.items():
        g1, g2 = key.split("-")
        matrix.loc[g1, g2] = value
    return matrix


