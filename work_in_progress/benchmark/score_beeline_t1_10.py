def score_mixed_network_sweep_t1_10():
    orig = (M.BEELINE_INPUT_ROOT, M.BEELINE_OUTPUT_ROOT, M.BEELINE_SCORES_CSV)
    M.BEELINE_INPUT_ROOT = PROJECT_ROOT / "code" / "Beeline" / "inputs" / "mixed_network_sweep_t1_10"
    M.BEELINE_OUTPUT_ROOT = PROJECT_ROOT / "analysis_data" / "mixed_network_sweep" / "beeline_inference_t1_10"
    M.BEELINE_SCORES_CSV = PROJECT_ROOT / "analysis_data" / "mixed_network_sweep" / "beeline_analysis_output_t1_10.csv"
    try:
        df = M.score_beeline()
    finally:
        M.BEELINE_INPUT_ROOT, M.BEELINE_OUTPUT_ROOT, M.BEELINE_SCORES_CSV = orig
    return df


